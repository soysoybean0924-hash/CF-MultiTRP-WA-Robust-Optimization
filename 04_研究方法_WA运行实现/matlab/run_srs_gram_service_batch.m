function state=run_srs_gram_service_batch(root,targetOuter)
%RUN_SRS_GRAM_SERVICE_BATCH Experimental changed-service system run.
% The Gram-weighted exposure is an input feature; its decomposition is not
% validated as a source covariance. This run is separate from fixed-service
% beam comparisons. Checkpoints are written after every completed step.
addpath(fullfile(root,'03_研究场景构造','matlab'), ...
    fullfile(root,'04_研究方法_WA运行实现','matlab'));
inputPath=fullfile(root,'03_研究场景构造','inputs', ...
    'srs_overlap_jakes_v3_main','input.mat');
inputHash=chasi_sha256_file(inputPath);
assert(strcmp(inputHash,strtrim(fileread([inputPath '.sha256']))));
x=load(inputPath,'data'); data=x.data; c=data.config;
[resources,service]=srs_experimental_service(data.resources,data,2);
[initial,~]=chasi_target_common_initial(resources,c.rank, ...
    c.powerWattPerTrp,c.initialSeed);
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp, ...
    'outer_iterations',1,'outer_rel_tol',c.outerObjectiveRelativeTolerance, ...
    'outer_precoder_tol',c.outerCovarianceRelativeTolerance, ...
    'admm_iterations',c.admmIterations,'cg_iterations',c.cgIterations, ...
    'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
    'pf_floor',c.pfFloor,'users',data.sceneConfig.users, ...
    'branch','matrix_pf_statistical');
solverHash=chasi_sha256_file(fullfile(root, ...
    '04_研究方法_WA运行实现','matlab','chasi_matrix_wmmse.m'));
serviceHash=chasi_sha256_file(fullfile(root, ...
    '04_研究方法_WA运行实现','matlab','srs_experimental_service.m'));
runnerHash=chasi_sha256_file([mfilename('fullpath') '.m']);
outDir=fullfile(root,'07_实验结果与进展','local_runs', ...
    'srs_overlap_jakes_v3_main','gram_service_experimental');
if ~isfolder(outDir), mkdir(outDir); end
checkpoint=fullfile(outDir,'latest.mat');
if isfile(checkpoint)
    z=load(checkpoint,'state'); state=z.state;
    assert(strcmp(state.inputSha256,inputHash) && ...
        strcmp(state.solverSha256,solverHash) && ...
        strcmp(state.serviceSha256,serviceHash) && ...
        strcmp(state.runnerSha256,runnerHash) && ...
        isequaln(state.cfg,cfg));
else
    state=struct('model','experimental_gram_service_totalC', ...
        'inputSha256',inputHash,'solverSha256',solverHash, ...
        'serviceSha256',serviceHash,'runnerSha256',runnerHash, ...
        'cfg',cfg,'service',service,'precoder',{initial}, ...
        'iter',0,'history',struct([]),'consecutiveStop',0, ...
        'complete',false,'stopReason','initial_state');
    saveAtomic(checkpoint,state);
end
while state.iter<targetOuter && ~state.complete
    out=chasi_matrix_wmmse(resources,cfg,state.precoder);
    last=out.trajectory(end); admm=out.last_admm_history(end);
    if ~ismember(out.reason,{'max_outer_iterations', ...
            'relative_objective_precoder_and_admm_tolerance'})
        state.stopReason=out.reason; saveAtomic(checkpoint,state); break
    end
    change=covarianceChange(state.precoder,out.precoder);
    meets=last.relative_objective_change<=cfg.outer_rel_tol && ...
        change<=cfg.outer_precoder_tol && last.previous_admm_converged;
    if meets, state.consecutiveStop=state.consecutiveStop+1;
    else, state.consecutiveStop=0; end
    entry=struct('outer',state.iter+1, ...
        'estimatedObjective',out.optimization_objective, ...
        'trueSumSE',out.true_sum_rate,'trueR5',out.true_rate5, ...
        'truePerUserSE',out.true_per_ue_rate, ...
        'power',out.power,'maxPowerViolation',out.max_power_violation, ...
        'relativeObjectiveChange',last.relative_objective_change, ...
        'covarianceChange',change, ...
        'innerSolved',logical(last.previous_admm_converged), ...
        'innerCount',admm.inner,'admmPrimal',admm.primal, ...
        'admmDual',admm.dual,'epsPrimal',admm.eps_primal, ...
        'epsDual',admm.eps_dual);
    state.history=[state.history;entry]; %#ok<AGROW>
    state.iter=state.iter+1; state.precoder=out.precoder;
    if state.consecutiveStop>=c.consecutiveOuterSteps
        state.complete=true;
        state.stopReason='five_outer_covariance_objective_admm';
    else
        state.stopReason='batch_limit';
    end
    saveAtomic(checkpoint,state);
    fprintf('GRAM_SERVICE outer=%d SE=%.7g R5=%.7g inner=%d/%d dx=%.3g status=%s\n', ...
        state.iter,entry.trueSumSE,entry.trueR5,entry.innerCount, ...
        c.admmIterations,change,state.stopReason);
end
end

function value=covarianceChange(old,new)
a=0;b=0;
for g=1:numel(old)
 for l=1:size(old{g},1)
  x=reshape(old{g}(l,:,:,:),size(old{g},3),[]);
  y=reshape(new{g}(l,:,:,:),size(new{g},3),[]);
  q=x*x'; d=y*y'-q;
  a=a+sum(abs(d).^2,'all'); b=b+sum(abs(q).^2,'all');
 end
end
value=sqrt(a)/max(1,sqrt(b));
end

function saveAtomic(path,state)
temporary=[path '.partial.mat'];
assert(~isfile(temporary),'Interrupted write exists; inspect before resume');
save(temporary,'state','-v7.3');
assert(movefile(temporary,path,'f'));
end
