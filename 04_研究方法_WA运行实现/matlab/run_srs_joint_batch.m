function state=run_srs_joint_batch( ...
    targetRoot,inputPath,branchId,batchOuter,checkpointPath)
%CHASI_RUN_TARGET_AGED_BATCH Resume-safe serial native WMMSE/ADMM steps.
% Each completed outer step is saved atomically. The native target solver is
% called with one outer update. Pilot branches use marginal posterior C.
assert(isfolder(targetRoot) && isfile(inputPath));
assert(batchOuter>=1 && batchOuter==floor(batchOuter));
assert(ismember(branchId,{'ideal_sumse','nominal_sumse','robust_sumse', ...
    'ideal_pf','nominal_pf','robust_pf'}));
addpath(fullfile(targetRoot,'04_研究方法_WA运行实现','matlab'));
expectedHash=strtrim(fileread([inputPath '.sha256']));
inputHash=chasi_sha256_file(inputPath);
assert(strcmp(inputHash,expectedHash),'Input SHA-256 mismatch');
loaded=load(inputPath,'data'); data=loaded.data;
assert(ismember(data.modelId, ...
    {'srs_joint_snapshot_v2','srs_overlap_snapshot_v1','srs_overlap_jakes_v3'}));
assert(strcmp(data.sourceCodeSha256,chasi_sha256_file( ...
    fullfile(targetRoot,'03_研究场景构造','matlab','prepare_srs_joint_input.m'))));
if ismember(data.modelId,{'srs_overlap_snapshot_v1','srs_overlap_jakes_v3'})
    snapshotFile='srs_overlap_snapshot.m';
else
    snapshotFile='srs_joint_snapshot.m';
end
assert(strcmp(data.snapshotCodeSha256,chasi_sha256_file( ...
    fullfile(targetRoot,'03_研究场景构造','matlab',snapshotFile))));
assert(strcmp(data.sceneGeneratorSha256,chasi_sha256_file( ...
    fullfile(targetRoot,'03_研究场景构造','matlab','chasi_generate_scene.m'))));
assert(strcmp(data.sceneConfigSha256,chasi_sha256_file( ...
    fullfile(targetRoot,'02_研究背景搭建','matlab','chasi_config.m'))));
config=data.config;
if isfield(data,'configPath'), configPath=data.configPath;
else, configPath=fullfile(targetRoot,'03_研究场景构造', ...
    'config','srs_joint_snapshot_v2.json'); end
assert(strcmp(data.configSha256,chasi_sha256_file(configPath)));
codeSha256=chasi_sha256_file(fullfile(targetRoot,'04_研究方法_WA运行实现','matlab','chasi_matrix_wmmse.m'));
runnerSha256=chasi_sha256_file(fullfile(targetRoot,'04_研究方法_WA运行实现','matlab','run_srs_joint_batch.m'));
nativeCfg=struct('rank',config.rank,'budget',config.powerWattPerTrp, ...
    'outer_iterations',1,'outer_rel_tol',config.outerObjectiveRelativeTolerance, ...
    'outer_precoder_tol',config.outerCovarianceRelativeTolerance, ...
    'admm_iterations',config.admmIterations, ...
    'cg_iterations',config.cgIterations, ...
    'eps_abs',config.admmAbsoluteTolerance,'eps_rel',config.admmRelativeTolerance, ...
    'pf_floor',config.pfFloor,'users',data.sceneConfig.users);
resources=data.resources;
switch branchId
    case 'ideal_sumse'
        nativeCfg.branch='ideal';
    case 'nominal_sumse'
        nativeCfg.branch='matrix_nominal';
    case 'robust_sumse'
        nativeCfg.branch='matrix_statistical';
    case 'ideal_pf'
        nativeCfg.branch='matrix_pf_nominal';
        for g=1:numel(resources), resources(g).H=resources(g).H_true; end
    case 'nominal_pf'
        nativeCfg.branch='matrix_pf_nominal';
    case 'robust_pf'
        nativeCfg.branch='matrix_pf_statistical';
end
allIds=[];
for g=1:numel(resources), allIds=[allIds;resources(g).ueIds(:)]; end %#ok<AGROW>
scheduledIds=unique(double(allIds));
if isfile(checkpointPath)
    loaded=load(checkpointPath,'state'); state=loaded.state;
    assert(strcmp(state.runnerVersion,'srs_joint_batch_v2') && ...
        strcmp(state.modelId,data.modelId) && ...
        strcmp(state.inputSha256,inputHash) && ...
        strcmp(state.configSha256,data.configSha256) && ...
        strcmp(state.codeSha256,codeSha256) && ...
        strcmp(state.runnerSha256,runnerSha256) && ...
        strcmp(state.branchId,branchId) && ...
        isequaln(state.nativeCfg,nativeCfg));
    assert(state.iter==numel(state.history));
    if state.complete
        fprintf('BRANCH_ALREADY_COMPLETE %s outer=%d reason=%s\n', ...
            branchId,state.iter,state.stopReason);
        return
    end
else
    state=struct('runnerVersion','srs_joint_batch_v2', ...
        'modelId',data.modelId,'inputSha256',inputHash, ...
        'configSha256',data.configSha256,'branchId',branchId, ...
        'codeSha256',codeSha256,'runnerSha256',runnerSha256, ...
        'nativeCfg',nativeCfg,'iter',0, ...
        'precoder',{data.initialPrecoder},'history',struct([]), ...
        'consecutiveStop',0,'complete',false, ...
        'stopReason','initial_state');
    saveAtomic(checkpointPath,state);
end
for step=1:batchOuter
    out=chasi_matrix_wmmse(resources,nativeCfg,state.precoder);
    assert(numel(out.trajectory)>=2);
    last=out.trajectory(end);
    trueRates=out.true_per_ue_rate(:);
    assert(numel(trueRates)==data.sceneConfig.users && ...
        all(isfinite(trueRates)) && all(trueRates>=-1e-9));
    truePF=sum(log1p(max(0,trueRates(scheduledIds))/config.pfFloor));
    admm=out.last_admm_history(end);
    covarianceChange=txCovarianceChange(state.precoder,out.precoder);
    meets=last.relative_objective_change<=nativeCfg.outer_rel_tol && ...
        covarianceChange<=nativeCfg.outer_precoder_tol && ...
        last.previous_admm_converged;
    if meets, state.consecutiveStop=state.consecutiveStop+1;
    else, state.consecutiveStop=0; end
    entry=struct('outer',state.iter+1, ...
        'estimatedObjective',out.optimization_objective, ...
        'trueSumSE',out.true_sum_rate,'truePF',truePF, ...
        'trueRate5',out.true_rate5, ...
        'truePerUserSE',trueRates,'maxPower',max(out.power), ...
        'relativeObjectiveChange',last.relative_objective_change, ...
        'precoderChange',last.previous_precoder_change, ...
        'covarianceChange',covarianceChange, ...
        'innerSolved',logical(last.previous_admm_converged), ...
        'admmPrimal',admm.primal,'admmDual',admm.dual, ...
        'epsPrimal',admm.eps_primal,'epsDual',admm.eps_dual, ...
        'innerCount',admm.inner,'nativeReason',out.reason);
    state.history=[state.history;entry]; %#ok<AGROW>
    state.iter=state.iter+1;
    state.precoder=out.precoder;
    if state.consecutiveStop>=config.consecutiveOuterSteps
        state.complete=true; state.stopReason='five_outer_covariance_objective_admm';
    elseif ismember(out.reason, ...
            {'optimization_objective_decrease', ...
             'inexact_precoder_step_no_proxy_improvement'})
        state.complete=false; state.stopReason=out.reason;
    else
        state.stopReason='batch_limit';
    end
    saveAtomic(checkpointPath,state);
    fprintf(['BRANCH_BATCH %s outer=%d trueSumSE=%.8g truePF=%.8g ', ...
        'inner=%d/%d rel=%.4g dx=%.4g status=%s\n'], ...
        branchId,state.iter,entry.trueSumSE,entry.truePF, ...
        entry.innerCount,config.admmIterations, ...
        entry.relativeObjectiveChange,entry.precoderChange,state.stopReason);
    if state.complete, break; end
end
end

function change=txCovarianceChange(old,new)
numerator=0; denominator=0;
for g=1:numel(old)
    for l=1:size(old{g},1)
        x=reshape(old{g}(l,:,:,:),size(old{g},3),[]);
        y=reshape(new{g}(l,:,:,:),size(new{g},3),[]);
        q0=x*x'; q1=y*y';
        numerator=numerator+sum(abs(q1-q0).^2,'all');
        denominator=denominator+sum(abs(q0).^2,'all');
    end
end
change=sqrt(numerator)/max(1,sqrt(denominator));
end

function saveAtomic(path,state)
parent=fileparts(path);
if ~isfolder(parent), mkdir(parent); end
temporary=[path '.partial.mat'];
assert(~isfile(temporary), ...
    'Interrupted checkpoint write exists; inspect it before resuming.');
save(temporary,'state','-v7.3');
assert(movefile(temporary,path,'f'));
end

