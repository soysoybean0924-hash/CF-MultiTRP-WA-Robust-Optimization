function rows=export_srs_overlap_trajectory(root,csvPath)
%EXPORT_SRS_OVERLAP_TRAJECTORY Checkpoint history without convergence relabeling.
base=fullfile(root,'07_实验结果与进展','local_runs','srs_overlap_jakes_v3_main');
names={'ideal_pf','nominal_pf','robust_pf'};
rows=struct('branch',{},'outer',{},'trueSumSE',{},'truePF',{}, ...
 'trueR5',{},'estimatedObjective',{},'maxPower',{}, ...
 'relativeObjectiveChange',{},'precoderChange',{},'covarianceChange',{}, ...
 'innerSolved',{},'innerCount',{},'admmPrimal',{},'epsPrimal',{}, ...
 'admmDual',{},'epsDual',{},'stopReason',{});
for i=1:numel(names)
 loaded=load(fullfile(base,names{i},'latest.mat'),'state'); s=loaded.state;
 for j=1:s.iter
  e=s.history(j); n=numel(rows)+1;
  rows(n)=struct('branch',names{i},'outer',e.outer, ...
   'trueSumSE',e.trueSumSE,'truePF',e.truePF,'trueR5',e.trueRate5, ...
   'estimatedObjective',e.estimatedObjective,'maxPower',e.maxPower, ...
   'relativeObjectiveChange',e.relativeObjectiveChange, ...
   'precoderChange',e.precoderChange,'covarianceChange',e.covarianceChange, ...
   'innerSolved',e.innerSolved,'innerCount',e.innerCount, ...
   'admmPrimal',e.admmPrimal,'epsPrimal',e.epsPrimal, ...
   'admmDual',e.admmDual,'epsDual',e.epsDual, ...
   'stopReason',s.stopReason);
 end
end
writetable(struct2table(rows),csvPath);
end
