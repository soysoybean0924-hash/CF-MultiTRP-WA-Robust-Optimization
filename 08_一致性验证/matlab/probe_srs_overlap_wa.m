function result=probe_srs_overlap_wa(root,outPath)
%PROBE_SRS_OVERLAP_WA Bounded one-group WA cost/feasibility diagnostic.
addpath(fullfile(root,'03_研究场景构造','matlab'), ...
    fullfile(root,'04_研究方法_WA运行实现','matlab'));
inputPath=fullfile(root,'03_研究场景构造','inputs', ...
 'srs_overlap_jakes_v3_main','input.mat');
s=load(inputPath,'data'); data=s.data; c=data.config;
resources=data.resources(1); initial=data.initialPrecoder(1);
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp, ...
 'outer_iterations',1,'admm_iterations',10,'cg_iterations',10, ...
 'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
 'pf_floor',c.pfFloor,'users',data.sceneConfig.users, ...
 'branch','matrix_pf_nominal');
t=tic; out=chasi_matrix_wmmse(resources,cfg,initial);
result=struct('modelId',data.modelId,'inputSha256',chasi_sha256_file(inputPath), ...
 'branch',cfg.branch,'group',1,'admmCap',10,'cgCap',10, ...
 'elapsedSeconds',toc(t),'stopReason',out.reason, ...
 'maxPowerViolation',out.max_power_violation, ...
 'objective',out.optimization_objective,'admm',out.last_admm_history(end));
save(outPath,'result','-v7');
end
