function result=run_srs_service_ablation(root,outPath)
%RUN_SRS_SERVICE_ABLATION Separate changed-service system experiment.
% Experimental source risk is a decision feature, not a covariance split.
addpath(fullfile(root,'03_研究场景构造','matlab'), ...
    fullfile(root,'04_研究方法_WA运行实现','matlab'));
inputPath=fullfile(root,'03_研究场景构造','inputs', ...
    'srs_overlap_jakes_v3_main','input.mat');
s=load(inputPath,'data'); data=s.data; c=data.config;
[resources,record]=srs_experimental_service(data.resources,data,2);
[initial,~]=chasi_target_common_initial(resources,c.rank,c.powerWattPerTrp,c.initialSeed);
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp, ...
 'outer_iterations',1,'outer_rel_tol',c.outerObjectiveRelativeTolerance, ...
 'outer_precoder_tol',c.outerCovarianceRelativeTolerance, ...
 'admm_iterations',c.admmIterations,'cg_iterations',c.cgIterations, ...
 'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
 'pf_floor',c.pfFloor,'users',data.sceneConfig.users, ...
 'branch','matrix_pf_statistical');
t=tic; out=chasi_matrix_wmmse(resources,cfg,initial);
result=struct('inputSha256',chasi_sha256_file(inputPath), ...
 'modelId',data.modelId,'method','experimental_source_risk_service_totalC', ...
 'changedLinks',record.changedLinks,'totalLinks',record.totalLinks, ...
 'elapsedSeconds',toc(t),'trueSumSE',out.true_sum_rate, ...
 'trueR5',out.true_rate5,'maxPower',max(out.power), ...
 'maxPowerViolation',out.max_power_violation, ...
 'stopReason',out.reason, ...
 'innerSolved',out.trajectory(end).previous_admm_converged, ...
 'serviceRecord',record,'precoder',{out.precoder});
save(outPath,'result','-v7.3');
end
