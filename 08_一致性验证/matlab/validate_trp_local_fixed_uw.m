function report=validate_trp_local_fixed_uw(outPath)
%VALIDATE_TRP_LOCAL_FIXED_UW Tiny fixed-U/W central vs serial TRP blocks.
stream=RandStream('mt19937ar','Seed',2281);
G=2; L=2; K=2; Nr=2; Nt=2; rank=1; budget=1;
resources=repmat(struct('H',[],'C',[],'servingMask',[], ...
    'resourceWeightNu',.5),1,G);
initial=cell(1,G);
for g=1:G
    resources(g).H=cn(stream,K,L,Nr,Nt);
    resources(g).C=complex(zeros(K,L,Nr,Nr));
    for k=1:K
        for l=1:L
            resources(g).C(k,l,:,:)=reshape(.02*eye(Nr),1,1,Nr,Nr);
        end
    end
    resources(g).servingMask=true(L,K);
    initial{g}=.1*cn(stream,L,K,Nt,rank);
end
cfg=struct('branch','matrix_sum','rank',rank,'budget',budget, ...
    'outer_iterations',1,'admm_iterations',250,'cg_iterations',100, ...
    'eps_abs',1e-7,'eps_rel',1e-6, ...
    'capture_first_step',true,'probe_fixed_receiver_weight',true);
central=chasi_matrix_wmmse(resources,cfg,initial);
p=central.firstProbe;
local=chasi_trp_local_fixed_uw(resources,p.parts,p.initialPrecoder, ...
    budget,120);
reference=p.admmHistory(end).fixed_receiver_weight_precoder_objective;
gap=(local.fixedObjective-reference)/max(1,abs(reference));
assert(local.maxPowerViolation<1e-8);
assert(p.admmHistory(end).max_power_violation<1e-8);
assert(abs(gap)<3e-3, ...
    'TRP block solver differs from central fixed-U/W ADMM reference');
report=struct('seed',2281,'groups',G,'trps',L,'usersPerGroup',K, ...
    'centralFixedObjective',reference, ...
    'trpBlockFixedObjective',local.fixedObjective, ...
    'relativeObjectiveGap',gap, ...
    'centralADMMIterations',p.admmHistory(end).inner, ...
    'trpBlockSweeps',numel(local.history), ...
    'trpBlockElapsedSeconds',local.elapsedSeconds, ...
    'trpBlockMaxPowerViolation',local.maxPowerViolation, ...
    'method','serial TRP block coordinate, not distributed ADMM');
save(outPath,'report','-v7');
fprintf('TRP_BLOCK gap=%.5g sweeps=%d centralInner=%d violation=%.3g\n', ...
    gap,report.trpBlockSweeps,report.centralADMMIterations, ...
    local.maxPowerViolation);
end

function x=cn(stream,varargin)
x=(randn(stream,varargin{:})+1i*randn(stream,varargin{:}))/sqrt(2);
end
