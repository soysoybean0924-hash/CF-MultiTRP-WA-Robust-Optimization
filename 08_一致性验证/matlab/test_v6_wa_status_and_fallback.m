function report=test_v6_wa_status_and_fallback(root,inputPath,configDir)
% Future licensed integration test on an already frozen formal input.
startup;assert(isfile(inputPath) && isfolder(configDir));
offlineDir=[tempname '_v6_wa_offline'];
deadlineDir=[tempname '_v6_wa_deadline'];
limit=struct('admm_iterations',1,'cg_iterations',2);
offline=run_v5_online_six(root,inputPath,configDir,offlineDir, ...
    1,1,limit,'offline','centralized');
assert(all(isinf([offline.waLog.deadlineSeconds])) && ...
    ~any([offline.waLog.deadlineExceeded]), ...
    'Offline WA incorrectly inherited a 1 ms soft deadline');
limit.max_update_seconds=1e-9;
realtime=run_v5_online_six(root,inputPath,configDir,deadlineDir, ...
    1,1,limit,'realtime_diagnostic','centralized');
assert(all([realtime.waLog.deadlineExceeded]) && ...
    all([realtime.waLog.fallbackApplied]) && ...
    all([realtime.waLog.powerFeasible]) && ...
    all([realtime.waLog.serviceFeasible]), ...
    'Real-time deadline fallback did not preserve feasible beams');
assert(all(arrayfun(@(r)~isempty(r.solverStatus) && ...
    ~isempty(r.effectiveReason) && isfinite(r.elapsedSeconds), ...
    realtime.waLog)));
report=struct('offlineCheckpoint',fullfile(offlineDir,'latest.mat'), ...
    'deadlineCheckpoint',fullfile(deadlineDir,'latest.mat'), ...
    'offlineStatuses',{{offline.waLog.solverStatus}}, ...
    'deadlineStatuses',{{realtime.waLog.solverStatus}}, ...
    'deadlineFallbackCount',nnz([realtime.waLog.fallbackApplied]));
end
