function report=validate_v6_independent_seed_posterior(checkpointPaths,group,absoluteTti)
% Read-only independent-seed empirical posterior check at one fixed event.
% Truth is read only here, after online decisions. No gate is changed.
assert(iscell(checkpointPaths) && numel(checkpointPaths)>=30 && ...
    group>=1 && group==fix(group) && ...
    absoluteTti>=0 && absoluteTti==fix(absoluteTti));
N=numel(checkpointPaths);seeds=zeros(1,N);inputSha=cell(1,N);
traceRatio=zeros(1,N);observed=[];predicted=[];withoutCross=[];
crossFro=0;count=0;measurementSha='';modelId='';
for j=1:N
 assert(isfile(checkpointPaths{j}));
 loaded=load(checkpointPaths{j},'state');state=loaded.state;
 identity=state.identity;
 seeds(j)=identity.sceneSeed;inputSha{j}=identity.inputSha256;
 assert(numel(unique(seeds(1:j)))==j && ...
     numel(unique(inputSha(1:j)))==j, ...
     'Validation inputs must have independent scene seeds and SHA');
 if j==1
  measurementSha=identity.measurementSha256;
  modelId=identity.channelSource;
 end
 assert(strcmp(measurementSha,identity.measurementSha256) && ...
     strcmp(modelId,identity.channelSource) && ...
     ismember(modelId,{'generated_parameters','validated_external'}));
 eventIndex=find([state.eventLog.tti]==absoluteTti,1);
 assert(~isempty(eventIndex) && ...
     ~isempty(state.eventLog(eventIndex).measurementPath), ...
     'Selected absolute TTI has no saved measurement event');
 raw=load(state.eventLog(eventIndex).measurementPath,'measurement');
 m=raw.measurement;
 assert(strcmp(m.inputSha256,identity.inputSha256) && ...
     strcmp(m.channelTraceSha256,identity.channelTraceSha256) && ...
     m.tti==absoluteTti && group<=numel(m.posteriorByGroup));
 p=m.posteriorByGroup{group};
 assert(~isempty(p) && p.absoluteTti==absoluteTti && ...
     p.group==group && ~isempty(p.sourceCov5));
 [K,L,Nr,Nt]=size(p.estimateH);
 if j==1
  observed=complex(zeros(Nr,Nr));predicted=observed;
  withoutCross=observed;
 end
 assert(isequal(size(p.validationTruthH),size(p.estimateH)) && ...
     size(observed,1)==Nr);
 seedObserved=complex(zeros(Nr,Nr));seedPredicted=seedObserved;
 for k=1:K,for l=1:L
  error=reshape(double(p.validationTruthH(k,l,:,:))- ...
      double(p.estimateH(k,l,:,:)),Nr,Nt);
  actual=error*error'/Nt;
  physical=reshape(double(p.physicalC(k,l,:,:)),Nr,Nr);
  pieces=reshape(sum(double(p.sourceCov5(k,l,:,:,:)),5),Nr,Nr);
  cross=reshape(double(p.sourceCrossCovariance(k,l,:,:)),Nr,Nr);
  seedObserved=seedObserved+actual/(K*L);
  seedPredicted=seedPredicted+physical/(K*L);
  withoutCross=withoutCross+pieces/(N*K*L);
  crossFro=crossFro+norm(cross,'fro')/(N*K*L);
 end,end
 observed=observed+seedObserved/N;
 predicted=predicted+seedPredicted/N;
 traceRatio(j)=real(trace(seedObserved))/ ...
     max(real(trace(seedPredicted)),eps);
 count=count+K*L;
end
relative=norm(observed-predicted,'fro')/ ...
    max(norm(predicted,'fro'),eps);
ablated=norm(observed-withoutCross,'fro')/ ...
    max(norm(predicted,'fro'),eps);
standardError=std(traceRatio)/sqrt(N);
zScore=abs(mean(traceRatio)-1)/max(standardError,eps);
netCrossRelative=norm(predicted-withoutCross,'fro')/ ...
    max(norm(predicted,'fro'),eps);
crossInformative=netCrossRelative>.05;
diagnosticPassed=relative<.15 && zScore<3 && ...
    (~crossInformative || ablated>relative);
report=struct('independentSceneSeeds',seeds, ...
    'inputSha256',{inputSha},'absoluteTti',absoluteTti, ...
    'group',group,'channelSource',modelId, ...
    'measurementImplementationSha256',measurementSha, ...
    'seedCount',N,'linkCount',count, ...
    'empiricalErrorCovariance',observed, ...
    'meanPredictedPhysicalC',predicted, ...
    'meanFiveTermsWithoutSignedCross',withoutCross, ...
    'meanSignedCrossFro',crossFro, ...
    'netSignedCrossRelativeFro',netCrossRelative, ...
    'relativeCovarianceMismatch',relative, ...
    'crossOmittedRelativeMismatch',ablated, ...
    'meanWhitenedTraceRatio',mean(traceRatio), ...
    'seedStandardError',standardError,'traceZScore',zScore, ...
    'crossInformative',crossInformative, ...
    'diagnosticPassed',diagnosticPassed, ...
    'formalValidationPassed',false, ...
    'scope','one fixed group and absolute TTI; no automatic formal gate');
end
