function test_v6_trp_coordination_small(root)
% Run only after MATLAB licensing is confirmed. Same tiny fixed input.
addpath(fullfile(root,'04_研究方法_WA运行实现','matlab'));
H=complex(zeros(2,2,2,4));
H(1,1,1,:)=reshape([1 .3 .1 0],1,1,1,4);
H(1,2,1,:)=reshape([.4 .2 0 0],1,1,1,4);
H(2,1,2,:)=reshape([.2 .3 .1 0],1,1,1,4);
H(2,2,2,:)=reshape([1 .4 .2 0],1,1,1,4);
r=struct('H',H,'C',complex(zeros(2,2,2,2)), ...
    'C_stat',complex(zeros(2,2,2,2)), ...
    'servingMask',true(2,2),'ueIds',(1:2)', ...
    'resourceWeightNu',.5);
cfg=struct('rank',1,'budget',2,'outer_iterations',3, ...
    'admm_iterations',30,'cg_iterations',30, ...
    'outer_rel_tol',1e-5,'outer_precoder_tol',1e-5, ...
    'eps_abs',1e-6,'eps_rel',1e-5, ...
    'branch','matrix_pf_nominal','pf_floor',.01, ...
    'users',2,'defer_true_evaluation',true);
cfg.coordinationMode='centralized';
central=chasi_matrix_wmmse(r,cfg,[]);
cfg.coordinationMode='trp_jacobi_serial';
serial=chasi_matrix_wmmse(r,cfg,[]);
assert(all(central.power<=2+1e-6) && ...
    all(serial.power<=2+1e-6));
assert(strcmp(serial.trajectory(1).admm_trace(1).coordinationMode, ...
    'trp_jacobi_serial'));
assert(serial.trajectory(1).admm_trace(1).coordinationRounds==1 && ...
    serial.trajectory(1).admm_trace(1).estimatedExchangeBytes>0);
assert(central.trajectory(1).admm_trace(1).coordinationRounds==0);
for result={central,serial}
 out=result{1};
 assert(out.converged==strcmp(out.reason, ...
     'relative_objective_precoder_and_admm_tolerance'));
 assert(all(isfinite([out.trajectory.objective])) && ...
     all([out.trajectory.power_feasible]) && ...
     all([out.trajectory.service_feasible]));
 assert(~isempty(out.trajectory(end).stop_reason) && ...
     isfinite(out.solver_elapsed_seconds));
end
end
