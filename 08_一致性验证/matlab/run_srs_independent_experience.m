function summary=run_srs_independent_experience(root,outDir,inputPath)
%RUN_SRS_INDEPENDENT_EXPERIENCE Same frozen-beam traffic as paired WA.
% This remains a snapshot-beam diagnostic, not adaptive protocol evidence.
addpath(fullfile(root,'02_研究背景搭建','matlab'), ...
    fullfile(root,'03_研究场景构造','matlab'), ...
    fullfile(root,'04_研究方法_WA运行实现','matlab'));
if nargin<3
    inputPath=fullfile(root,'03_研究场景构造','inputs', ...
        'srs_overlap_jakes_v3_main','input.mat');
end
inputHash=chasi_sha256_file(inputPath);
x=load(inputPath,'data'); data=x.data; cfg=data.sceneConfig;
y=load(fullfile(outDir,'independent_pc.mat'),'result'); result=y.result;
assert(strcmp(result.inputSha256,inputHash),'Independent PC input differs');
cfg.trafficModel='target_busy_fraction'; cfg.trafficLoad=.30;
scene=chasi_generate_scene(cfg);
scene.resources=data.resources; scene.config=cfg;
[busy,tail,terminal]=chasi_traffic(cfg.users,1000,data.trafficSeed, ...
    cfg.trafficModel,cfg.trafficLoad);
traffic=struct('busy',busy,'tail',tail,'terminal',terminal);
options=struct('windowTti',1000,'offeredMbps',cfg.offeredMbps, ...
    'fastPeriodTti',cfg.fastPeriodTti,'slowPeriodTti',cfg.slowPeriodTti, ...
    'beamPolicy','frozen','trafficSeed',data.trafficSeed);
solution=struct('precoder',{result.precoder},'branch','independent_pc');
evaluation=chasi_time_evolution(scene,solution,options,traffic);
assert(~isfile(fullfile(outDir,'independent_pc_frozen_experience.mat')), ...
    'Preserve existing independent experience result');
save(fullfile(outDir,'independent_pc_frozen_experience.mat'), ...
    'evaluation','inputHash','-v7.3');
summary=struct('branch','independent_pc','inputSha256',inputHash, ...
    'r5Mbps',evaluation.experience_bottom5_mbps_all_zero_included, ...
    'meanMbps',evaluation.experience_mean_mbps_valid, ...
    'completedBursts',evaluation.completed_bursts, ...
    'totalBursts',evaluation.total_bursts, ...
    'actualBusyFraction',evaluation.actual_busy_ue_tti_fraction, ...
    'onlineUpdates',evaluation.online_wmmse_updates, ...
    'runtimeSeconds',evaluation.runtime_seconds);
fid=fopen(fullfile(outDir,'independent_pc_frozen_experience.json'),'wt');
assert(fid>=0); fprintf(fid,'%s',jsonencode(summary,PrettyPrint=true)); fclose(fid);
fprintf('INDEPENDENT_EXPERIENCE R5=%.8g MEAN=%.8g completed=%d/%d\n', ...
    summary.r5Mbps,summary.meanMbps,summary.completedBursts,summary.totalBursts);
end
