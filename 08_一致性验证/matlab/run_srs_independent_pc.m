function result=run_srs_independent_pc(root,outPath,inputPath)
%RUN_SRS_INDEPENDENT_PC Formal same-input local power-control baseline.
addpath(fullfile(root,'03_研究场景构造','matlab'), ...
    fullfile(root,'04_研究方法_WA运行实现','matlab'));
if nargin<3
    inputPath=fullfile(root,'03_研究场景构造','inputs', ...
        'srs_overlap_jakes_v3_main','input.mat');
end
assert(~isfile(outPath),'Preserve existing independent power-control result');
s=load(inputPath,'data'); data=s.data;
cfg=struct('rank',data.config.rank,'budget',data.config.powerWattPerTrp, ...
    'users',data.sceneConfig.users,'pf_floor',data.config.pfFloor);
t=tic; out=chasi_independent_power_control(data.resources,cfg);
result=struct('inputSha256',chasi_sha256_file(inputPath), ...
    'modelId',data.modelId,'method',out.branch, ...
    'elapsedSeconds',toc(t),'trueSumSE',out.true_sum_rate, ...
    'trueR5',out.true_rate5,'powerByTrp',out.power, ...
    'maxPowerViolation',out.max_power_violation, ...
    'stopReason',out.reason, ...
    'precoder',{out.precoder});
save(outPath,'result','-v7.3');
end
