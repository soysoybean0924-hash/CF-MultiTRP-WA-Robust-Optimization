function result=run_srs_sharing_one_outer(root,outPath)
%RUN_SRS_SHARING_ONE_OUTER Full 17-group serial-message WA bounded probe.
% This tests integration only. A 20-iteration inner cap cannot establish
% distributed V convergence or a fair performance ranking.
addpath(fullfile(root,'03_研究场景构造','matlab'), ...
    fullfile(root,'04_研究方法_WA运行实现','matlab'));
assert(~isfile(outPath),'Preserve prior distributed probe');
inputPath=fullfile(root,'03_研究场景构造','inputs', ...
    'srs_overlap_jakes_v3_main','input.mat');
inputHash=chasi_sha256_file(inputPath);
assert(strcmp(inputHash,strtrim(fileread([inputPath '.sha256']))));
x=load(inputPath,'data'); data=x.data; c=data.config;
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp, ...
    'outer_iterations',1,'outer_rel_tol',c.outerObjectiveRelativeTolerance, ...
    'outer_precoder_tol',c.outerCovarianceRelativeTolerance, ...
    'admm_iterations',20,'cg_iterations',c.cgIterations, ...
    'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
    'rho',.01,'pf_floor',c.pfFloor, ...
    'users',data.sceneConfig.users,'branch','matrix_pf_statistical');
start=tic;
out=chasi_matrix_wmmse_sharing(data.resources,cfg,data.initialPrecoder);
elapsed=toc(start); a=out.last_admm_history(end);
referenceFile=fullfile(root,'07_实验结果与进展','local_runs', ...
    'srs_overlap_jakes_v3_main','robust_pf','latest.mat');
y=load(referenceFile,'state'); s=y.state;
assert(strcmp(s.inputSha256,inputHash) && s.iter>=1);
centralFirst=s.history(1);
result=struct('modelId',data.modelId,'inputSha256',inputHash, ...
    'sharingSolverSha256',chasi_sha256_file(fullfile(root, ...
        '04_研究方法_WA运行实现','matlab','chasi_matrix_wmmse_sharing.m')), ...
    'vUpdaterSha256',chasi_sha256_file(fullfile(root, ...
        '04_研究方法_WA运行实现','matlab', ...
        'chasi_trp_sharing_admm_fixed_uw.m')), ...
    'method','TRP sharing ADMM serial message simulation', ...
    'groups',numel(data.resources),'trps',data.sceneConfig.trps, ...
    'innerCap',cfg.admm_iterations,'innerSolved', ...
        out.trajectory(end).previous_admm_converged, ...
    'primal',a.primal,'dual',a.dual, ...
    'epsPrimal',a.eps_primal,'epsDual',a.eps_dual, ...
    'trueSumSE',out.true_sum_rate,'trueR5',out.true_rate5, ...
    'totalPower',sum(out.power),'maxPowerViolation',out.max_power_violation, ...
    'outerReason',out.reason,'runtimeSeconds',elapsed, ...
    'centralFirstOuter',centralFirst, ...
    'precoder',{out.precoder},'trajectory',out.trajectory, ...
    'innerHistory',out.last_admm_history);
save(outPath,'result','-v7.3');
fprintf(['SHARING_FORMAL_ONE inner=%d/%d solved=%d primal=%.3g/%.3g ', ...
    'dual=%.3g/%.3g SE=%.7g R5=%.7g violation=%.3g time=%.3f reason=%s\n'], ...
    a.inner,cfg.admm_iterations,result.innerSolved,a.primal,a.eps_primal, ...
    a.dual,a.eps_dual,result.trueSumSE,result.trueR5, ...
    result.maxPowerViolation,elapsed,result.outerReason);
end
