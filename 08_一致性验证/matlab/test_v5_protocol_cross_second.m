function report=test_v5_protocol_cross_second(root)
% TS 28.554/image semantics: exclude both volume and time of the
% successful empty-buffer tail. Assign a completed burst to its ACK second.
addpath(fullfile(root,'08_一致性验证','matlab'));
T=1001;arrival=zeros(3,T);capacity=200*ones(3,T);
bler=zeros(3,T);draw=.5*ones(3,T);
arrival(1,999)=100;arrival(1,1000)=200;bler(1,999)=1;
arrival(2,1000)=50; % immediate tail: no effective duration
arrival(3,1001)=50;bler(3,1001)=1; % unfinished at window end
ev=chasi_v4_rlc_event_sim(arrival,capacity,bler,841,draw);
counter=chasi_acked_rlc_seconds(ev,1);
assert(isequal(counter.ackedBits(1,:),[0 100]));
assert(abs(counter.effectiveSeconds(1,2)-.002)<eps);
assert(~counter.valid(1,1) && counter.valid(1,2));
assert(counter.crossSecondBursts==1 && ...
    counter.zeroDurationBursts==1 && counter.openBurstCount==1);
assert(sum(ev.ackedBits,'all')==350);
assert(counter.bursts(1).excludedTailAckBits==200);
assert(ev.retransmission(1,1000) && ...
    ev.attemptNumber(1,1000)==2 && ev.success(1,1001));
fragmented=chasi_v4_rlc_event_sim( ...
    reshape([250 0 0],1,3),100*ones(1,3), ...
    zeros(1,3),842,.5*ones(1,3));
fragmentedCounter=chasi_acked_rlc_seconds(fragmented,1);
assert(sum(fragmented.fragmentAckBits,'all')==250 && ...
    fragmented.sduAckBits(3)==250 && ...
    sum(fragmentedCounter.ackedBits,'all')==0 && ...
    fragmentedCounter.bursts(1).excludedTailAckBits==250, ...
    'An incomplete SDU fragment must not count as delivered payload');
report=struct('deliveredAckBits',sum(ev.ackedBits,'all'), ...
    'effectiveMetricBits',sum(counter.ackedBits,'all'), ...
    'crossSecondBursts',counter.crossSecondBursts, ...
    'zeroDurationBursts',counter.zeroDurationBursts, ...
    'openBurstCount',counter.openBurstCount, ...
    'ue1RateMbps',counter.rateMbps(1,2));
fprintf('CROSS_PROTOCOL delivered=%g metric=%g cross=%d zero=%d open=%d rate=%g\n', ...
 report.deliveredAckBits,report.effectiveMetricBits, ...
 report.crossSecondBursts,report.zeroDurationBursts, ...
 report.openBurstCount,report.ue1RateMbps);
end
