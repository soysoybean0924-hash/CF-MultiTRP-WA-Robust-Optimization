function report=acceptance_multistep(root,branch,outDir)
% Bounded one-group parity and 1+2 continuation, using one immutable input.
assert(~isfolder(outDir));mkdir(outDir);
s=chasi_load_frozen_binary(fullfile(root,'03_研究场景构造','inputs','structured_main_v1'),1);
r=s.resources(1);c=s.config;
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp,'outer_iterations',3, ...
 'outer_rel_tol',c.outerObjectiveRelativeTolerance, ...
 'outer_precoder_tol',c.outerCovarianceRelativeTolerance, ...
 'admm_iterations',15,'cg_iterations',10, ...
 'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
 'pf_floor',c.pfFloor,'users',21*c.usersPerCell,'branch',branch);
full=chasi_matrix_wmmse(r,cfg,{r.initial});
cfg.outer_iterations=1;first=chasi_matrix_wmmse(r,cfg,{r.initial});
firstV=first.precoder{1};save(fullfile(outDir,'resume_checkpoint.mat'),'firstV','-v7');
clear firstV
loaded=load(fullfile(outDir,'resume_checkpoint.mat'),'firstV');
cfg.outer_iterations=2;resumed=chasi_matrix_wmmse(r,cfg,{loaded.firstV});
v=full.precoder{1};vr=resumed.precoder{1};
report=struct('branch',branch,'input_manifest_sha256',s.input_manifest_sha256, ...
 'outer_cap',3,'admm_cap',15,'cg_cap',10, ...
 'full_reason',full.reason,'first_reason',first.reason, ...
 'resumed_reason',resumed.reason, ...
 'full_objective',full.optimization_objective, ...
 'full_true_weighted_sum_se',sum(full.true_per_ue_rate), ...
 'full_max_power_w',max(full.power), ...
 'full_trajectory',{full.trajectory}, ...
 'resume_max_precoder_abs_diff',max(abs(v-vr),[],'all'), ...
 'resume_objective_abs_diff',abs(full.optimization_objective-resumed.optimization_objective), ...
 'resume_true_se_abs_diff',abs(sum(full.true_per_ue_rate)-sum(resumed.true_per_ue_rate)));
fid=fopen(fullfile(outDir,'matlab_summary.json'),'wt');assert(fid>=0);
fprintf(fid,'%s',jsonencode(report,PrettyPrint=true));fclose(fid);
fwritecomplex(fullfile(outDir,'matlab_precoder'),v);
end

function fwritecomplex(base,v)
fid=fopen([base '.real.bin'],'wb');assert(fid>=0);
fwrite(fid,real(v),'double');fclose(fid);
fid=fopen([base '.imag.bin'],'wb');assert(fid>=0);
fwrite(fid,imag(v),'double');fclose(fid);
end
