function report=probe_trp_sharing_admm_formal(root,outPath,maxIterations,rho,epsAbs,epsRel)
%PROBE_TRP_SHARING_ADMM_FORMAL Two formal groups, fixed-U/W bounded probe.
% Keeps 21 TRPs and across-group physical power. An iteration cap is not
% relabeled as convergence; this is separate from full 17-group WA.
addpath(fullfile(root,'03_研究场景构造','matlab'), ...
    fullfile(root,'04_研究方法_WA运行实现','matlab'));
if nargin<3, maxIterations=20; end
if nargin<4, rho=1; end
assert(maxIterations>=1 && maxIterations==floor(maxIterations));
assert(rho>0 && isfinite(rho));
inputPath=fullfile(root,'03_研究场景构造','inputs', ...
    'srs_overlap_jakes_v3_main','input.mat');
x=load(inputPath,'data'); data=x.data; c=data.config;
if nargin<5, epsAbs=c.admmAbsoluteTolerance; end
if nargin<6, epsRel=c.admmRelativeTolerance; end
assert(epsAbs>0 && epsRel>0);
G=2; resources=data.resources(1:G); initial=data.initialPrecoder(1:G);
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp, ...
    'outer_iterations',1,'admm_iterations',c.admmIterations, ...
    'cg_iterations',c.cgIterations, ...
    'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
    'pf_floor',c.pfFloor,'users',data.sceneConfig.users, ...
    'branch','matrix_pf_statistical','capture_first_step',true, ...
    'probe_fixed_receiver_weight',true);
central=chasi_matrix_wmmse(resources,cfg,initial);
probe=central.firstProbe;
distributed=chasi_trp_sharing_admm_fixed_uw(resources,probe.parts, ...
    probe.initialPrecoder,c.powerWattPerTrp,rho=rho, ...
    maxIterations=maxIterations,absoluteTolerance=epsAbs, ...
    relativeTolerance=epsRel);
reference=probe.admmHistory(end).fixed_receiver_weight_precoder_objective;
centralLast=probe.admmHistory(end);
last=distributed.history(end);
report=struct('modelId',data.modelId, ...
    'inputSha256',chasi_sha256_file(inputPath), ...
    'groups',G,'trps',data.sceneConfig.trps,'rho',rho, ...
    'sharingAbsoluteTolerance',epsAbs, ...
    'sharingRelativeTolerance',epsRel, ...
    'centralFixedObjective',reference, ...
    'centralInnerSolved',centralLast.primal<=centralLast.eps_primal && ...
        centralLast.dual<=centralLast.eps_dual && ...
        centralLast.cg_relative<=max(1e-3,10*cfg.eps_rel), ...
    'centralInnerIterations',centralLast.inner, ...
    'centralPrimal',centralLast.primal, ...
    'centralDual',centralLast.dual, ...
    'centralEpsPrimal',centralLast.eps_primal, ...
    'centralEpsDual',centralLast.eps_dual, ...
    'centralCgRelative',centralLast.cg_relative, ...
    'sharingFixedObjective',distributed.fixedObjective, ...
    'sharingIterations',numel(distributed.history), ...
    'sharingConverged',distributed.converged, ...
    'sharingPrimal',last.primal,'sharingDual',last.dual, ...
    'sharingEpsPrimal',last.epsPrimal, ...
    'sharingEpsDual',last.epsDual, ...
    'sharingMaxPowerViolation',distributed.maxPowerViolation, ...
    'coordinationComplexScalarsPerIteration', ...
        distributed.coordinationComplexScalarsPerIteration, ...
    'parallelRuntimeMeasured',false, ...
    'sharingElapsedSeconds',distributed.elapsedSeconds, ...
    'history',distributed.history, ...
    'scope','two formal groups bounded fixed-UW probe, not complete WA');
save(outPath,'report','-v7.3');
fprintf(['FORMAL_TRP_ADMM groups=%d iterations=%d converged=%d ', ...
    'objective=%.7g reference=%.7g primal=%.3g/%.3g ', ...
    'dual=%.3g/%.3g violation=%.3g time=%.3f\n'], ...
    G,report.sharingIterations,report.sharingConverged, ...
    report.sharingFixedObjective,reference,last.primal,last.epsPrimal, ...
    last.dual,last.epsDual,report.sharingMaxPowerViolation, ...
    report.sharingElapsedSeconds);
end
