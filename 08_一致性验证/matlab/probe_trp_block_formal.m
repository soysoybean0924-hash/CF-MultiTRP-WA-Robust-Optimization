function report=probe_trp_block_formal(root,outPath,maxSweeps)
%PROBE_TRP_BLOCK_FORMAL Serial exact local blocks, same fixed-U/W QP.
if nargin<3, maxSweeps=50; end
addpath(fullfile(root,'03_研究场景构造','matlab'), ...
    fullfile(root,'04_研究方法_WA运行实现','matlab'));
inputPath=fullfile(root,'03_研究场景构造','inputs', ...
    'srs_overlap_jakes_v3_main','input.mat');
x=load(inputPath,'data'); data=x.data; c=data.config;
resources=data.resources(1:2); initial=data.initialPrecoder(1:2);
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp, ...
    'outer_iterations',1,'admm_iterations',c.admmIterations, ...
    'cg_iterations',c.cgIterations, ...
    'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
    'pf_floor',c.pfFloor,'users',data.sceneConfig.users, ...
    'branch','matrix_pf_statistical','capture_first_step',true, ...
    'probe_fixed_receiver_weight',true);
central=chasi_matrix_wmmse(resources,cfg,initial);
parts=central.firstProbe.parts;
local=chasi_trp_local_fixed_uw(resources,parts,initial, ...
    c.powerWattPerTrp,maxSweeps);
report=struct('inputSha256',chasi_sha256_file(inputPath), ...
    'groups',2,'trps',data.sceneConfig.trps, ...
    'centralOriginalFixedObjective',central.firstProbe.admmHistory(end).fixed_receiver_weight_precoder_objective, ...
    'blockFixedObjective',local.fixedObjective, ...
    'sweeps',numel(local.history), ...
    'lastRelativePrecoderChange',local.history(end).relativePrecoderChange, ...
    'maxPowerViolation',local.maxPowerViolation, ...
    'elapsedSeconds',local.elapsedSeconds, ...
    'history',local.history, ...
    'method','serial TRP block coordinate, not ADMM');
save(outPath,'report','-v7.3');
fprintf('FORMAL_TRP_BLOCK sweeps=%d objective=%.8g dx=%.4g violation=%.3g time=%.3f\n', ...
    report.sweeps,report.blockFixedObjective, ...
    report.lastRelativePrecoderChange,report.maxPowerViolation, ...
    report.elapsedSeconds);
end
