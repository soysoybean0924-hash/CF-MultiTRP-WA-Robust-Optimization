function link=chasi_v6_link_abstraction(streamSinrDb,config,scene,curvePath, ...
    prbByUeTti,inputSha256)
% Per-attempt block-error contract. No MCS or BLER is inferred from the
% diagnostic SINR without an independently validated matching curve.
[U,R,T]=size(streamSinrDb);assert(U>=1 && R==config.rank && T>=1);
diagnostic=reshape(min(streamSinrDb,[],2),U,T);
if nargin<4 || isempty(curvePath)
 link=struct('mode','fixed_proxy','bler',.05*ones(U,T), ...
     'mcsIndex',nan(U,T),'diagnosticSinrDb',diagnostic, ...
     'transportBlockBits',nan(U,T), ...
     'validated',false,'curveSha256','', ...
     'reason','missing_independent_rank_irc_channel_mcs_bler_calibration');
 return
end
assert(nargin>=6 && isequal(size(prbByUeTti),[U,T]) && ...
    all(prbByUeTti(:)>=0 & prbByUeTti(:)<=273 & ...
    prbByUeTti(:)==fix(prbByUeTti(:))));
assert(isfile(curvePath));x=load(curvePath,'curve');curve=x.curve;
fields={'mcsIndices','sinrGridDb','bler','lower95','upper95', ...
    'sampleCount','generationSeed','validationSeed','rank', ...
    'receiver','channelMode','sinrDefinition', ...
    'selectionThresholdDb','validationPassed', ...
    'inputSha256','tbsBitsByMcsAndPrb', ...
    'codeBlockLengthBitsByMcsAndPrb', ...
    'blerUnit','interferenceModel','transportMapping'};
for j=1:numel(fields),assert(isfield(curve,fields{j}),fields{j});end
assert(curve.rank==config.rank && strcmp(curve.receiver,'linear_irc') && ...
    strcmp(curve.channelMode,config.channelMode) && ...
    strcmp(curve.sinrDefinition,'minimum_post_irc_layer_across_active_groups') && ...
    strcmp(curve.blerUnit,'transport_block') && ...
    strcmp(curve.interferenceModel,'same_multi_trp_interference') && ...
    strcmp(curve.transportMapping,'one_mcs_aggregated_active_prbs_per_ue_tti') && ...
    curve.validationPassed && curve.validationSeed~=curve.generationSeed && ...
    all(isfinite(curve.generationSeed(:))) && ...
    all(isfinite(curve.validationSeed(:))));
assert(strcmp(curve.inputSha256,inputSha256) && ...
    isequal(size(curve.tbsBitsByMcsAndPrb), ...
        [numel(curve.mcsIndices),274]) && ...
    isequal(size(curve.codeBlockLengthBitsByMcsAndPrb), ...
        [numel(curve.mcsIndices),274]) && ...
    all(isfinite(curve.tbsBitsByMcsAndPrb(:)) & ...
        curve.tbsBitsByMcsAndPrb(:)>=0 & ...
        curve.tbsBitsByMcsAndPrb(:)==fix(curve.tbsBitsByMcsAndPrb(:))), ...
    'TBS table must match the frozen input and PRB range');
M=numel(curve.mcsIndices);grid=double(curve.sinrGridDb(:)');
assert(all(diff(grid)>0) && numel(grid)>=2 && M>=1 && ...
    all(curve.mcsIndices(:)==fix(curve.mcsIndices(:))) && ...
    numel(unique(curve.mcsIndices))==M && ...
    isequal(size(curve.bler),[M,274,numel(grid)], ...
    size(curve.lower95),size(curve.upper95),size(curve.sampleCount)));
assert(numel(curve.selectionThresholdDb)==M && ...
    all(isfinite(curve.selectionThresholdDb(:))));
activeDiagnostic=diagnostic(prbByUeTti>0);
assert(all(isfinite(activeDiagnostic(:))) && ...
    all(activeDiagnostic(:)>=grid(1) & activeDiagnostic(:)<=grid(end)), ...
    'SINR outside independent calibration support');
assert(scene.ueRxPorts==4 && scene.ueTxPorts==2);
mcs=nan(U,T);bler=nan(U,T);tbs=zeros(U,T);
for u=1:U,for t=1:T
 if prbByUeTti(u,t)==0
  bler(u,t)=0;continue
 end
 eligible=find(diagnostic(u,t)>=curve.selectionThresholdDb);
 assert(~isempty(eligible),'No MCS calibrated at this SINR');
 [~,j]=max(curve.mcsIndices(eligible));idx=eligible(j);
 mcs(u,t)=curve.mcsIndices(idx);
 tbs(u,t)=curve.tbsBitsByMcsAndPrb(idx,prbByUeTti(u,t)+1);
 assert(tbs(u,t)>0 && ...
     curve.codeBlockLengthBitsByMcsAndPrb(idx,prbByUeTti(u,t)+1)>0, ...
     'Calibrated MCS has no TBS/code-block contract on allocated PRBs');
 p=prbByUeTti(u,t)+1;
 bvec=reshape(double(curve.bler(idx,p,:)),1,[]);
 lo=reshape(double(curve.lower95(idx,p,:)),1,[]);
 hi=reshape(double(curve.upper95(idx,p,:)),1,[]);
 count=reshape(double(curve.sampleCount(idx,p,:)),1,[]);
 assert(all(isfinite(bvec) & bvec>=0 & bvec<=1 & ...
     isfinite(lo) & lo>=0 & lo<=bvec & ...
     isfinite(hi) & bvec<=hi & hi<=1 & ...
     isfinite(count) & count>=100 & count==fix(count)), ...
     'Independent BLER support missing for selected MCS/PRB');
 bler(u,t)=interp1(grid,bvec, ...
     diagnostic(u,t),'linear');
end,end
link=struct('mode','calibrated_curve','bler',bler,'mcsIndex',mcs, ...
    'transportBlockBits',tbs, ...
    'diagnosticSinrDb',diagnostic,'validated',true, ...
    'curveSha256',chasi_sha256_file(curvePath), ...
    'reason','independent_matching_curve_within_support');
end
