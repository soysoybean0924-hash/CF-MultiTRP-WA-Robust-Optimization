function d=diagnose_arvidson_probe(probePath,outPath)
%DIAGNOSE_ARVIDSON_PROBE Quantify why the first Eq.23 probe is unusable.
s=load(probePath,'result'); r=s.result;
X=double(r.testFeatures); y=double(r.testObserved(:));
p=double(r.testPredicted(:));
assert(size(X,1)==numel(y) && all(isfinite(y)));
% The stored original probe includes its training-mean constant error.
% Training rows were not saved, so a separate total-error comparator cannot
% be fit without rerunning the generator. Never tune it on held-out rows.
d=struct('target','single_draw_absolute_complex_error_not_RMSE', ...
 'unit','normalized channel amplitude','count',numel(y), ...
 'targetMean',mean(y),'targetMedian',median(y), ...
 'targetP05',prctile(y,5),'targetP95',prctile(y,95), ...
 'eq23Mae',mean(abs(p-y)), ...
 'eq23NormalizedMae',mean(abs(p-y))/max(mean(y),eps), ...
 'constantMae',double(r.testConstantMae), ...
 'totalAmplitudeMae',NaN, ...
 'totalBaselineReason','original probe did not save training features', ...
 'featureCorrelation',corr(X), ...
 'featureCondition',cond(X), ...
 'featureRank',rank(X), ...
 'coefficients',r.coefficients, ...
 'decision','reject_probe_as_conditional_RMSE_calibration');
save(outPath,'d','-v7');
end
