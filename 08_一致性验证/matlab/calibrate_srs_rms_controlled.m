function result=calibrate_srs_rms_controlled(outPath)
%CALIBRATE_SRS_RMS_CONTROLLED Eq.23 amplitude fit to independent MF trials.
% Flat channels imply no impulse-response truncation: alpha is fixed zero.
% Conditions, rather than individual absolute-error draws, are split.
stream=RandStream('mt19937ar','Seed',1721);
rb=[16 17]; noiseVariance=0.01; repeats=400; count=120;
X=zeros(count,3); rmsError=zeros(count,1); details=zeros(count,4);
for c=1:count
 N=6*rb(1+mod(c,2)); n=(0:N-1)';
 same=(mod(c,3)==0); if same, q=ones(N,1);
 else, q=exp(2i*pi*n/8); end
 rho=mean(q); targetAmplitude=0.2+1.8*rand(stream);
 interfererAmplitude=2*rand(stream);
 noise=sqrt(noiseVariance/2)*(randn(stream,N,repeats)+1i*randn(stream,N,repeats));
 h=interfererAmplitude*exp(2i*pi*rand(stream,1,repeats));
 y=targetAmplitude+q*h+noise;
 estimate=mean(y,1).';
 rmsError(c)=sqrt(mean(abs(estimate-targetAmplitude).^2));
 X(c,:)=[interfererAmplitude*double(same), ...
     interfererAmplitude*double(~same),1];
 details(c,:)=[rb(1+mod(c,2)),same,targetAmplitude,interfererAmplitude];
end
% Predeclared disjoint condition sets. No test-set tuning.
order=randperm(stream,count); train=order(1:72); tune=order(73:96); test=order(97:120);
coef=lsqnonneg(X(train,:),rmsError(train));
predict=X*coef; constant=mean(rmsError(train));
% Separate simple total-variance comparator, fitted on training conditions
% only. It does not reinterpret Eq.23's linear standard-deviation sum.
Z=[X(:,1).^2,X(:,2).^2,ones(count,1)];
quadratureCoef=lsqnonneg(Z(train,:),rmsError(train).^2);
quadraturePredict=sqrt(max(0,Z*quadratureCoef));
result=struct('seed',1721,'repeatsPerCondition',repeats, ...
 'model','Eq23_flat_MF_project_calibration', ...
 'targetUnit','complex flat matched-filter channel amplitude RMS', ...
 'alphaTruncation',0,'betaSame',coef(1),'betaOther',coef(2), ...
 'gamma',coef(3),'noiseVariancePerRE',noiseVariance, ...
 'trainMae',mean(abs(predict(train)-rmsError(train))), ...
 'tuneMae',mean(abs(predict(tune)-rmsError(tune))), ...
 'testMae',mean(abs(predict(test)-rmsError(test))), ...
 'testConstantMae',mean(abs(constant-rmsError(test))), ...
 'testQuadratureMae',mean(abs(quadraturePredict(test)-rmsError(test))), ...
 'testQuadratureRelativeMae', ...
     mean(abs(quadraturePredict(test)-rmsError(test)))/mean(rmsError(test)), ...
 'testTargetMean',mean(rmsError(test)), ...
 'testTargetMedian',median(rmsError(test)), ...
 'testTargetP05',prctile(rmsError(test),5), ...
 'testTargetP95',prctile(rmsError(test),95), ...
 'quadratureVarianceCoefficients',quadratureCoef, ...
 'quadraturePredictedRms',quadraturePredict, ...
 'testRelativeMae',mean(abs(predict(test)-rmsError(test)))/mean(rmsError(test)), ...
 'designRank',rank(X(train,:)), 'designCondition',cond(X(train,:)), ...
 'trainIndices',train,'tuneIndices',tune,'testIndices',test, ...
 'conditions',details,'empiricalRms',rmsError,'predictedRms',predict, ...
 'scope','flat scalar MF; no array covariance or aging calibration');
save(outPath,'result','-v7');
end
