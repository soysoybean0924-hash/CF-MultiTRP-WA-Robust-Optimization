function report=acceptance_derived_stop(root,outDir)
% Same first-two-UE service-TRP slice as acceptance_derived_stop.py.
assert(~isfolder(outDir));mkdir(outDir);
s=chasi_load_frozen_binary(fullfile(root,'03_研究场景构造','inputs','structured_main_v1'),1);
r=s.resources(1);u=1:2;l=find(any(r.servingMask(:,u),2));
r.H=r.H(u,l,:,:);r.H_hat=r.H_hat(u,l,:,:);
r.H_true=r.H_true(u,l,:,:);
r.C=r.C(u,l,:,:);r.C_stat=r.C_stat(u,l,:,:);
r.servingMask=r.servingMask(l,u);r.ueIds=r.ueIds(u);
initial=r.initial(l,u,:,:);r.initial=initial;
c=s.config;
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp, ...
 'outer_iterations',500,'outer_rel_tol',c.outerObjectiveRelativeTolerance, ...
 'outer_precoder_tol',c.outerCovarianceRelativeTolerance, ...
 'admm_iterations',c.admmIterations,'cg_iterations',c.cgIterations, ...
 'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
 'pf_floor',c.pfFloor,'users',21*c.usersPerCell,'branch','matrix_statistical');
tic;sol=chasi_matrix_wmmse(r,cfg,{initial});elapsed=toc;
v=sol.precoder{1};
report=struct('input_manifest_sha256',s.input_manifest_sha256, ...
 'derived_slice','group 1, first 2 scheduled UEs, union of their original serving TRPs', ...
 'global_user_ids_one_based',double(r.ueIds(:))', ...
 'trp_ids_one_based',double(l(:))', ...
 'outer_cap',500,'admm_cap',c.admmIterations,'cg_cap',c.cgIterations, ...
 'reason',sol.reason,'converged',sol.converged, ...
 'stopped_outer',sol.trajectory(end).outer, ...
 'objective',sol.optimization_objective, ...
 'true_weighted_sum_se',sum(sol.true_per_ue_rate), ...
 'max_power_w',max(sol.power),'wall_seconds',elapsed, ...
 'outer_objectives',[sol.trajectory.objective]);
fid=fopen(fullfile(outDir,'summary.json'),'wt');assert(fid>=0);
fprintf(fid,'%s',jsonencode(report,PrettyPrint=true));fclose(fid);
fid=fopen(fullfile(outDir,'precoder.real.bin'),'wb');assert(fid>=0);
fwrite(fid,real(v),'double');fclose(fid);
fid=fopen(fullfile(outDir,'precoder.imag.bin'),'wb');assert(fid>=0);
fwrite(fid,imag(v),'double');fclose(fid);
end
