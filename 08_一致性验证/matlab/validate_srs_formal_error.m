function report=validate_srs_formal_error(root,outPath,inputPath)
%VALIDATE_SRS_FORMAL_ERROR Offline held-out truth check of formal input C.
% The same simulator generates truth and posterior, so this checks the
% implementation and finite-sample coverage, not external calibration.
addpath(fullfile(root,'03_研究场景构造','matlab'));
if nargin<3
    inputPath=fullfile(root,'03_研究场景构造','inputs', ...
        'srs_overlap_jakes_v3_main','input.mat');
end
loaded=load(inputPath,'data'); data=loaded.data;
inputHash=chasi_sha256_file(inputPath);
assert(strcmp(inputHash,strtrim(fileread([inputPath '.sha256']))));
G=numel(data.resources); age=zeros(G,1); groupMean=zeros(G,1);
groupCount=zeros(G,1); errors=cell(G,1); exposures=cell(G,1);
for g=1:G
    r=data.resources(g); [K,L,Nr,Nt]=size(r.H);
    e=zeros(K*L,1); risk=zeros(K*L,1); t=0;
    for k=1:K
        for l=1:L
            t=t+1;
            delta=reshape(double(r.H_true(k,l,:,:))- ...
                double(r.H(k,l,:,:)),Nr,Nt);
            C=reshape(double(r.C(k,l,:,:)),Nr,Nr);
            C=(C+C')/2;
            [factor,p]=chol(C,'lower');
            assert(p==0,'Formal posterior covariance is not positive definite');
            z=factor\delta;
            e(t)=sum(abs(z).^2,'all')/(Nr*Nt);
            risk(t)=double(r.srs_source_risk(k,l,1));
        end
    end
    errors{g}=e; exposures{g}=risk;
    age(g)=double(r.age_ms); groupMean(g)=mean(e);
    groupCount(g)=numel(e);
end
allError=vertcat(errors{:}); allRisk=vertcat(exposures{:});
ordered=sort(allRisk); threshold=ordered(max(1,ceil(.75*numel(ordered))));
highRisk=allRisk>=threshold;
d=Nr*Nt;
gaussianRadius95SquaredNormalized=gammaincinv(.95,d)/d;
report=struct('modelId',data.modelId,'inputSha256',inputHash, ...
    'sampleScope','scheduled UE-TRP links and all transmit ports', ...
    'normalizedSquaredErrorDefinition', ...
    'sum(abs(chol(C) inverse times (Htrue-Hhat)).^2)/(Nr*Nt)', ...
    'expectedMeanUnderModel',1,'observedMean',mean(allError), ...
    'observedMedian',median(allError), ...
    'gaussianEllipsoidConfidence',.95, ...
    'gaussianRadius95SquaredNormalized', ...
        gaussianRadius95SquaredNormalized, ...
    'empiricalCoverageAt95', ...
        mean(allError<=gaussianRadius95SquaredNormalized), ...
    'boundMeaning','95 percent probability under assumed complex Gaussian posterior, not absolute bound', ...
    'highRiskMean',mean(allError(highRisk)), ...
    'otherRiskMean',mean(allError(~highRisk)), ...
    'riskUpperQuartileThreshold',threshold, ...
    'ageMs',age,'groupMean',groupMean,'groupCount',groupCount, ...
    'normalizedSquaredError',allError, ...
    'offlineTruthOnly',true, ...
    'limitation','single formal simulated realization, not independent field calibration');
save(outPath,'report','-v7.3');
fprintf('FORMAL_ERROR links=%d whitenedMean=%.6g highRisk=%.6g other=%.6g\n', ...
    numel(allError),report.observedMean, ...
    report.highRiskMean,report.otherRiskMean);
end
