function report=validate_trp_sharing_admm_fixed_uw(outPath)
%VALIDATE_TRP_SHARING_ADMM_FIXED_UW Exact same tiny fixed-U/W reference.
stream=RandStream('mt19937ar','Seed',2281);
G=2; L=2; K=2; Nr=2; Nt=2; streams=1; budget=1;
resources=repmat(struct('H',[],'C',[],'servingMask',[], ...
    'resourceWeightNu',.5),1,G);
initial=cell(1,G);
for g=1:G
    resources(g).H=cn(stream,K,L,Nr,Nt);
    resources(g).C=complex(zeros(K,L,Nr,Nr));
    for k=1:K
        for l=1:L
            resources(g).C(k,l,:,:)=reshape(.02*eye(Nr),1,1,Nr,Nr);
        end
    end
    resources(g).servingMask=true(L,K);
    initial{g}=.1*cn(stream,L,K,Nt,streams);
end
cfg=struct('branch','matrix_sum','rank',streams,'budget',budget, ...
    'outer_iterations',1,'admm_iterations',250,'cg_iterations',100, ...
    'eps_abs',1e-7,'eps_rel',1e-6, ...
    'capture_first_step',true,'probe_fixed_receiver_weight',true);
central=chasi_matrix_wmmse(resources,cfg,initial);
p=central.firstProbe;
distributed=chasi_trp_sharing_admm_fixed_uw(resources,p.parts, ...
    p.initialPrecoder,budget,rho=1,maxIterations=1000, ...
    absoluteTolerance=1e-7,relativeTolerance=1e-6);
reference=p.admmHistory(end).fixed_receiver_weight_precoder_objective;
gap=(distributed.fixedObjective-reference)/max(1,abs(reference));
assert(distributed.maxPowerViolation<1e-8);
assert(distributed.converged,'Sharing ADMM did not meet its own residuals');
assert(abs(gap)<3e-3, ...
    'TRP sharing ADMM differs from centralized fixed-U/W reference');
last=distributed.history(end);
report=struct('seed',2281,'groups',G,'trps',L, ...
    'usersPerGroup',K,'centralFixedObjective',reference, ...
    'trpSharingFixedObjective',distributed.fixedObjective, ...
    'relativeObjectiveGap',gap, ...
    'centralADMMIterations',p.admmHistory(end).inner, ...
    'sharingADMMIterations',numel(distributed.history), ...
    'sharingPrimal',last.primal,'sharingDual',last.dual, ...
    'sharingEpsPrimal',last.epsPrimal, ...
    'sharingEpsDual',last.epsDual, ...
    'sharingElapsedSeconds',distributed.elapsedSeconds, ...
    'coordinationComplexScalarsPerIteration', ...
        distributed.coordinationComplexScalarsPerIteration, ...
    'parallelRuntimeMeasured',distributed.parallelRuntimeMeasured, ...
    'maxPowerViolation',distributed.maxPowerViolation);
save(outPath,'report','-v7');
fprintf('TRP_ADMM gap=%.5g iters=%d primal=%.3g/%.3g dual=%.3g/%.3g violation=%.3g\n', ...
    gap,report.sharingADMMIterations,last.primal,last.epsPrimal, ...
    last.dual,last.epsDual,distributed.maxPowerViolation);
end

function x=cn(stream,varargin)
x=(randn(stream,varargin{:})+1i*randn(stream,varargin{:}))/sqrt(2);
end
