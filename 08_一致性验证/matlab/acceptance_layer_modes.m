function acceptance_layer_modes(root,outDir)
% Four one-group protected modes with common frozen V and two WA updates.
assert(~isfolder(outDir));mkdir(outDir);
inputRoot=fullfile(root,'03_研究场景构造','inputs','structured_main_v1');
configPath=fullfile(root,'05_研究创新点_鲁棒施加','config','study.json');
s=chasi_load_frozen_binary(inputRoot);c=s.config;
cfg=jsondecode(fileread(configPath));layer=chasi_layer1_calibrate(s.resources,cfg);
modes={'uniform','variable','fixed','mapped'};
for j=1:numel(modes)
 mode=modes{j};r=s.resources(1);
 [rr,meta]=chasi_layer_protection(r,layer,cfg,mode,cfg.fixed_level);
 initial=r.initial.*reshape(rr.servingMask,size(rr.servingMask,1),size(rr.servingMask,2),1,1);
 solverCfg=struct('rank',c.rank,'budget',meta.effective_cap_w, ...
  'outer_iterations',2,'outer_rel_tol',c.outerObjectiveRelativeTolerance, ...
  'outer_precoder_tol',c.outerCovarianceRelativeTolerance, ...
  'admm_iterations',15,'cg_iterations',10, ...
  'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
  'pf_floor',c.pfFloor,'users',21*c.usersPerCell,'branch','matrix_statistical');
 sol=chasi_matrix_wmmse(rr,solverCfg,{initial});v=sol.precoder{1};
 row=struct('mode',mode,'input_manifest_sha256',s.input_manifest_sha256, ...
  'config_sha256',chasi_sha256_file(configPath),'outer_cap',2,'admm_cap',15, ...
  'cg_cap',10,'initialization','frozen initial V masked by protected service', ...
  'mechanism',struct('strengths',meta.strengths,'effective_cap_w',meta.effective_cap_w, ...
   'changed_service_links',meta.changed_service_links), ...
  'reason',sol.reason,'objective',sol.optimization_objective, ...
  'true_weighted_sum_se',sum(sol.true_per_ue_rate), ...
  'max_power_w',max(sol.power),'trajectory',{sol.trajectory});
 fid=fopen(fullfile(outDir,[mode '.json']),'wt');assert(fid>=0);
 fprintf(fid,'%s',jsonencode(row,PrettyPrint=true));fclose(fid);
 fid=fopen(fullfile(outDir,[mode '.real.bin']),'wb');assert(fid>=0);
 fwrite(fid,real(v),'double');fclose(fid);
 fid=fopen(fullfile(outDir,[mode '.imag.bin']),'wb');assert(fid>=0);
 fwrite(fid,imag(v),'double');fclose(fid);
 fprintf('%s %s %.12g\n',mode,sol.reason,row.true_weighted_sum_se);
end
end
