function report=export_srs_layer_activation(root,outPath)
%EXPORT_SRS_LAYER_ACTIVATION Evidence for implemented and missing layers.
% All decisions use estimated inputs. Held-out H_true is not read here.
addpath(fullfile(root,'03_研究场景构造','matlab'));
inputPath=fullfile(root,'03_研究场景构造','inputs', ...
    'srs_overlap_jakes_v3_main','input.mat');
inputHash=chasi_sha256_file(inputPath);
x=load(inputPath,'data'); data=x.data; resources=data.resources;
outDir=fullfile(root,'07_实验结果与进展','local_runs', ...
    'srs_overlap_jakes_v3_main');
names={'ideal_pf','nominal_pf','robust_pf'};
states=cell(1,3); power=zeros(3,data.sceneConfig.trps);
for i=1:3
    s=load(fullfile(outDir,names{i},'latest.mat'),'state');
    states{i}=s.state;
    assert(strcmp(states{i}.inputSha256,inputHash));
    for g=1:numel(resources)
        nu=double(resources(g).resourceWeightNu);
        for l=1:size(states{i}.precoder{g},1)
            power(i,l)=power(i,l)+nu* ...
                sum(abs(states{i}.precoder{g}(l,:,:,:)).^2,'all');
        end
    end
end
linkC=[]; linkGain=[]; ages=[]; pilotRisk=[];
for g=1:numel(resources)
    r=resources(g); [K,L,~,Nt]=size(r.H);
    for k=1:K
        for l=1:L
            linkC(end+1,1)=real(trace(squeeze(double(r.C(k,l,:,:)))))*Nt; %#ok<AGROW>
            linkGain(end+1,1)=sum(abs(r.H(k,l,:,:)).^2,'all'); %#ok<AGROW>
            ages(end+1,1)=double(r.age_ms); %#ok<AGROW>
            pilotRisk(end+1,1)=double(r.srs_source_risk(k,l,1)); %#ok<AGROW>
        end
    end
end
serviceFile=fullfile(outDir,'gram_service_experimental','latest.mat');
service=struct('available',isfile(serviceFile));
if service.available
    y=load(serviceFile,'state'); state=y.state;
    assert(strcmp(state.inputSha256,inputHash));
    service.changedLinks=state.service.changedLinks;
    service.totalLinks=state.service.totalLinks;
    service.outerSteps=state.iter;
    service.complete=state.complete;
    service.stopReason=state.stopReason;
    service.lastTrueR5=state.history(end).trueR5;
    exposure=[];
    for g=1:numel(state.service.interferenceToOwnPrior)
        block=state.service.interferenceToOwnPrior{g};
        exposure=[exposure;block(:)]; %#ok<AGROW>
    end
    service.pilotGramExposureMinMedianMax= ...
        [min(exposure),median(exposure),max(exposure)];
    strength=exposure./(1+exposure);
    service.implicitServiceProtectionStrengthMinMedianMax= ...
        [min(strength),median(strength),max(strength)];
    service.strengthDefinition= ...
        'interferenceToOwnPrior/(1+interferenceToOwnPrior); service score multiplies by 1-strength';
end
report=struct('modelId',data.modelId,'inputSha256',inputHash, ...
    'sourceStatistic','analytic total posterior C and pilot-Gram exposure feature', ...
    'sourceCovarianceSplitInternallyValidated',true, ...
    'sourceCovarianceSplitExternallyValidated',false, ...
    'beamTotalCActiveInRobustBranch',true, ...
    'beamExtraCovarianceActive',false, ...
    'serviceGramExperimental',service, ...
    'independentPowerLayerActive',false, ...
    'jointVAmpitudeOptimizesPower',true, ...
    'linkwiseConservatismMapActive',false, ...
    'linkCount',numel(linkC), ...
    'ageMsMinMax',[min(ages),max(ages)], ...
    'posteriorCTraceTimesPortsMinMedianMax', ...
        [min(linkC),median(linkC),max(linkC)], ...
    'estimatedChannelNormSquaredMinMedianMax', ...
        [min(linkGain),median(linkGain),max(linkGain)], ...
    'sameLabelPriorRiskMinMedianMax', ...
        [min(pilotRisk),median(pilotRisk),max(pilotRisk)], ...
    'branchPowerWatt',power,'powerDifferenceRobustMinusNominalWatt', ...
        power(3,:)-power(2,:), ...
    'physicalCapPerTrpWatt',data.config.powerWattPerTrp, ...
    'branchOuterSteps',cellfun(@(s)s.iter,states), ...
    'branchComplete',cellfun(@(s)s.complete,states));
save(outPath,'report','-v7');
jsonPath=strrep(outPath,'.mat','.json');
fid=fopen(jsonPath,'wt'); assert(fid>=0);
fprintf(fid,'%s',jsonencode(report,PrettyPrint=true)); fclose(fid);
end
