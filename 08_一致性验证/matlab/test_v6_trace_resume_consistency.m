function report=test_v6_trace_resume_consistency(root,inputPath,configDir,firstTti,finalTti)
% Future licensed test: two isolated short runs, one uninterrupted and one
% resumed. Requires an already frozen v6 input; generates no input here.
startup;
assert(firstTti>=1 && finalTti>firstTti && ...
    finalTti==fix(finalTti) && isfile(inputPath));
x=load(inputPath,'data');d=x.data;
assert(d.schemaVersion==6 && ~isempty(d.channelTracePath) && ...
    isfile(d.channelTracePath));
absolute=d.config.decisionTti+firstTti;
a=chasi_v6_channel_trace(d.channelTracePath, ...
    d.channelTraceScene,1,absolute,1:2);
chasi_v6_channel_trace(d.channelTracePath, ...
    d.channelTraceScene,1,absolute+1,1:2);
b=chasi_v6_channel_trace(d.channelTracePath, ...
    d.channelTraceScene,1,absolute,1:2);
assert(isequaln(a,b),'Trace changed under out-of-order reconstruction');
freshDir=[tempname '_v6_fresh'];
resumeDir=[tempname '_v6_resume'];
override=struct('admm_iterations',2,'cg_iterations',3);
fresh=run_v5_online_six(root,inputPath,configDir, ...
    freshDir,finalTti,1,override,'offline','centralized');
partial=run_v5_online_six(root,inputPath,configDir, ...
    resumeDir,firstTti,1,override,'offline','centralized');
assert(partial.iter==firstTti);
resumed=run_v5_online_six(root,inputPath,configDir, ...
    resumeDir,finalTti,1,override,'offline','centralized');
assert(any([fresh.eventLog(firstTti+1:finalTti).waTrigger]), ...
    'Resume interval did not cross an SRS/CSI-RS WA update');
same=isequaln(fresh.trueRate,resumed.trueRate) && ...
    isequaln(fresh.powerW,resumed.powerW) && ...
    isequaln(fresh.capacityBits,resumed.capacityBits) && ...
    isequaln(fresh.streamSinrDb,resumed.streamSinrDb) && ...
    isequaln(fresh.proxyRateMbps,resumed.proxyRateMbps) && ...
    isequaln(fresh.precoders,resumed.precoders) && ...
    isequaln(fresh.finalAirPrecoder,resumed.finalAirPrecoder) && ...
    isequaln(fresh.arrivalBits,resumed.arrivalBits) && ...
    isequaln(fresh.commonAckDraw,resumed.commonAckDraw) && ...
    isequaln(fresh.actualRbByGroupTti,resumed.actualRbByGroupTti) && ...
    isequaln(fresh.rngState,resumed.rngState) && ...
    isequal({fresh.waLog.branch},{resumed.waLog.branch}) && ...
    isequal([fresh.waLog.tti],[resumed.waLog.tti]) && ...
    isequal({fresh.waLog.solverStatus}, ...
        {resumed.waLog.solverStatus}) && ...
    isequal([fresh.waLog.powerFeasible], ...
        [resumed.waLog.powerFeasible]);
assert(same,'Uninterrupted and resumed online outputs differ');
for g=1:numel(fresh.resources)
 assert(isequaln(fresh.resources(g).H_true, ...
     resumed.resources(g).H_true) && ...
     isequaln(fresh.resources(g).H,resumed.resources(g).H) && ...
     isequaln(fresh.resources(g).C,resumed.resources(g).C) && ...
     isequaln(fresh.resources(g).sourceCov5, ...
         resumed.resources(g).sourceCov5) && ...
     isequaln(fresh.resources(g).sourceCross, ...
         resumed.resources(g).sourceCross));
end
report=struct('sameOutOfOrderTrace',isequaln(a,b), ...
    'sameFirstAndResumedOutput',same, ...
    'inputSha256',fresh.identity.inputSha256, ...
    'traceSha256',fresh.identity.channelTraceSha256, ...
    'freshCheckpoint',fullfile(freshDir,'latest.mat'), ...
    'resumedCheckpoint',fullfile(resumeDir,'latest.mat'), ...
    'firstTti',firstTti,'finalTti',finalTti);
end
