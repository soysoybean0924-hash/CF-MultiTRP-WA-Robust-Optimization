function report=validate_six_branch_entry_small(inputRoot,outPath)
% One resource group, one outer update, reduced inner cap; entry coverage only.
scene=chasi_load_frozen_binary(inputRoot,1);r=scene.resources;
c=scene.config;
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp,'outer_iterations',1, ...
 'outer_rel_tol',c.outerObjectiveRelativeTolerance, ...
 'outer_precoder_tol',c.outerCovarianceRelativeTolerance, ...
 'admm_iterations',3,'cg_iterations',10, ...
 'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
 'pf_floor',c.pfFloor,'users',21*c.usersPerCell);
names={'ideal_sumse','nominal_sumse','robust_sumse','ideal_pf','nominal_pf','robust_pf'};
branches={'ideal','matrix_nominal','matrix_statistical', ...
 'ideal_pf','matrix_pf_nominal','matrix_pf_statistical'};
rows=struct('name',{},'reason',{},'true_weighted_sum_se',{},'max_power_w',{});
for i=1:numel(names)
 rr=r;cfg.branch=branches{i};
 sol=chasi_matrix_wmmse(rr,cfg,{rr.initial});
 rows(i)=struct('name',names{i},'reason',sol.reason, ...
  'true_weighted_sum_se',sum(sol.true_per_ue_rate), ...
  'max_power_w',max(sol.power(:)));
end
report=struct('input_manifest_sha256',scene.input_manifest_sha256, ...
 'scope','one group, one outer, three ADMM inner max; not convergence', ...
 'rows',rows);
if nargin>=2 && ~isempty(outPath)
 assert(~isfile(outPath));fid=fopen(outPath,'wt');assert(fid>=0);
 fprintf(fid,'%s',jsonencode(report,PrettyPrint=true));fclose(fid);
end
end
