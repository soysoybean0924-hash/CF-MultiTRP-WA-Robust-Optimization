function report=test_v6_power_ablation_pair_and_gate(root,inputPath,baseConfigDir,constrainedConfigDir)
% Future licensed integration test; consumes an existing frozen v6 input.
% Test artifacts go to unique temporary directories, not formal results.
startup;
assert(isfile(inputPath) && isfolder(baseConfigDir) && ...
    isfolder(constrainedConfigDir));
spec=jsondecode(fileread(fullfile(constrainedConfigDir, ...
    'source_all.json')));
assert(isfield(spec,'experienceConstraint') && ...
    isempty(spec.experienceConstraint.proxyCalibrationPath), ...
    'Gate test requires the uncalibrated constrained ablation');
baseDir=[tempname '_v6_source_all'];
constrainedDir=[tempname '_v6_power_constrained'];
override=struct('admm_iterations',2,'cg_iterations',3);
base=run_v5_online_six(root,inputPath,baseConfigDir,baseDir, ...
    1,1,override,'offline','centralized');
constrained=run_v5_online_six(root,inputPath, ...
    constrainedConfigDir,constrainedDir, ...
    1,1,override,'offline','centralized');
assert(isequaln(base.arrivalBits,constrained.arrivalBits) && ...
    isequaln(base.commonAckDraw,constrained.commonAckDraw) && ...
    isequaln(base.actualRbByGroupTti, ...
        constrained.actualRbByGroupTti));
baseCheckpoint=fullfile(baseDir,'latest.mat');
constrainedCheckpoint=fullfile(constrainedDir,'latest.mat');
powerPair=chasi_v6_compare_power_ablation_runs( ...
    baseCheckpoint,constrainedCheckpoint);
assert(powerPair.paired && ...
    powerPair.sameFiveControlBranchBeamsAtEveryWa && ...
    powerPair.sameUnconstrainedSourceBeamAtEveryWa);
save(fullfile(constrainedDir, ...
    sprintf('power_ablation_pair_tti_%04d.mat',constrained.iter)), ...
    'powerPair','-v7.3');
summary=chasi_v5_protocol_finalize(root,inputPath, ...
    constrainedCheckpoint,[tempname '_v6_gate_eval'],'');
assert(~strcmp(summary.edgeStatus,'pass') && ...
    ~strcmp(summary.powerStatus,'pass') && ...
    ismember('missing_validated_sinr_mcs_bler_curve', ...
        summary.blockingReasons) && ...
    ismember('independent_seed_proxy_ack_calibration_missing_or_failed', ...
        summary.blockingReasons), ...
    'Uncalibrated proxy or BLER produced a formal target decision');
report=struct('paired',powerPair.paired, ...
    'baseCheckpoint',baseCheckpoint, ...
    'constrainedCheckpoint',constrainedCheckpoint, ...
    'edgeStatus',summary.edgeStatus, ...
    'powerStatus',summary.powerStatus, ...
    'blockingReasons',{summary.blockingReasons});
end
