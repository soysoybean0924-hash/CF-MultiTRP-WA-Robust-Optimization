function report=tight_central_fixed_uw_two_groups(root,outPath)
%TIGHT_CENTRAL_FIXED_UW_TWO_GROUPS Compare sharing ADMM at tighter precision.
addpath(fullfile(root,'03_研究场景构造','matlab'), ...
    fullfile(root,'04_研究方法_WA运行实现','matlab'));
inputPath=fullfile(root,'03_研究场景构造','inputs', ...
    'srs_overlap_jakes_v3_main','input.mat');
x=load(inputPath,'data'); data=x.data; c=data.config;
resources=data.resources(1:2); initial=data.initialPrecoder(1:2);
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp, ...
    'outer_iterations',1,'admm_iterations',1000, ...
    'cg_iterations',c.cgIterations,'eps_abs',1e-7,'eps_rel',1e-6, ...
    'pf_floor',c.pfFloor,'users',data.sceneConfig.users, ...
    'branch','matrix_pf_statistical','capture_first_step',true, ...
    'probe_fixed_receiver_weight',true);
start=tic; out=chasi_matrix_wmmse(resources,cfg,initial);
p=out.firstProbe.admmHistory(end);
report=struct('inputSha256',chasi_sha256_file(inputPath), ...
    'groups',2,'trps',data.sceneConfig.trps, ...
    'fixedObjective',p.fixed_receiver_weight_precoder_objective, ...
    'innerIterations',p.inner, ...
    'converged',p.primal<=p.eps_primal && p.dual<=p.eps_dual && ...
        p.cg_relative<=max(1e-3,10*cfg.eps_rel), ...
    'primal',p.primal,'dual',p.dual, ...
    'epsPrimal',p.eps_primal,'epsDual',p.eps_dual, ...
    'cgRelative',p.cg_relative, ...
    'maxPowerViolation',p.max_power_violation, ...
    'elapsedSeconds',toc(start));
save(outPath,'report','-v7');
fprintf('CENTRAL_TIGHT obj=%.8g inner=%d solved=%d primal=%.3g/%.3g dual=%.3g/%.3g time=%.3f\n', ...
    report.fixedObjective,report.innerIterations,report.converged, ...
    p.primal,p.eps_primal,p.dual,p.eps_dual,report.elapsedSeconds);
end
