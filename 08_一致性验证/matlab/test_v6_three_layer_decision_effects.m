function report=test_v6_three_layer_decision_effects(root)
% Synthetic five-source decisions: service mask, WA beam and link power.
startup;
K=2;L=2;Nr=2;Nt=2;H=complex(zeros(K,L,Nr,Nt));
H(1,1,1,1)=sqrt(2);H(1,2,1,1)=sqrt(1.8);
H(2,1,2,2)=sqrt(2);H(2,2,2,2)=sqrt(1.8);
C=complex(zeros(K,L,Nr,Nr));five=complex(zeros(K,L,Nr,Nr,5));
for k=1:K,for l=1:L
 block=.5*eye(Nr);C(k,l,:,:)=reshape(block,1,1,Nr,Nr);
 if (k==1 && l==1) || (k==2 && l==2)
  fractions=[.2 .7 0 .1 0];
 else
  fractions=[.8 .1 0 .1 0];
 end
 for q=1:5
  five(k,l,:,:,q)=reshape(fractions(q)*block,1,1,Nr,Nr,1);
 end
end,end
four=cat(5,five(:,:,:,:,1:2), ...
    five(:,:,:,:,3)+five(:,:,:,:,5),five(:,:,:,:,4));
r=struct('H',H,'C',C,'C_stat',C, ...
    'sourceCov',four,'sourceCov5',five, ...
    'sourceCross',complex(zeros(size(C))), ...
    'servingMask',logical([1 1;0 0]), ...
    'ueIds',(1:K)','age_ms',20,'resourceWeightNu',.5);
data=struct('modelId','srs_csi_joint_v6_formal', ...
    'resources',r,'config',struct('powerWattPerTrp',2, ...
    'revisitTti',20,'ttiMs',1));
p=struct('enabled',false(5,3),'strength',ones(5,3), ...
    'powerReserveFraction',.5,'serviceMargin',0);
[off,~]=chasi_v3_source_policy(data,1,p);
p.enabled(2,1)=true;
[service,~]=chasi_v3_source_policy(data,1,p);
assert(~isequaln(off.servingMask,service.servingMask) && ...
    isequal(sum(off.servingMask,1),sum(service.servingMask,1)), ...
    'Pilot-pollution service switch did not change service');
p.enabled(:)=false;p.enabled(1,2)=true;
[beam,~]=chasi_v3_source_policy(data,1,p);
assert(norm(beam.policyCov(:))>0 && isequaln(beam.C,off.C));
cfg=struct('rank',1,'budget',2,'outer_iterations',2, ...
    'admm_iterations',40,'cg_iterations',30, ...
    'branch','matrix_pf_statistical','pf_floor',.01, ...
    'users',K,'defer_true_evaluation',true);
plain=chasi_matrix_wmmse(off,cfg,[]);
protected=chasi_matrix_wmmse(beam,cfg,[]);
beamDifference=norm(plain.precoder{1}(:)-protected.precoder{1}(:));
assert(beamDifference>1e-8, ...
    'Beam protection altered only metadata, not the WA decision');
p.enabled(:)=false;p.enabled(4,3)=true;
[power,~]=chasi_v3_source_policy(data,1,p);
assert(min(power.powerWattPerTrp)<2);
riskOff={zeros(K,L)};riskOn={.8*ones(K,L)};
opts=struct('iterations',4,'step',.1,'powerPrice',0);
baseline=chasi_v3_link_power(off,plain.precoder, ...
    2*ones(L,1),riskOff,opts);
limited=chasi_v3_link_power(power,plain.precoder, ...
    min(power.powerWattPerTrp)*ones(L,1),riskOn,opts);
powerDifference=sum(baseline.actualTrpPowerW)- ...
    sum(limited.actualTrpPowerW);
assert(powerDifference>1e-8 && ...
    all(limited.actualTrpPowerW<=min(power.powerWattPerTrp)+1e-6), ...
    'Power protection altered only metadata, not transmitted power');
report=struct('serviceChanged',true, ...
    'waBeamDifferenceFro',beamDifference, ...
    'actualAirPowerDifferenceW',powerDifference, ...
    'physicalCUnchanged',isequaln(beam.C,off.C), ...
    'additionalPolicyCovSeparate',norm(beam.policyCov(:))>0);
end
