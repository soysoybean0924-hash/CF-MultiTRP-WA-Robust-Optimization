function report=validate_trp_sharing_wmmse_small(outPath)
%VALIDATE_TRP_SHARING_WMMSE_SMALL One complete U/W/V outer update comparison.
stream=RandStream('mt19937ar','Seed',2281);
G=2; L=2; K=2; Nr=2; Nt=2; streams=1;
resources=repmat(struct('H',[],'C',[],'servingMask',[], ...
    'resourceWeightNu',.5),1,G);
initial=cell(1,G);
for g=1:G
    resources(g).H=cn(stream,K,L,Nr,Nt);
    resources(g).C=complex(zeros(K,L,Nr,Nr));
    for k=1:K
        for l=1:L
            resources(g).C(k,l,:,:)=reshape(.02*eye(Nr),1,1,Nr,Nr);
        end
    end
    resources(g).servingMask=true(L,K);
    initial{g}=.1*cn(stream,L,K,Nt,streams);
end
cfg=struct('branch','matrix_sum','rank',streams,'budget',1, ...
    'outer_iterations',1,'admm_iterations',500, ...
    'cg_iterations',100,'eps_abs',1e-7,'eps_rel',1e-6, ...
    'rho',1,'capture_first_step',true);
central=chasi_matrix_wmmse(resources,cfg,initial);
sharing=chasi_matrix_wmmse_sharing(resources,cfg,initial);
gap=sharing.optimization_objective-central.optimization_objective;
assert(central.max_power_violation<1e-8 && ...
    sharing.max_power_violation<1e-8);
assert(sharing.trajectory(end).previous_admm_converged);
assert(abs(gap)<1e-3, ...
    'Full small WMMSE outer update differs from centralized reference');
report=struct('seed',2281,'centralObjective', ...
    central.optimization_objective, ...
    'sharingObjective',sharing.optimization_objective, ...
    'objectiveDifference',gap, ...
    'centralReason',central.reason,'sharingReason',sharing.reason, ...
    'centralInnerCount',central.last_admm_history(end).inner, ...
    'sharingInnerCount',sharing.last_admm_history(end).inner, ...
    'centralMaxPowerViolation',central.max_power_violation, ...
    'sharingMaxPowerViolation',sharing.max_power_violation, ...
    'sharingVUpdate',sharing.v_update, ...
    'scope','tiny single outer step, not full formal WA convergence');
save(outPath,'report','-v7');
fprintf('SHARING_WMMSE_SMALL gap=%.7g centralInner=%d sharingInner=%d\n', ...
    gap,report.centralInnerCount,report.sharingInnerCount);
end

function x=cn(stream,varargin)
x=(randn(stream,varargin{:})+1i*randn(stream,varargin{:}))/sqrt(2);
end
