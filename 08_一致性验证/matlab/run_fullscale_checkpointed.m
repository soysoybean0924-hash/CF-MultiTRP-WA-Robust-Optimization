function run_fullscale_checkpointed(branch, maxSteps)
% Continue a full 17-group, 210-UE frozen-input WA branch with checkpoints.
% A step is one outer WMMSE update. The inner ADMM/CG tolerances are unchanged.
if nargin<1, branch='matrix_pf_statistical'; end
if nargin<2, maxSteps=200; end
assert(ismember(branch,{'ideal_pf','matrix_pf_nominal','matrix_pf_statistical'}));
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(root); startup();
inputRoot=fullfile(root,'03_研究场景构造','inputs','structured_main_v1');
s=chasi_load_frozen_binary(inputRoot);
resources=s.resources; c=s.config;
assert(numel(resources)==17 && s.manifest.srsSenderCount==210);
out=fullfile(root,'07_实验结果与进展','local_runs','fullscale_checkpointed',branch);
if ~isfolder(out), mkdir(out); end
checkpoint=fullfile(out,'latest.mat');
if isfile(checkpoint)
    old=load(checkpoint,'precoder','step','history');
    precoder=old.precoder; step=old.step; history=old.history;
else
    precoder={resources.initial}; step=0; history=struct([]);
end
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp,'outer_iterations',1,...
    'outer_rel_tol',c.outerObjectiveRelativeTolerance,...
    'outer_precoder_tol',c.outerCovarianceRelativeTolerance,...
    'admm_iterations',c.admmIterations,'cg_iterations',c.cgIterations,...
    'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance,...
    'pf_floor',c.pfFloor,'users',210,'rho',.05,'branch',branch);
while step<maxSteps
    started=tic;
    sol=chasi_matrix_wmmse(resources,cfg,precoder);
    next=sol.precoder;
    step=step+1;
    admm=sol.last_admm_history(end);
    change=sqrt(sum(cellfun(@(a,b)sum(abs(a(:)-b(:)).^2),next,precoder)))/...
        max(1,sqrt(sum(cellfun(@(a)sum(abs(a(:)).^2),precoder))));
    rel=inf;
    if ~isempty(history)
        rel=abs(sol.optimization_objective-history(end).objective)/...
            max(1,abs(history(end).objective));
    end
    converged=admm.primal<=admm.eps_primal && ...
        admm.dual<=admm.eps_dual && ...
        admm.cg_relative<=max(1e-3,10*cfg.eps_rel);
    row=struct('step',step,'objective',sol.optimization_objective,...
        'relative_objective_change',rel,'precoder_change',change,...
        'admm_converged',converged,'admm_iterations',admm.inner,...
        'admm_primal',admm.primal,'admm_dual',admm.dual,...
        'admm_eps_primal',admm.eps_primal,'admm_eps_dual',admm.eps_dual,...
        'cg_relative',admm.cg_relative,'r5_se',sol.true_rate5,...
        'mean_se',mean(sol.true_per_ue_rate),'power_w',sum(sol.power),...
        'elapsed_s',toc(started));
    history=[history,row]; %#ok<AGROW>
    precoder=next;
    tmp=[checkpoint '.partial'];
    save(tmp,'precoder','step','history','-v7.3');
    movefile(tmp,checkpoint,'f');
    fid=fopen(fullfile(out,'progress.json'),'w');
    fwrite(fid,jsonencode(struct('classification','fullscale_checkpointed',...
        'input_manifest_sha256',s.input_manifest_sha256,...
        'scene_seed',c.sceneSeed,'measurement_seed',c.measurementSeed,...
        'initial_seed',c.initialSeed,'branch',branch,'history',history),...
        PrettyPrint=true)); fclose(fid);
    fprintf('%s outer=%d obj=%.6g r5=%.6g ADMM=%d/%d CG=%.3g time=%.1fs\n',...
        branch,step,row.objective,row.r5_se,admm.inner,c.admmIterations,...
        row.cg_relative,row.elapsed_s);
    if rel<=cfg.outer_rel_tol && change<=cfg.outer_precoder_tol && converged
        fprintf('CONVERGED\n'); return
    end
    if ismember(sol.reason,{'inexact_precoder_step_no_proxy_improvement',...
            'optimization_objective_decrease'})
        fprintf('STALLED_%s\n',upper(sol.reason)); return
    end
end
fprintf('MAX_STEPS_UNCONVERGED\n');
end
