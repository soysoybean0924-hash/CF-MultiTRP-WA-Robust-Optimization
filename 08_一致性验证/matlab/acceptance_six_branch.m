function acceptance_six_branch(root,outDir)
% Six one-group branches, two outer updates each; no formal experiment.
assert(~isfolder(outDir));mkdir(outDir);
s=chasi_load_frozen_binary(fullfile(root,'03_研究场景构造','inputs','structured_main_v1'),1);
r=s.resources(1);c=s.config;
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp,'outer_iterations',2, ...
 'outer_rel_tol',c.outerObjectiveRelativeTolerance, ...
 'outer_precoder_tol',c.outerCovarianceRelativeTolerance, ...
 'admm_iterations',15,'cg_iterations',10, ...
 'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
 'pf_floor',c.pfFloor,'users',21*c.usersPerCell);
names={'ideal','matrix_nominal','matrix_statistical','ideal_pf', ...
 'matrix_pf_nominal','matrix_pf_statistical'};
for j=1:numel(names)
 cfg.branch=names{j};sol=chasi_matrix_wmmse(r,cfg,{r.initial});v=sol.precoder{1};
 row=struct('branch',names{j},'input_manifest_sha256',s.input_manifest_sha256, ...
  'outer_cap',2,'admm_cap',15,'cg_cap',10,'reason',sol.reason, ...
  'objective',sol.optimization_objective, ...
  'true_weighted_sum_se',sum(sol.true_per_ue_rate), ...
  'max_power_w',max(sol.power),'trajectory',{sol.trajectory});
 fid=fopen(fullfile(outDir,[names{j} '.json']),'wt');assert(fid>=0);
 fprintf(fid,'%s',jsonencode(row,PrettyPrint=true));fclose(fid);
 fid=fopen(fullfile(outDir,[names{j} '.real.bin']),'wb');assert(fid>=0);
 fwrite(fid,real(v),'double');fclose(fid);
 fid=fopen(fullfile(outDir,[names{j} '.imag.bin']),'wb');assert(fid>=0);
 fwrite(fid,imag(v),'double');fclose(fid);
 fprintf('%s %s %.12g\n',names{j},sol.reason,row.true_weighted_sum_se);
end
end
