function [Hhat,Ce,crossCe,detail]=chasi_static_measurement_chain( ...
    Htrue,Rrx,csiNoiseVariance,Nc,pilotId,pilotEnergy, ...
    srsNoiseVariance,srsRows,Np)
%CHASI_STATIC_MEASUREMENT_CHAIN Explicit static Gaussian adaptation.
% A hypothetical calibrated four-row CSI-RS observation conditions the
% prior; an orthogonal-port or reused-port SRS observation then updates it.
% The caller owns all physical noise, pilot, port, and seed choices.
[M,C,Yc]=chasi_csi_rs_gaussian_prior( ...
    Htrue,Rrx,csiNoiseVariance,Nc);
[Hhat,Ce,crossCe,Ys]=chasi_pilot_lmmse_static( ...
    Htrue,C,pilotId,pilotEnergy,srsNoiseVariance,srsRows,Np,M);
detail=struct('model','static Gaussian CSI-RS plus SRS pilot LMMSE', ...
    'csiPriorMean',M,'csiPriorCov',C,'csiObservation',Yc, ...
    'srsObservation',Ys);
end
