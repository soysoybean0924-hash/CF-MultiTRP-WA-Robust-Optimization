function [resources,allTrue,events]=chasi_v5_online_measurement(data,resources,allTrue,tti,stream)
% One causal 1-ms step: true evolution -> SRS -> CSI-RS -> decision posterior.
% stream.State is owned/checkpointed by caller. All UEs transmit SRS.
assert(ismember(data.modelId,{'srs_csi_joint_v5','srs_csi_joint_v6_formal'}));
G=numel(resources);U=size(data.pilotId,1);L=size(data.priorRx,4);
Nr=size(data.priorRx,1);Nt=size(resources(1).H,4);
if ~isfield(resources,'error_diagnostic')
    [resources.error_diagnostic]=deal([]);
end
c=data.config;a=besselj(0,2*pi*(c.speedKmh/3.6)* ...
    (c.frequencyGhz*1e9)/299792458*(c.ttiMs/1000));
generatedTrace=isfield(data,'channelSource') && ...
    strcmp(data.channelSource,'generated_parameters');
if generatedTrace
 if ~isfield(resources,'priorMeanCurrent')
  [resources.priorMeanCurrent]=deal([]);
  [resources.priorRxCurrent]=deal([]);
  [resources.temporal_diagnostic]=deal([]);
 end
end
if ~isfield(resources,'sourceCross')
 for g=1:G
  resources(g).sourceCross=complex(zeros(size(resources(g).C),'single'));
 end
end
events=struct('tti',tti,'srsGroup',0,'csiRs',false, ...
    'waTrigger',false,'srsObservationY',[], ...
    'srsTruthAllUe',[], ...
    'srsPriorCrossFro',[],'srsPilotId',[], ...
    'srsPriorCrossBlocks',[], ...
    'srsPriorModelId','','srsReceiverContract','', ...
    'srsPriorSeed',[],'srsPriorSampleCount',[], ...
    'srsPriorPsdProjectionFro',[], ...
    'srsPosteriorPsdProjectionFro',[], ...
    'srsPriorBuildWallSeconds',[], ...
    'srsPilotReuseGroup',{{}}, ...
    'csiObservationByGroup',{{}},'posteriorByGroup',{{}}, ...
    'measurementPath','');
for g=1:G
 r=resources(g);ids=double(r.ueIds(:));
 if isfield(data,'channelTracePath') && ~isempty(data.channelTracePath)
  r.H_true=chasi_v6_channel_trace(data.channelTracePath, ...
      data.channelTraceScene,g,tti,ids);
  allTrue{g}=[];
 else
  for u=1:U,for l=1:L
   R=data.priorRx(:,:,u,l);
   old=reshape(double(allTrue{g}(u,l,:,:)),Nr,Nt);
   z=cn(stream,Nr,Nt);
   allTrue{g}(u,l,:,:)=single(reshape(a*old+sqrt(1-a^2)* ...
       chol(R,'lower')*z,1,1,Nr,Nt));
  end,end
 end
 if isempty(data.channelTracePath)
  r.H_true=allTrue{g}(ids,:,:,:);
 end
 if generatedTrace
  statistics=chasi_v6_public_srs_prior(data.channelTraceScene, ...
      data.channelTraceInfo.meta,g,tti,tti-1,ids);
  before=struct('priorRx',statistics.previousPriorRx, ...
      'meanH',statistics.previousMeanH,'absoluteTti',tti-1, ...
      'ueIds',statistics.ueIds);
  [r.H,r.C,r.sourceCov5,r.temporal_diagnostic,r.sourceCross]= ...
      chasi_v6_temporal_posterior(r.H,r.C,r.sourceCov5, ...
          before,statistics,r.sourceCross);
  r.priorMeanCurrent=statistics.meanH;
  r.priorRxCurrent=statistics.priorRx;
 else
  r.H=single(a*double(r.H));
  for k=1:numel(ids),for l=1:L
   R=data.priorRx(:,:,ids(k),l);
   for q=1:5
    Q=a^2*reshape(double(r.sourceCov5(k,l,:,:,q)),Nr,Nr);
    if q==4,Q=Q+(1-a^2)*R;end
    r.sourceCov5(k,l,:,:,q)=single(reshape(Q,1,1,Nr,Nr,1));
   end
   r.C(k,l,:,:)=single(reshape( ...
       sum(double(r.sourceCov5(k,l,:,:,:)),5),1,1,Nr,Nr));
  end,end
 end
 resources(g)=r;
end
if mod(tti,c.hopIntervalTti)==0
    g=mod(tti/c.hopIntervalTti,c.resourceGroups)+1;
    events.srsGroup=g;
    if g<=G
        r=resources(g);ids=double(r.ueIds(:));
        if isfield(data,'channelTracePath') && ...
                ~isempty(data.channelTracePath)
            allTrue{g}=chasi_v6_channel_trace(data.channelTracePath, ...
                data.channelTraceScene,g,tti);
        end
        if ndims(data.pilotEnergy)==3
            groupEnergy=data.pilotEnergy(:,:,g);
        else
            groupEnergy=data.pilotEnergy;
        end
        z=cn(stream,Nt,L,2*c.uePilotLabels);
        measurementPrior=data.priorRx;
        measurementMean=complex(zeros(size(allTrue{g})));
        jointPrior=[];
        if isfield(data,'channelTraceInfo') && ...
                ~isempty(data.channelTraceInfo)
            measurementMean=double(data.channelTraceInfo.priorMeanH);
        end
        if generatedTrace
            srsStats=chasi_v6_public_srs_prior( ...
                data.channelTraceScene,data.channelTraceInfo.meta,g,tti);
            measurementPrior=srsStats.priorRx;
            measurementMean=double(srsStats.meanH);
            jointPrior=srsStats.jointPrior;
        end
        snap=srs_overlap_snapshot(double(allTrue{g}),measurementPrior, ...
            data.pilotId,groupEnergy,data.pilotNoiseVariance, ...
            z,0,c.ageCoherenceMs,double(allTrue{g}), ...
            c.ulPortToDlRowsOneBased(:)',r.srs_rb_count, ...
            c.speedKmh,c.frequencyGhz,measurementMean,jointPrior);
        events.srsObservationY=single(snap.Y);
        events.srsTruthAllUe=single(allTrue{g});
        r.H=single(snap.H_hat(ids,:,:,:));
        r.C=single(permute(snap.C(:,:,ids,:),[3,4,1,2]));
        r.srs_diagnostic.pilotGram=snap.gram;
        r.srs_diagnostic.receivedY=single(snap.Y);
        r.srs_diagnostic.receivedTargetPower= ...
            snap.receivedTargetPower(ids,:);
        r.srs_diagnostic.receivedInterferencePower= ...
            snap.receivedInterferencePower(ids,:);
        r.srs_diagnostic.receivedNoisePower= ...
            snap.receivedNoisePower(ids,:);
        r.srs_diagnostic.receivedPresinr= ...
            snap.receivedPresinr(ids,:);
        r.srs_diagnostic.a=1;r.srs_diagnostic.measurementTti=tti;
        if generatedTrace
            r.srs_diagnostic.informationSet=srsStats.informationSet;
            r.srs_diagnostic.priorModelId=srsStats.modelId;
            r.srs_diagnostic.priorCovarianceScope= ...
                srsStats.covarianceScope;
            r.srs_diagnostic.priorSeed=srsStats.priorSeed;
            r.srs_diagnostic.priorSampleCount=srsStats.sampleCount;
            r.srs_diagnostic.receiverContract= ...
                srsStats.receiverContract;
            r.srs_diagnostic.priorPsdProjectionFro= ...
                srsStats.priorPsdProjectionFro;
            r.srs_diagnostic.priorValidationPassed=false;
            r.srs_diagnostic.priorFailureReason= ...
                data.channelTraceInfo.meta.failureReason;
            r.srs_diagnostic.priorCrossFro=snap.priorCrossFro;
            r.srs_diagnostic.priorCrossBlocks= ...
                chasi_v6_srs_prior_blocks(jointPrior,ids,Nr);
            r.srs_diagnostic.observationCovariance= ...
                snap.observationCovariance;
            r.srs_diagnostic.posteriorPsdProjectionFro= ...
                snap.posteriorPsdProjectionFro;
            r.srs_diagnostic.pilotReuseGroup=snap.pilotReuseGroup;
            events.srsPriorCrossFro=snap.priorCrossFro;
            events.srsPriorCrossBlocks= ...
                r.srs_diagnostic.priorCrossBlocks;
            events.srsPilotId=data.pilotId;
            events.srsPilotReuseGroup=snap.pilotReuseGroup;
            events.srsPriorModelId=srsStats.modelId;
            events.srsReceiverContract=srsStats.receiverContract;
            events.srsPriorSeed=srsStats.priorSeed;
            events.srsPriorSampleCount=srsStats.sampleCount;
            events.srsPriorPsdProjectionFro= ...
                srsStats.priorPsdProjectionFro;
            events.srsPosteriorPsdProjectionFro= ...
                snap.posteriorPsdProjectionFro;
            events.srsPriorBuildWallSeconds= ...
                srsStats.buildWallSeconds;
        end
        r.age_ms=0;
        % Reconstruct the five independent terms from this SRS observation.
        prior=struct('modelId','srs_overlap_jakes_v3','resources',r, ...
            'pilotId',data.pilotId,'pilotEnergy',groupEnergy, ...
            'priorRx',measurementPrior, ...
            'pilotNoiseVariance',data.pilotNoiseVariance);
        if generatedTrace,prior.jointPrior=jointPrior;end
        s=srs_overlap_source_statistics(prior,1);
        r.sourceCov5=single(cat(5,s.covariance, ...
            zeros(numel(ids),L,Nr,Nr,1)));
        r.sourceCross=single(s.crossSourceCovariance);
        resources(g)=r;events.waTrigger=true;
    end
end
if mod(tti,c.csiRsPeriodTti)==0
    events.csiRs=true;events.waTrigger=true;
    csiObservations=cell(1,G);
    for g=1:G
        r=resources(g);ids=double(r.ueIds(:));
        lastCsiY=complex(zeros(numel(ids),L,Nr,Nt,'single'));
        for k=1:numel(ids),for l=1:L
            P=reshape(double(r.C(k,l,:,:)),Nr,Nr);
            R=data.priorRx(:,:,ids(k),l);
            obsVar=real(trace(R))/Nr/10^(c.csiRsSnrDb/10);
            if isfield(data,'csiRsObservationVarianceByUeTrp') && ...
                    ~isempty(data.csiRsObservationVarianceByUeTrp)
                obsVar=data.csiRsObservationVarianceByUeTrp(ids(k),l);
            end
            J=P/(P+obsVar*eye(Nr));F=eye(Nr)-J;
            y=reshape(double(r.H_true(k,l,:,:)),Nr,Nt)+ ...
                sqrt(obsVar)*cn(stream,Nr,Nt);
            lastCsiY(k,l,:,:)=single(reshape(y,1,1,Nr,Nt));
            mu=reshape(double(r.H(k,l,:,:)),Nr,Nt);
            r.H(k,l,:,:)=single(reshape(mu+J*(y-mu),1,1,Nr,Nt));
            for q=1:5
                Q=reshape(double(r.sourceCov5(k,l,:,:,q)),Nr,Nr);
                r.sourceCov5(k,l,:,:,q)=single(reshape(F*Q*F',1,1,Nr,Nr,1));
            end
            cross=reshape(double(r.sourceCross(k,l,:,:)),Nr,Nr);
            r.sourceCross(k,l,:,:)=single(reshape(F*cross*F',1,1,Nr,Nr));
            Q=reshape(double(r.sourceCov5(k,l,:,:,5)),Nr,Nr)+J*(obsVar*eye(Nr))*J';
            r.sourceCov5(k,l,:,:,5)=single(reshape(Q,1,1,Nr,Nr,1));
            r.C(k,l,:,:)=single(reshape( ...
                sum(double(r.sourceCov5(k,l,:,:,:)),5)+ ...
                double(r.sourceCross(k,l,:,:)),1,1,Nr,Nr));
        end,end
        r.csi_diagnostic.lastCsiTti=tti;
        r.csi_diagnostic.lastObservation=lastCsiY;
        csiObservations{g}=lastCsiY;
        resources(g)=r;
    end
    events.csiObservationByGroup=csiObservations;
end
for g=1:G
 r=resources(g);
 r.age_ms=(tti-r.srs_diagnostic.measurementTti)*c.ttiMs;
 if isfield(r,'csi_diagnostic') && ...
         isfinite(r.csi_diagnostic.lastCsiTti)
     r.csi_diagnostic.csiAgeMs= ...
         (tti-r.csi_diagnostic.lastCsiTti)*c.ttiMs;
 end
 r.sourceCov=single(cat(5,r.sourceCov5(:,:,:,:,1:2), ...
     sum(double(r.sourceCov5(:,:,:,:,[3 5])),5), ...
     r.sourceCov5(:,:,:,:,4)));
 % WA's statistical branch reads C_stat; keep it identical to the
 % decision-time physical posterior after every age/SRS/CSI update.
 r.C_stat=r.C;
 if events.waTrigger
  sourceTrace=zeros(numel(r.ueIds),L,5);
  totalTrace=zeros(numel(r.ueIds),L);
  maxMismatch=0;
  for k=1:numel(r.ueIds),for l=1:L
   physical=reshape(double(r.C(k,l,:,:)),Nr,Nr);
   reconstructed=reshape(sum(double(r.sourceCov5(k,l,:,:,:)),5),Nr,Nr)+ ...
       reshape(double(r.sourceCross(k,l,:,:)),Nr,Nr);
   maxMismatch=max(maxMismatch,norm(physical-reconstructed,'fro')/ ...
       max(norm(physical,'fro'),eps));
   totalTrace(k,l)=real(trace(physical));
   for q=1:5
    sourceTrace(k,l,q)=real(trace(reshape( ...
        double(r.sourceCov5(k,l,:,:,q)),Nr,Nr)));
   end
  end,end
  assert(maxMismatch<1e-5, ...
      'Decision-time physical C and five-source split disagree');
  centerHz=NaN;channelUnit='project_normalized';
  if isfield(data,'channelTraceInfo') && ...
          ~isempty(data.channelTraceInfo)
   centerHz=data.channelTraceInfo.meta.groupCenterOffsetHz(g);
   channelUnit=data.channelTraceInfo.meta.channelUnit;
  end
  events.posteriorByGroup{g}=struct('group',g, ...
      'absoluteTti',tti,'groupCenterOffsetHz',centerHz, ...
      'channelUnit',channelUnit, ...
      'ueIds',double(r.ueIds(:)),'estimateH',r.H, ...
      'validationTruthH',r.H_true, ...
      'physicalC',r.C,'sourceCov5',r.sourceCov5, ...
      'sourceCrossCovariance',r.sourceCross, ...
      'informationSet',conditionalField(r.srs_diagnostic, ...
          'informationSet'), ...
      'priorModelId',conditionalField(r.srs_diagnostic, ...
          'priorModelId'), ...
      'priorCovarianceScope',conditionalField( ...
          r.srs_diagnostic,'priorCovarianceScope'), ...
      'priorSeed',conditionalField(r.srs_diagnostic,'priorSeed'), ...
      'priorSampleCount',conditionalField(r.srs_diagnostic, ...
          'priorSampleCount'), ...
      'priorValidationPassed',conditionalField( ...
          r.srs_diagnostic,'priorValidationPassed'), ...
      'priorFailureReason',conditionalField( ...
          r.srs_diagnostic,'priorFailureReason'), ...
      'conditionalMean',conditionalField(r,'priorMeanCurrent'), ...
      'diffusePriorRx',conditionalField(r,'priorRxCurrent'), ...
      'temporalProjection',conditionalField(r,'temporal_diagnostic'), ...
      'physicalCTrace',totalTrace,'sourceTrace',sourceTrace, ...
      'maxSourceMismatch',maxMismatch,'srsAgeMs',r.age_ms, ...
      'crossSourceAssumption', ...
      'target-pollution signed cross stored separately', ...
      'csiAgeMs',r.csi_diagnostic.csiAgeMs, ...
      'srsMeasurementTti',r.srs_diagnostic.measurementTti, ...
      'csiMeasurementTti',r.csi_diagnostic.lastCsiTti);
 end
 if events.waTrigger
  realized=zeros(size(r.C),'single');
  for k=1:numel(r.ueIds),for l=1:L
   e=reshape(double(r.H_true(k,l,:,:))- ...
       double(r.H(k,l,:,:)),Nr,Nt);
   realized(k,l,:,:)=single(reshape(e*e'/Nt,1,1,Nr,Nr));
  end,end
  r.error_diagnostic=struct( ...
      'realizedErrorOuterByTxAverage',realized, ...
      'definition','(Htrue-Hhat)*(Htrue-Hhat)''/Nt; diagnostic only, never policy input', ...
      'expectedConditionalCovariance',r.C);
 end
 resources(g)=r;
end
end

function z=cn(stream,varargin)
z=(randn(stream,varargin{:})+1i*randn(stream,varargin{:}))/sqrt(2);
end
function value=conditionalField(resource,name)
value=[];
if isfield(resource,name),value=resource.(name);end
end
