function out=chasi_v6_channel_trace(path,scene,group,tti,ueIds)
% Immutable, independently generated TR 38.901 network-trace contract.
% H is a top-level -v7.3 variable [UE,TRP,RX,TX,group,absolute TTI+1].
% meta and priorRx are top-level variables, so matfile can slice H.
assert(isfile(path),'TR 38.901 channel trace MAT is missing');
cfg=scene.config;
expectedScenario='UMi';
if startsWith(cfg.channelMode,'uma'),expectedScenario='UMa';end
m=matfile(path);meta=m.meta;
generated=isfield(meta,'traceKind') && ...
    strcmp(meta.traceKind,'generated_parameters');
required={'modelId','scenario','carrierHz','scsHz','ttiMs', ...
    'arrayShape','ueArrayShape','trpXY','ueXY','generatorId', ...
    'generationSeed','priorSeed','validationSeed', ...
    'spatialConsistency','polarizedRayCoupling', ...
    'posteriorTemporalModel','temporalPosteriorMatched', ...
    'rayPriorAssumption','priorPosteriorMatched', ...
    'crossUeResidualMatched', ...
    'lspCrossCorrelation','rayDelaysAndAngles','validationPassed', ...
    'errorModelValidationPassed','exportComplete','channelUnit', ...
    'channelNormalizationNoiseW', ...
    'matchedSrsNoiseVariance','csiRsNoiseVarianceByUeTrp', ...
    'absoluteTtiOrigin','groupCenterOffsetHz'};
required=[required,{'srsEstimatorSha256', ...
    'sourceAttributionSha256','onlineUpdaterSha256'}];
for j=1:numel(required)
 assert(isfield(meta,required{j}), ...
     ['Missing channel trace metadata: ' required{j}]);
end
if generated
 assert(isnumeric(meta.generationSeed) && ...
     isscalar(meta.generationSeed) && isfinite(meta.generationSeed) && ...
     meta.generationSeed>=0 && ...
     isfield(meta,'priorEnsembleSamples') && ...
     meta.priorEnsembleSamples>=2 && ...
     isfinite(meta.priorSeed) && meta.priorSeed>=0 && ...
     isfield(meta,'ueVelocityMps') && ...
     isequal(size(meta.ueVelocityMps),[cfg.users,3]) && ...
     all(isfinite(meta.ueVelocityMps(:))) && ...
     isfield(meta,'receiverInformationSet') && ...
     isfield(meta,'pathlossInputKind') && ...
     strcmp(meta.pathlossInputKind, ...
         'public_expected_los_nlos_pathloss_db'));
else
 assert(all(arrayfun(@(x)isnumeric(x)&&isscalar(x)&&isfinite(x), ...
     [meta.generationSeed meta.priorSeed meta.validationSeed])) && ...
     all([meta.generationSeed meta.priorSeed meta.validationSeed]>=0));
end
assert(all(cellfun(@(v)isscalar(v) && ...
    (islogical(v) || isnumeric(v)), ...
    {meta.spatialConsistency,meta.polarizedRayCoupling, ...
    meta.temporalPosteriorMatched,meta.priorPosteriorMatched, ...
    meta.crossUeResidualMatched, ...
    meta.lspCrossCorrelation,meta.rayDelaysAndAngles, ...
    meta.validationPassed,meta.errorModelValidationPassed, ...
    meta.exportComplete})));
assert(strcmp(meta.modelId,'TR38901_network_v17_1') && ...
    (ischar(meta.posteriorTemporalModel) || ...
     isstring(meta.posteriorTemporalModel)) && ...
    strcmp(meta.scenario,expectedScenario) && ...
    meta.carrierHz==cfg.frequencyGhz*1e9 && ...
    meta.scsHz==cfg.scsHz && meta.ttiMs==cfg.ttiMs && ...
    isequal(meta.arrayShape,[4 8 2]) && ...
    isequal(meta.ueArrayShape,[1 2 2]) && ...
    isequal(size(meta.trpXY),[cfg.trps,2]) && ...
    isequal(size(meta.ueXY),[cfg.users,2]) && ...
    max(abs(meta.trpXY-scene.trp_xy),[],'all')<1e-8 && ...
    max(abs(meta.ueXY-scene.ue_xy),[],'all')<1e-8 && ...
    (generated || meta.spatialConsistency) && meta.polarizedRayCoupling && ...
    meta.lspCrossCorrelation && meta.rayDelaysAndAngles && ...
    meta.absoluteTtiOrigin==0 && ...
    isequal(size(meta.groupCenterOffsetHz),[1,cfg.srsHops]) && ...
    all(isfinite(meta.groupCenterOffsetHz)) && ...
    strcmp(meta.channelUnit,'noise_normalized_channel') && ...
    abs(meta.channelNormalizationNoiseW- ...
        cfg.noiseWattPerRb*cfg.rbTotal)<1e-12* ...
        max(1,cfg.noiseWattPerRb*cfg.rbTotal) && ...
    isscalar(meta.matchedSrsNoiseVariance) && ...
    isfinite(meta.matchedSrsNoiseVariance) && ...
    meta.matchedSrsNoiseVariance>0 && ...
    isequal(size(meta.csiRsNoiseVarianceByUeTrp), ...
        [cfg.users,cfg.trps]) && ...
    all(isfinite(meta.csiRsNoiseVarianceByUeTrp(:)) & ...
        meta.csiRsNoiseVarianceByUeTrp(:)>0) && ...
    (generated || meta.validationPassed) && meta.exportComplete && ...
    (generated || numel(unique([meta.generationSeed meta.priorSeed ...
        meta.validationSeed]))==3), ...
    'Trace is not an independently validated matching network channel');
counts=[cfg.rbGroups.count];starts=[cfg.rbGroups.start];
expectedHz=(starts+(counts-1)/2-(cfg.rbTotal+1)/2)*12*cfg.scsHz;
assert(max(abs(meta.groupCenterOffsetHz-expectedHz))<1e-6, ...
    'Trace resource-group frequency centers differ from frozen scene');
if generated
 assert(isfield(meta,'losTransitionMode') && ...
     strcmp(meta.losTransitionMode,'hard_7_6_3_3') && ...
     isfield(meta,'phaseIntegrationStepMeters') && ...
     meta.phaseIntegrationStepMeters==.25, ...
     'Generated LOS transition or phase coordinate contract changed');
 assert(isfield(meta,'logicalHShape') && ...
     isequal(meta.logicalHShape,[cfg.users cfg.trps ...
         cfg.ueRxPorts cfg.txPorts cfg.srsHops ...
         cfg.decisionTti+1001]), ...
     'Generated trace logical dimensions or time extent differ');
 assert(isequal(size(m,'links'),[cfg.users cfg.trps]), ...
     'Generated trace link parameter dimensions differ from scene');
 assert(isequal(size(m,'siteFields'),[1 cfg.trps/3]) && ...
     isequal(size(m,'dropDraw'),[cfg.users cfg.trps/3 2]), ...
     'Generated joint spatial field dimensions differ from scene');
else
 sz=size(m,'H');
 assert(numel(sz)==6 && ...
     isequal(sz(1:5),[cfg.users cfg.trps ...
     cfg.ueRxPorts cfg.txPorts cfg.srsHops]) && ...
     sz(6)>=cfg.decisionTti+1001, ...
     'Trace H must cover every formal port, group and absolute TTI');
end
if nargin<3
 assert(strcmp(meta.srsEstimatorSha256, ...
         chasi_sha256_file(which('srs_overlap_snapshot'))) && ...
     strcmp(meta.sourceAttributionSha256, ...
         chasi_sha256_file(which('srs_overlap_source_statistics'))) && ...
     strcmp(meta.onlineUpdaterSha256, ...
         chasi_sha256_file(which('chasi_v5_online_measurement'))), ...
     'Trace posterior validation source identity mismatch');
 priorRx=m.priorRx;priorMeanH=m.priorMeanH;
 pathlossDb=m.pathlossDb;
 assert(isequal(size(priorRx),[cfg.ueRxPorts ...
     cfg.ueRxPorts cfg.users cfg.trps]) && ...
     isequal(size(priorMeanH),[cfg.users cfg.trps ...
         cfg.ueRxPorts cfg.txPorts]) && ...
     isequal(size(pathlossDb),[cfg.users cfg.trps]) && ...
     all(isfinite(pathlossDb(:)) & pathlossDb(:)>0) && ...
     all(isfinite(real(priorRx(:))) & ...
         isfinite(imag(priorRx(:)))) && ...
     all(isfinite(real(priorMeanH(:))) & ...
         isfinite(imag(priorMeanH(:)))), ...
     'Trace prior/pathloss dimensions or units invalid');
 assert(all(isfinite(real(priorRx(:))) & ...
     isfinite(imag(priorRx(:)))));
 out=struct('meta',meta,'priorRx',priorRx, ...
     'priorMeanH',priorMeanH, ...
     'pathlossDb',pathlossDb,'fileSha256',chasi_sha256_file(path), ...
     'formalChannelEligible',logical(meta.spatialConsistency && ...
         meta.validationPassed && meta.errorModelValidationPassed && ...
         meta.temporalPosteriorMatched && meta.priorPosteriorMatched && ...
         meta.crossUeResidualMatched));
 return
end
assert(group>=1 && group<=cfg.srsHops && ...
    tti>=0 && tti<=cfg.decisionTti+1000 && ...
    tti==fix(tti));
if nargin<5,ueIds=1:cfg.users;end
ueIds=double(ueIds(:));
assert(all(ueIds>=1 & ueIds<=cfg.users & ueIds==fix(ueIds)) && ...
    numel(unique(ueIds))==numel(ueIds));
if generated
 out=complex(zeros(numel(ueIds),cfg.trps,cfg.ueRxPorts,cfg.txPorts,'single'));
 persistent cachedPath cachedSize cachedDate cachedFields
 file=dir(path);
 if isempty(cachedPath) || ~strcmp(cachedPath,path)
  cachedFields=m.siteFields;
  cachedPath=path;cachedSize=file.bytes;cachedDate=file.datenum;
 else
  assert(file.bytes==cachedSize && file.datenum==cachedDate, ...
      'Frozen generated trace changed during on-demand reconstruction');
 end
 fields=cachedFields;
 for k=1:numel(ueIds)
  u=ueIds(k);
  linkRow=m.links(u,:);
  frozen=m.dropDraw(u,:,:);
  for l=1:cfg.trps
   link=linkRow(l);
   site=ceil(l/3);
   drop=reshape(frozen(1,site,:),1,2);
   [ray,rx,tx]=chasi_v6_tr38901_rebuild_link( ...
       link,fields{site},drop,meta,scene.trp_xy(l,:),tti);
   h=chasi_v6_tr38901_ray_response(ray,rx,tx, ...
       meta.carrierHz,meta.groupCenterOffsetHz(group),0);
   out(k,l,:,:)=single(reshape(h,1,1,cfg.ueRxPorts,cfg.txPorts));
  end
 end
else
 assert(tti+1<=sz(6));
 out=single(m.H(ueIds,:,:,:,group,tti+1));
end
assert(isequal(size(out),[numel(ueIds) cfg.trps ...
    cfg.ueRxPorts cfg.txPorts]) && ...
    all(isfinite(real(out(:))) & isfinite(imag(out(:)))));
end
