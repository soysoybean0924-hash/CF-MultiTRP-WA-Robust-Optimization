function info=chasi_v6_generate_parameter_trace(scene,seed,path)
% Deterministic, on-demand UMi/UMa ray-parameter trace. No dense H tensor.
% Scoped outdoor 7.6.3 spatial fields; independent validation remains gated.
cfg=scene.config;assert(~isfile(path) && seed>=0 && seed==fix(seed));
% Reject legacy fixed-name remnants before expensive trace construction.
legacyPartial=[path '.partial'];
assert(~isfile(legacyPartial), ...
    'Incomplete legacy trace exists: %s. Quarantine it before retry.', ...
    legacyPartial);
assert(~ismember(seed,17113091+10000*(1:16)), ...
    'Receiver ensemble seed must differ from truth seed');
assert(ismember(cfg.channelMode,{'umi_pathloss_subset','uma_pathloss_subset'}));
if startsWith(cfg.channelMode,'umi'),scenario='UMi';hbs=10;
else,scenario='UMa';hbs=25;end
U=cfg.users;L=cfg.trps;fc=cfg.frequencyGhz;
template=struct('ray',[],'rx',[],'tx',[], ...
    'referenceDistanceMeters',[],'bearingRad',[],'ueId',[]);
links=repmat(template,U,L);pathlossDb=zeros(U,L);
priorRx=complex(zeros(4,4,U,L));
priorMeanH=complex(zeros(U,L,cfg.ueRxPorts,cfg.txPorts,'single'));
noiseW=cfg.noiseWattPerRb*cfg.rbTotal;
assert(noiseW>0 && seed+1000000*U+L<=double(intmax('uint32')), ...
    'Generated channel seeds exceed MT19937 supported range');
sites=L/3;assert(sites==fix(sites));
for site=1:sites
 sectors=3*site-2:3*site;
 assert(max(abs(double(scene.trp_xy(sectors,:))- ...
     double(scene.trp_xy(sectors(1),:))),[],'all')<1e-8, ...
     'Three co-sited sectors must share one BS location');
end
siteFields=cell(1,sites);dropDraw=cell(U,sites,2);
publicVelocity=zeros(U,3);
losState=false(U,sites);
for site=1:sites
 siteFields{site}=chasi_v6_tr38901_site_field( ...
     'create',seed,scenario,site,fc);
 for u=1:U
  xy=double(scene.ue_xy(u,:));
  losState(u,site)=chasi_v6_tr38901_site_field( ...
      'los',siteFields{site},xy,scene.trp_xy(3*site-2,:));
  for condition=0:1
   dropDraw{u,site,condition+1}=chasi_v6_tr38901_site_field( ...
       'evaluate',siteFields{site},xy,logical(condition));
   initial=dropDraw{u,site,condition+1};
   trp=double(scene.trp_xy(3*site-2,:));
   distance=max(10,norm(xy-trp));
   p=chasi_v6_tr38901_lsp_table( ...
       scenario,logical(condition),fc,distance);
   localStream=RandStream('mt19937ar','Seed', ...
       seed+1000000*u+site);
   sample=chasi_v6_tr38901_lsp(p,localStream,initial.lspNormal);
   initialCluster=chasi_v6_tr38901_clusters( ...
       p,sample,localStream,initial.ssp);
   strongest=initialCluster.strongestClusterIndices;
   initial.ssp.fixedStrongestOriginalIndices= ...
       initialCluster.keptOriginalIndices(strongest);
   dropDraw{u,site,condition+1}=initial;
  end
 end
end
jointLspMismatch=0;
for site=1:sites,for condition=1:2
 jointLspMismatch=max(jointLspMismatch, ...
     siteFields{site}.condition{condition}.lspJoint.crossCorrelationMismatch);
end,end
for u=1:U
 % A straight 3 km/h trajectory with a seed-fixed global direction.
 directionStream=RandStream('mt19937ar','Seed',cfg.seed+100000+u);
 heading=2*pi*rand(directionStream);
 velocity=(cfg.speedKmh/3.6)*[cos(heading) sin(heading) 0];
 publicVelocity(u,:)=velocity;
 for l=1:L
  site=ceil(l/3);linkSeed=seed+1000000*u+site;
  stream=RandStream('mt19937ar','Seed',linkSeed);
  trp=double(scene.trp_xy(l,:));ue=double(scene.ue_xy(u,:));
  d2=max(10,norm(ue-trp));d3=hypot(d2,hbs-1.5);
  isLos=losState(u,site);
  draw=dropDraw{u,site,double(isLos)+1};
  p=chasi_v6_tr38901_lsp_table(scenario,logical(isLos),fc,d2);
  sample=chasi_v6_tr38901_lsp(p,stream, ...
      draw.lspNormal);
  pl=chasi_v6_tr38901_outdoor_pathloss( ...
      scenario,isLos,fc,d2,d3,hbs)-sample.sfDb;
  cluster=chasi_v6_tr38901_clusters(p,sample,stream, ...
      draw.ssp);
  bearing=mod(l-1,3)*2*pi/3;
  [ray,rx,tx]=chasi_v6_tr38901_rays(p,sample,cluster,stream, ...
      trp,ue,velocity,bearing,fc*1e9,draw.ray);
  ray.initialXY=ue;
  ray.power=ray.power*10^(-pl/10)/noiseW;
  storedTx=struct('positionMeters',tx.positionMeters);
  links(u,l)=struct('ray',ray,'rx',rx,'tx',storedTx, ...
      'referenceDistanceMeters',d3,'bearingRad',bearing, ...
      'ueId',u);
  pathlossDb(u,l)=pl;
  [Q,meanH]=chasi_v6_tr38901_ray_prior( ...
      ray,rx,tx,fc*1e9);
  priorRx(:,:,u,l)=Q;
  priorMeanH(u,l,:,:)=single(reshape(meanH,1,1, ...
      cfg.ueRxPorts,cfg.txPorts));
 end
end
for u=1:U,for site=1:sites
 sectors=3*site-2:3*site;
 reference=links(u,sectors(1)).ray;
 assert(isequaln(reference,links(u,sectors(2)).ray) && ...
     isequaln(reference,links(u,sectors(3)).ray), ...
     'Co-sited sectors must share Steps 1-9 random channel parameters');
end,end
counts=[cfg.rbGroups.count];starts=[cfg.rbGroups.start];
meta=struct('modelId','TR38901_network_v17_1', ...
    'traceKind','generated_parameters','scenario',scenario, ...
    'scope','outdoor UMi/UMa LOS/NLOS; no O2I, oxygen absorption or blockage', ...
    'motionModel',['seeded straight UE motion and frozen 2-D fields;' ...
        'Procedure B 5-7 candidate'], ...
    'losTransitionMode','hard_7_6_3_3', ...
    'phaseIntegrationStepMeters',.25, ...
    'carrierHz',fc*1e9,'scsHz',cfg.scsHz,'ttiMs',cfg.ttiMs, ...
    'arrayShape',[4 8 2],'ueArrayShape',[1 2 2], ...
    'trpXY',scene.trp_xy,'ueXY',scene.ue_xy, ...
    'generatorId','chasi_v6_generate_parameter_trace', ...
    'generationSeed',seed,'priorSeed',17113091, ...
    'mobilitySeed',cfg.seed+100000, ...
    'priorEnsembleSamples',16,'ueVelocityMps',publicVelocity, ...
    'validationSeed',NaN,'spatialConsistency',false, ...
    'jointLspMaximumCorrelationMismatch',jointLspMismatch, ...
    'posteriorTemporalModel', ...
        'independent_ensemble_cross_covariance_gaussian_projection', ...
    'phaseCrossModel', ...
        'finite_Hermite_spectrum_of_Gaussian_copula_uniform_phase', ...
    'phaseCrossQuadratureNodes',48,'phaseCrossHermiteOrder',24, ...
    'temporalPosteriorMatched',false, ...
    'rayPriorAssumption', ...
        'public_geometry_independent_seed_finite_ensemble_moments', ...
    'priorPosteriorMatched',false, ...
    'crossUeResidualMatched',false, ...
    'polarizedRayCoupling',true,'lspCrossCorrelation',true, ...
    'rayDelaysAndAngles',true,'validationPassed',false, ...
    'errorModelValidationPassed',false,'exportComplete',true, ...
    'channelUnit','noise_normalized_channel', ...
    'channelNormalizationNoiseW',noiseW, ...
    'matchedSrsNoiseVariance',NaN, ...
    'csiRsNoiseVarianceByUeTrp',nan(U,L), ...
    'absoluteTtiOrigin',0, ...
    'logicalHShape',[U L cfg.ueRxPorts cfg.txPorts ...
        cfg.srsHops cfg.decisionTti+1001], ...
    'groupCenterOffsetHz',(starts+(counts-1)/2-(cfg.rbTotal+1)/2)*12*cfg.scsHz, ...
    'srsEstimatorSha256',chasi_sha256_file(which('srs_overlap_snapshot')), ...
    'sourceAttributionSha256',chasi_sha256_file(which('srs_overlap_source_statistics')), ...
    'onlineUpdaterSha256',chasi_sha256_file(which('chasi_v5_online_measurement')), ...
    'generatorSha256',chasi_sha256_file([mfilename('fullpath') '.m']), ...
    'failureReason',['projected_joint_LSP_cross_space_correlation;' ...
        'finite_ensemble_joint_UE_rx_prior_tx_averaging_and_' ...
        'Gaussian_posterior_statistical_validation_pending']);
names={'chasi_v6_tr38901_lsp_table','chasi_v6_tr38901_lsp', ...
    'chasi_v6_tr38901_spectral_field', ...
    'chasi_v6_tr38901_lsp_field', ...
    'chasi_v6_tr38901_site_field', ...
    'chasi_v6_tr38901_outdoor_pathloss', ...
    'chasi_v6_tr38901_rebuild_link', ...
    'chasi_v6_tr38901_phase_cross_kernel', ...
    'chasi_v6_channel_statistics','chasi_v6_temporal_posterior', ...
    'chasi_v6_public_srs_prior', ...
    'chasi_v6_srs_prior_blocks', ...
    'chasi_v6_tr38901_clusters','chasi_v6_tr38901_rays', ...
    'chasi_v6_tr38901_ray_response','chasi_v6_tr38901_ray_prior', ...
    'chasi_tr38901_array_panel'};
meta.componentNames=names;
meta.componentSha256=cellfun(@(name)chasi_sha256_file(which(name)), ...
    names,'UniformOutput',false);
% Pilot-noise definitions use the receiver's independent public prior,
% never the saved hidden channel realization or its conditional ray power.
public=chasi_v6_public_srs_prior(scene,meta,1,0);
truthPathlossDb=pathlossDb;
pathlossDb=zeros(U,L);
priorRx=public.priorRx;
priorMeanH=public.meanH;
publicHome=zeros(U,1);
for u=1:U
 for l=1:L
  d2=max(10,norm(double(scene.ue_xy(u,:))- ...
      double(scene.trp_xy(l,:))));
  d3=hypot(d2,hbs-1.5);
  if strcmp(scenario,'UMi'),losScale=36;else,losScale=63;end
  pLos=min(1,18/d2+(1-18/d2)*exp(-d2/losScale));
  losDb=chasi_v6_tr38901_outdoor_pathloss( ...
      scenario,true,fc,d2,d3,hbs);
  nlosDb=chasi_v6_tr38901_outdoor_pathloss( ...
      scenario,false,fc,d2,d3,hbs);
  pathlossDb(u,l)=pLos*losDb+(1-pLos)*nlosDb;
  scale=real(trace(public.priorRx(:,:,u,l)))/cfg.ueRxPorts;
  meta.csiRsNoiseVarianceByUeTrp(u,l)= ...
      scale/10^(cfg.csiRsSnrDb/10);
 end
 publicHome(u)=real(trace(public.priorRx(:,:,u,scene.home(u))))/ ...
     cfg.ueRxPorts;
end
meta.matchedSrsNoiseVariance=median(publicHome)/ ...
    10^(cfg.pilotSnrDb/10);
meta.pilotNoisePriorModelId=public.modelId;
meta.receiverInformationSet=public.informationSet;
meta.pathlossInputKind='public_expected_los_nlos_pathloss_db';
folder=fileparts(path);if ~isfolder(folder),mkdir(folder);end
% A unique same-folder staging file avoids collisions after interrupted saves.
partial=[tempname(folder) '.mat.partial'];
assert(~isfile(partial) && ~isfile(path));
save(partial,'meta','links','siteFields','dropDraw', ...
    'priorRx','priorMeanH','pathlossDb', ...
    'truthPathlossDb','-v7.3');
contents=whos('-file',partial);
required={'meta','links','siteFields','dropDraw', ...
    'priorRx','priorMeanH','pathlossDb','truthPathlossDb'};
assert(all(ismember(required,{contents.name})), ...
    'Staged channel trace is incomplete: %s',partial);
assert(~isfile(path) && movefile(partial,path), ...
    'Could not publish staged channel trace: %s',partial);
info=struct('path',path,'sha256',chasi_sha256_file(path), ...
    'traceKind',meta.traceKind,'formalChannelEligible',false);
end
