function out=chasi_srs_ul_power_control(pathlossDb,srsRbByGroup,cfg,pilotMatchedEnergy)
% TS 38.213 7.3.1 open-loop SRS power equation with configured inputs.
% PL is simulated UMi/UMa large-scale pathloss to the home TRP.
% P0, alpha and P_CMAX are scenario assumptions; the closed-loop state is
% fixed at zero. RF effects and full TR 38.901 are outside this model.
pl=double(pathlossDb(:));rb=double(srsRbByGroup(:)');
required={'mode','p0Dbm','pCmaxDbm','mu', ...
    'closedLoopAdjustmentDb','referencePowerW','fractionalCompensation'};
for j=1:numel(required),assert(isfield(cfg,required{j}),required{j});end
assert(strcmp(cfg.mode,'ts38213_open_loop_simulated_pathloss') && ...
    all(isfinite(pl) & pl>0) && all(rb>=1 & rb==fix(rb)) && ...
    isfinite(cfg.p0Dbm) && isfinite(cfg.pCmaxDbm) && ...
    cfg.mu>=0 && cfg.mu==fix(cfg.mu) && ...
    cfg.fractionalCompensation>=0 && cfg.fractionalCompensation<=1 && ...
    cfg.referencePowerW>0 && pilotMatchedEnergy>0 && ...
    cfg.closedLoopAdjustmentDb==0);
unclippedDbm=cfg.p0Dbm+10*log10(2^cfg.mu*rb)+ ...
    cfg.fractionalCompensation*pl+cfg.closedLoopAdjustmentDb;
powerDbm=min(cfg.pCmaxDbm,unclippedDbm);
powerW=10.^((powerDbm-30)/10);
relativeEnergy=powerW/cfg.referencePowerW;
pilotEnergy=pilotMatchedEnergy*repmat(reshape(relativeEnergy, ...
    numel(pl),1,numel(rb)),1,2,1);
out=struct('mode',cfg.mode,'powerWByUeGroup',powerW, ...
    'powerWPerPortByUeGroup',powerW/2, ...
    'powerDbmByUeGroup',powerDbm, ...
    'unclippedPowerDbmByUeGroup',unclippedDbm, ...
    'relativePilotEnergyByUeGroup',relativeEnergy, ...
    'pilotEnergy',pilotEnergy,'pathlossDbByUe',pl, ...
    'srsRbByGroup',rb,'clippedHigh',unclippedDbm>cfg.pCmaxDbm, ...
    'scope','TS 38.213 open-loop total UE power split equally over two SRS ports; referencePowerW is total UE power and pilotMatchedEnergy is per-port reference energy; simulated UMi/UMa home pathloss, no dynamic TPC or RF calibration');
end
