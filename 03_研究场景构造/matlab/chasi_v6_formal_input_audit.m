function audit=chasi_v6_formal_input_audit(d)
% Audit requested versus generated values; no claim of TR 38.901 fidelity.
c=d.config;s=d.sceneConfig;G=numel(d.resources);
requested=struct('sites',7,'sectorsPerSite',3,'trps',21, ...
    'usersPerCell',10,'users',210,'siteSpacingM',300, ...
    'txPorts',64,'ueTxPorts',2,'ueRxPorts',4, ...
    'speedKmh',3,'frequencyGhz',3.5,'bandwidthHz',100e6, ...
    'scsHz',30000,'rank',2,'resourceGroups',17,'prbTotal',273, ...
    'prbFraction',.5,'srsHopTti',20,'srsRevisitTti',340, ...
    'csiRsPeriodTti',40,'protocolTti',1000, ...
    'trafficBusyFraction',.3, ...
    'srsUlPowerMode','ts38213_open_loop_simulated_pathloss', ...
    'channelMode','umi_pathloss_subset');
traceActive=isfield(d,'channelTracePath') && ...
    ~isempty(d.channelTracePath);
if traceActive,requested.channelMode='tr38901_network_trace';end
actual=struct('sites',s.sites,'sectorsPerSite',s.sectorsPerSite, ...
    'trps',s.trps,'usersPerCell',c.usersPerCell,'users',s.users, ...
    'siteSpacingM',s.siteSpacingM,'txPorts',size(d.resources(1).H,4), ...
    'ueTxPorts',s.ueTxPorts,'ueRxPorts',size(d.priorRx,1), ...
    'speedKmh',c.speedKmh,'frequencyGhz',c.frequencyGhz, ...
    'bandwidthHz',s.bandwidthHz,'scsHz',s.scsHz, ...
    'rank',c.rank,'resourceGroups',G,'prbTotal',s.rbTotal, ...
    'prbFraction',mean(d.prbSchedule.usedRbByTti)/s.rbTotal, ...
    'srsHopTti',c.hopIntervalTti,'srsRevisitTti',c.revisitTti, ...
    'csiRsPeriodTti',c.csiRsPeriodTti, ...
    'protocolTti',size(d.prbSchedule.allocatedRbByGroupTti,2), ...
    'trafficBusyFraction',d.formalTraffic.actualPlannedBusyFraction, ...
    'srsUlPowerMode',d.ulPowerControl.mode, ...
    'channelMode',c.channelMode);
rb=double([d.resources.srs_rb_count]);
actual.srsRbByGroup=rb;
actual.prbFractionByTrp=mean(d.prbEffectiveByTrp,2);
actual.prbByTti=d.prbSchedule.usedRbByTti;
actual.trafficTailTtiFraction=d.formalTraffic.actualTailTtiFraction;
actual.trafficTailPayloadFraction=d.formalTraffic.actualTailPayloadFraction;
actual.payloadBitsPerPlannedBusyTti= ...
    d.formalTraffic.payloadBitsPerPlannedBusyTti;
actual.sduCount=d.formalTraffic.sduCount;
actual.offeredPayloadBits=d.formalTraffic.offeredPayloadBits;
actual.trafficBusyFractionDeviation= ...
    actual.trafficBusyFraction-requested.trafficBusyFraction;
actual.srsUlPowerMinW=min(d.ulPowerControl.powerWByUeGroup,[],'all');
actual.srsUlPowerMaxW=max(d.ulPowerControl.powerWByUeGroup,[],'all');
actual.srsUlPowerByUeGroupW=d.ulPowerControl.powerWByUeGroup;
actual.srsUlPathlossDbByUe=d.ulPowerControl.pathlossDbByUe;
actual.srsPilotEnergyByUePortGroup=d.pilotEnergy;
assert(numel(d.txArrayPanel)==s.trps && ...
    all(cellfun(@(p)isequal(size(p.positionWavelength),[3,64]) && ...
    numel(p.polarizationSlantRad)==64,d.txArrayPanel)));
actual.txPanelPositionWavelength=d.txArrayPanel{1}.positionWavelength;
actual.txPolarizationSlantRad=d.txArrayPanel{1}.polarizationSlantRad;
measuredPresinr=[];
for g=1:G
    measuredPresinr=[measuredPresinr; ...
        d.resources(g).srs_diagnostic.receivedPresinr(:)]; %#ok<AGROW>
end
actual.initialMeasuredPresinrDb=10*log10(max(measuredPresinr,realmin));
names=fieldnames(requested);mismatch={};
for j=1:numel(names)
 f=names{j};if strcmp(f,'trafficBusyFraction'),continue;end
 if ~isequaln(requested.(f),actual.(f)),mismatch{end+1}=f;end %#ok<AGROW>
end
% Analytic reference quality at each SRS comb, before finite-sequence
% Gram leakage; this is a prior expectation, not realized Presinr.
U=size(d.pilotId,1);L=size(d.priorRx,4);P=size(d.pilotId,2);
referenceSinr=zeros(U,L,P,G);signal=referenceSinr;interference=signal;
for group=1:G
 if ndims(d.pilotEnergy)==3,groupEnergy=d.pilotEnergy(:,:,group);
 else,groupEnergy=d.pilotEnergy;end
for port=1:P
 for u=1:U
  peers=find(d.pilotId(:,port)==d.pilotId(u,port));
  for l=1:L
   target=real(trace(d.priorRx(:,:,u,l)))/size(d.priorRx,1)* ...
       groupEnergy(u,port);
   if isfield(d,'channelTraceInfo') && ~isempty(d.channelTraceInfo)
    meanH=reshape(double(d.channelTraceInfo.priorMeanH(u,l,:,:)), ...
        size(d.priorRx,1),[]);
    target=target+sum(abs(meanH).^2,'all')/numel(meanH)* ...
        groupEnergy(u,port);
   end
   interf=0;
   for j=peers(:)'
    if j~=u
     interf=interf+real(trace(d.priorRx(:,:,j,l)))/ ...
         size(d.priorRx,1)*groupEnergy(j,port);
     if isfield(d,'channelTraceInfo') && ~isempty(d.channelTraceInfo)
      peerMean=reshape(double(d.channelTraceInfo.priorMeanH(j,l,:,:)), ...
          size(d.priorRx,1),[]);
      interf=interf+sum(abs(peerMean).^2,'all')/numel(peerMean)* ...
          groupEnergy(j,port);
     end
    end
   end
   signal(u,l,port,group)=target;
   interference(u,l,port,group)=interf;
   referenceSinr(u,l,port,group)= ...
       target/(interf+d.pilotNoiseVariance);
  end
 end
end
end
sourceError=0;
for g=1:G
 r=d.resources(g);[K,LL,Nr,~,~]=size(r.sourceCov5);
 for k=1:K,for l=1:LL
  C=reshape(double(r.C(k,l,:,:)),Nr,Nr);
  total=reshape(sum(double(r.sourceCov5(k,l,:,:,:)),5),Nr,Nr);
  sourceError=max(sourceError,norm(C-total,'fro')/max(norm(C,'fro'),eps));
 end,end
end
audit=struct('requested',requested,'actual',actual, ...
    'mismatch',{mismatch},'sourceFiveToPhysicalRelativeMax',sourceError, ...
    'configuredMatchedPilotSnrDb',c.pilotSnrDb, ...
    'referenceReceivedSinrDb',10*log10(max(referenceSinr,realmin)), ...
    'referenceReceivedSignal',signal, ...
    'referenceCopilotInterference',interference, ...
    'referenceSinrDefinition', ...
    'prior received target/(same-label prior interference+matched noise); includes configured open-loop SRS power, excludes finite Gram', ...
    'channelScope',c.channelMode, ...
    'channelComponents',struct( ...
        'sevenSiteThreeSectorGeometry',true, ...
        'umiUmaPathlossSubset',ismember(c.channelMode, ...
            {'umi_pathloss_subset','uma_pathloss_subset'}), ...
        'umiUmaLosShadowSubset',ismember(c.channelMode, ...
            {'umi_pathloss_subset','uma_pathloss_subset'}), ...
        'tr38901ElementPowerPattern',true, ...
        'eightByFourDualPolarizedPanelGeometry',true, ...
        'tr38901DelayAngleClusters',traceActive && ...
            d.channelTraceInfo.meta.rayDelaysAndAngles, ...
        'tr38901SpatialConsistency',traceActive && ...
            d.channelTraceInfo.meta.spatialConsistency, ...
        'temporalPosteriorMatched',traceActive && ...
            d.channelTraceInfo.meta.temporalPosteriorMatched, ...
        'rayPriorPosteriorMatched',traceActive && ...
            d.channelTraceInfo.meta.priorPosteriorMatched, ...
        'crossUeResidualMatched',traceActive && ...
            d.channelTraceInfo.meta.crossUeResidualMatched, ...
        'eightByFourDualPolarizedArrayResponse',traceActive && ...
            d.channelTraceInfo.meta.polarizedRayCoupling, ...
        'fullTr38901',traceActive && ...
            d.channelTraceInfo.meta.validationPassed && ...
            d.channelTraceInfo.meta.spatialConsistency && ...
            d.formalChannelEligible, ...
        'errorPosteriorIndependentlyValidated',traceActive && ...
            d.channelTraceInfo.meta.errorModelValidationPassed), ...
    'rankScope','fixed Rank 2 as selected formal scenario', ...
    'receiverScope','normalized covariance IRC diagnostic, not full NR receiver', ...
    'physicalCrossTerms','conditionally zero only under the declared independent linear Gaussian innovations; independent full-scale empirical calibration pending');
assert(sourceError<1e-5);
assert(all(actual.prbFractionByTrp==.5));
end
