function out=chasi_v6_public_srs_prior(scene,meta,group,tti,previousTti,ueIds)
% Receiver-side moments from an independent ensemble of the frozen model.
% Only public geometry/trajectory, channel law, and a distinct prior seed
% enter this function. No saved links, site fields, H_true, or generator
% realization are read. Each sample shares one field across co-sited TRPs.
if nargin<5,previousTti=[];end
buildClock=tic;
cfg=scene.config;
if nargin<6,ueIds=1:cfg.users;end
ueIds=double(ueIds(:));U=numel(ueIds);
assert(all(ueIds>=1 & ueIds<=cfg.users & ueIds==fix(ueIds)) && ...
    numel(unique(ueIds))==U);
L=cfg.trps;Nr=cfg.ueRxPorts;
Nt=cfg.txPorts;S=double(meta.priorEnsembleSamples);
jointBytes=16*double(U*Nr)^2*double(L);
assert(jointBytes<=512*1024^2, ...
    'Receiver joint prior exceeds the bounded in-memory block budget');
assert(group>=1 && group<=cfg.srsHops && tti>=0 && tti==fix(tti) && ...
    S>=2 && S==fix(S) && isfinite(meta.priorSeed) && ...
    isequal(size(meta.ueVelocityMps),[cfg.users,3]));
if ~isempty(previousTti)
 assert(previousTti>=0 && previousTti<tti && previousTti==fix(previousTti));
end
assert(meta.priorSeed+10000*S+1000000*cfg.users+L<= ...
    double(intmax('uint32')));
now=complex(zeros(U,L,Nr,Nt,S,'single'));
if ~isempty(previousTti)
 before=complex(zeros(U,L,Nr,Nt,S,'single'));
end
for sample=1:S
 seed=double(meta.priorSeed)+10000*sample;
 sampleMeta=struct('scenario',meta.scenario, ...
     'carrierHz',meta.carrierHz,'ttiMs',meta.ttiMs, ...
     'channelNormalizationNoiseW',meta.channelNormalizationNoiseW, ...
     'generationSeed',seed);
 for site=1:L/3
  field=chasi_v6_tr38901_site_field('create',seed, ...
      char(meta.scenario),site,double(meta.carrierHz)/1e9);
  sectors=3*site-2:3*site;
  trp=double(scene.trp_xy(sectors(1),:));
  for u=1:U
   actualUe=ueIds(u);
   xy=double(scene.ue_xy(actualUe,:));drop=cell(1,2);
   for condition=0:1
    draw=chasi_v6_tr38901_site_field('evaluate',field,xy, ...
        logical(condition));
    distance=max(10,norm(xy-trp));
    p=chasi_v6_tr38901_lsp_table(char(meta.scenario), ...
        logical(condition),double(meta.carrierHz)/1e9,distance);
    stream=RandStream('mt19937ar','Seed',seed+1000000*actualUe+site);
    lsp=chasi_v6_tr38901_lsp(p,stream,draw.lspNormal);
    clusters=chasi_v6_tr38901_clusters(p,lsp,stream,draw.ssp);
    strongest=clusters.strongestClusterIndices;
    draw.ssp.fixedStrongestOriginalIndices= ...
        clusters.keptOriginalIndices(strongest);
    drop{condition+1}=draw;
   end
   for l=sectors
    link=struct('ray',struct('initialXY',xy, ...
        'velocityMps',double(meta.ueVelocityMps(actualUe,:))), ...
        'bearingRad',mod(l-1,3)*2*pi/3,'ueId',actualUe);
    [ray,rx,tx]=chasi_v6_tr38901_rebuild_link( ...
        link,field,drop,sampleMeta,scene.trp_xy(l,:),tti);
    h=chasi_v6_tr38901_ray_response(ray,rx,tx, ...
        meta.carrierHz,meta.groupCenterOffsetHz(group),0);
    now(u,l,:,:,sample)=single(reshape(h,1,1,Nr,Nt,1));
    if ~isempty(previousTti)
     [oldRay,oldRx,oldTx]=chasi_v6_tr38901_rebuild_link( ...
         link,field,drop,sampleMeta,scene.trp_xy(l,:),previousTti);
     old=chasi_v6_tr38901_ray_response(oldRay,oldRx,oldTx, ...
         meta.carrierHz,meta.groupCenterOffsetHz(group),0);
     before(u,l,:,:,sample)=single(reshape(old,1,1,Nr,Nt,1));
    end
   end
  end
 end
end
R=complex(zeros(Nr,Nr,U,L));joint=complex(zeros(U*Nr,U*Nr,L));
meanH=complex(zeros(U,L,Nr,Nt,'single'));
cross=complex(zeros(Nr,Nr,U,L));
previousR=complex(zeros(Nr,Nr,U,L));
previousMean=complex(zeros(U,L,Nr,Nt,'single'));
for l=1:L
 sampleMatrix=complex(zeros(U*Nr,Nt,S));
 for sample=1:S,for u=1:U
  ix=(u-1)*Nr+(1:Nr);
  sampleMatrix(ix,:,sample)=reshape(double(now(u,l,:,:,sample)),Nr,Nt);
 end,end
 meanMatrix=mean(sampleMatrix,3);
 centered=sampleMatrix-meanMatrix;
 factor=reshape(centered,U*Nr,Nt*S)/sqrt(Nt*(S-1));
 Q=factor*factor';Q=(Q+Q')/2;
 joint(:,:,l)=Q;
 for u=1:U
  ix=(u-1)*Nr+(1:Nr);
  R(:,:,u,l)=Q(ix,ix);
  meanH(u,l,:,:)=single(reshape(meanMatrix(ix,:),1,1,Nr,Nt));
 end
 if ~isempty(previousTti)
  for u=1:U
   current=reshape(double(now(u,l,:,:,:)),Nr,Nt,S);
   old=reshape(double(before(u,l,:,:,:)),Nr,Nt,S);
   newAverage=mean(current,3);oldAverage=mean(old,3);
   previousMean(u,l,:,:)=single(reshape(oldAverage,1,1,Nr,Nt));
   current=reshape(current-newAverage,Nr,Nt*S);
   old=reshape(old-oldAverage,Nr,Nt*S);
   previousR(:,:,u,l)=old*old'/(Nt*(S-1));
   cross(:,:,u,l)=current*old'/(Nt*(S-1));
  end
 end
end
out=struct('priorRx',R,'meanH',meanH,'jointPrior',joint, ...
    'crossRx',cross,'previousPriorRx',previousR, ...
    'previousMeanH',previousMean,'group',group,'absoluteTti',tti, ...
    'previousTti',previousTti,'ueIds',ueIds, ...
    'crossEpochMatched',nan(U,L), ...
    'conditionTransitionCount',nan(U,L), ...
    'previousConditionTransitionCount',nan(U,L), ...
    'informationSet',struct('trpXY',scene.trp_xy, ...
        'ueInitialXY',scene.ue_xy, ...
        'ueVelocityMps',meta.ueVelocityMps, ...
        'carrierHz',meta.carrierHz,'group',group, ...
        'absoluteTti',tti,'pilotAssignment', ...
            'supplied by SRS estimator, not by prior sampler', ...
        'measurements', ...
            'past and current SRS/CSI observations enter posterior separately', ...
        'excluded',{{'truth siteFields','truth links', ...
            'H_true','evaluation truth','truth generator seed'}}), ...
    'modelId','independent_seed_finite_ensemble_rx_joint_tx_average', ...
    'receiverContract', ...
        'per-TRP transmit-port-averaged finite-sample joint Rx Q', ...
    'covarianceScope', ...
        'E[(H-mu)*(H-mu)''/Nt] per TRP; same Rx block used for each Tx pilot column', ...
    'priorSeed',meta.priorSeed,'sampleCount',S, ...
    'priorPsdProjectionFro',0, ...
    'priorPsdConstruction','Hermitian sample Gram factor times factor conjugate transpose', ...
    'buildWallSeconds',toc(buildClock), ...
    'jointPriorBytes',jointBytes, ...
    'generatorSeedUsed',false,'trueChannelRead',false);
end
