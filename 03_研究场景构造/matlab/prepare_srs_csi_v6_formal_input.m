function info=prepare_srs_csi_v6_formal_input(root,inputPath,validationGroups,sceneSeedOverride)
% New immutable formal input. Reuse the v5 posterior generator unchanged;
% its parent input lives only under this new version's directory.
startup;
if nargin<2 || isempty(inputPath)
 inputPath=fullfile(root,'03_研究场景构造','inputs', ...
     'srs_csi_joint_v6_formal','input.mat');
end
if nargin<3,validationGroups=17;end
if nargin<4,sceneSeedOverride=[];end
assert(validationGroups>=1 && validationGroups<=17);
if isfile(inputPath)
 assert(strcmp(chasi_sha256_file(inputPath), ...
     strtrim(fileread([inputPath '.sha256']))));
 saved=load(inputPath,'data');d=saved.data;
 configPath=fullfile(root,'03_研究场景构造','config', ...
     'srs_csi_joint_v6_formal.json');
 assert(strcmp(d.modelId,'srs_csi_joint_v6_formal') && ...
     d.schemaVersion==6 && numel(d.resources)==validationGroups && ...
     strcmp(d.v6ConfigSha256,chasi_sha256_file(configPath)) && ...
     strcmp(d.v6GeneratorSha256, ...
         chasi_sha256_file([mfilename('fullpath') '.m'])), ...
     'Existing v6 input identity mismatch');
 assert(strcmp(d.srsUlPowerControlSha256, ...
     chasi_sha256_file(which('chasi_srs_ul_power_control'))), ...
     'SRS UL power-control implementation changed');
 assert(strcmp(d.errorModel.attributionSha256, ...
     chasi_sha256_file(which('srs_overlap_source_statistics'))) && ...
     strcmp(d.errorModel.snapshotSha256, ...
         chasi_sha256_file(which('srs_overlap_snapshot'))), ...
     'Frozen error-model implementation changed');
 if isfield(d,'channelTracePath') && ~isempty(d.channelTracePath)
     assert(isfile(d.channelTracePath) && ...
         strcmp(d.channelTraceSha256, ...
             chasi_sha256_file(d.channelTracePath)), ...
         'Frozen TR 38.901 trace identity changed');
     assert(strcmp(d.channelTraceLoaderSha256, ...
         chasi_sha256_file(which('chasi_v6_channel_trace'))), ...
         'TR 38.901 trace loader implementation changed');
     if strcmp(d.channelSource,'generated_parameters')
         for j=1:numel(d.channelTraceInfo.meta.componentNames)
             name=d.channelTraceInfo.meta.componentNames{j};
             if strcmp(name,'chasi_v6_tr38901_rebuild_link')
                 assert(ismember(d.channelTraceInfo.meta.componentSha256{j}, ...
                     {chasi_sha256_file(which(name)), '507e920a0a64fcce9dfbcc5f53cbb5e6e6de251febb4af7a7908ae73bbe471f0'}), ...
                     'Unrecognized trace rebuild source; do not reuse');
                 continue % Current runtime identity is checked below.
             elseif strcmp(name,'chasi_v6_srs_prior_blocks')
                 assert(ismember(d.channelTraceInfo.meta.componentSha256{j}, ...
                     {chasi_sha256_file(which(name)), '885eebaea8b459101f4aa0e3a313c513a509fddc5b663ddad1aa3efc16117251'}), ...
                     'Unrecognized SRS prior audit helper; do not reuse');
                 continue % Syntax-only audit fix does not change saved rays.
             end
             assert(strcmp(d.channelTraceInfo.meta.componentSha256{j}, ...
                 chasi_sha256_file(which(name))), ...
                 'Frozen generated-channel component changed');
         end
         assert(isfield(d,'losEventSha256') && ...
             strcmp(d.losEventSha256, ...
                 chasi_sha256_file(which('chasi_v6_los_transition_events'))), ...
             'Frozen LOS event implementation changed');
         assert(strcmp(d.channelRebuildSha256, ...
             chasi_sha256_file(which('chasi_v6_tr38901_rebuild_link'))) && ...
             strcmp(d.channelResponseSha256, ...
             chasi_sha256_file(which('chasi_v6_tr38901_ray_response'))) && ...
             strcmp(d.channelPanelSha256, ...
             chasi_sha256_file(which('chasi_tr38901_array_panel'))), ...
             'Generated channel reconstruction source changed');
     end
 end
 if ~isempty(sceneSeedOverride)
     assert(d.sceneSeed==sceneSeedOverride, ...
         'Frozen input has a different independent seed');
 end
 info=struct('inputPath',inputPath, ...
     'inputSha256',chasi_sha256_file(inputPath));return
end
parentDir=fileparts(inputPath);if ~isfolder(parentDir),mkdir(parentDir);end
generationClock=tic;
logStage(parentDir,'START',generationClock);
% Check fixed-name interrupted writes before any expensive channel build.
assert(~isfile([inputPath '.partial']), ...
    'Incomplete v6 input exists: %s. Inspect or quarantine it.', ...
    [inputPath '.partial']);
assert(~isfile([fullfile(parentDir,'generated_channel_parameters.mat') '.partial']), ...
    'Incomplete legacy channel trace exists. Inspect it before retry.');
assert(~isfile([fullfile(parentDir,'v5_parent_input.mat') '.partial']), ...
    'Incomplete parent input exists. Inspect it before retry.');
v6cfg=fullfile(root,'03_研究场景构造','config', ...
    'srs_csi_joint_v6_formal.json');
v6=jsondecode(fileread(v6cfg));
assert(strcmp(v6.modelId,'srs_csi_joint_v6_formal') && ...
    ismember(v6.channelMode,{'umi_pathloss_subset','uma_pathloss_subset'}) && ...
    ismember(v6.channelSource, ...
        {'generated_parameters','validated_external','simplified_subset'}) && ...
    v6.targetBusyFraction==.3 && ...
    v6.payloadBitsPerPlannedBusyTti>0 && ...
    v6.tailPayloadFraction>0 && v6.tailPayloadFraction<1);
v5cfg=fullfile(root,'03_研究场景构造','config',char(v6.parentConfig));
c=jsondecode(fileread(v5cfg));
if ~isempty(sceneSeedOverride)
    assert(sceneSeedOverride>=0 && ...
        sceneSeedOverride==fix(sceneSeedOverride));
    delta=sceneSeedOverride-c.sceneSeed;
    c.sceneSeed=sceneSeedOverride;
    c.measurementSeed=c.measurementSeed+1000*delta;
    c.initialSeed=c.initialSeed+1000*delta;
    assert(c.measurementSeed>=0 && c.initialSeed>=0);
end
c.channelMode=v6.channelMode;
c.srsUlPowerControl=v6.srsUlPowerControl;
if strcmp(v6.channelSource,'validated_external')
    assert(isfield(v6,'channelTracePath') && ...
        ~isempty(v6.channelTracePath) && isfile(v6.channelTracePath), ...
        'External trace source requires an existing trace MAT');
    c.channelTracePath=char(v6.channelTracePath);
elseif strcmp(v6.channelSource,'generated_parameters')
    assert(isempty(v6.channelTracePath), ...
        'Generated source cannot also select an external trace');
    c.channelTracePath=fullfile(parentDir,'generated_channel_parameters.mat');
    if isfile(c.channelTracePath)
        logStage(parentDir,'REUSE_EXISTING_TRACE',generationClock);
    else
        logStage(parentDir,'GENERATE_TRACE_START',generationClock);
    end
    cfg=chasi_config(struct('seed',c.sceneSeed, ...
            'usersPerCell',c.usersPerCell,'rank',c.rank, ...
            'powerWattPerTrp',c.powerWattPerTrp, ...
            'prbUtilization',c.prbUtilization, ...
            'scheduleMode',c.scheduleMode, ...
            'pilotSnrDb',c.pilotSnrDb, ...
            'csiRsSnrDb',c.csiRsSnrDb, ...
            'csiRsPeriodTti',c.csiRsPeriodTti, ...
            'speedKmh',c.speedKmh,'channelMode',c.channelMode, ...
            'frequencyGhz',c.frequencyGhz, ...
            'noiseWattPerRb',c.noiseWattPerRb, ...
            'serviceTrps',2,'srsMode','pilot_reuse_gaussian', ...
            'srsPilotSequences',c.uePilotLabels, ...
            'decisionTti',c.decisionTti,'durationTti',c.decisionTti, ...
            'ttiMs',c.ttiMs));
    scene=chasi_generate_scene(cfg);
    if ~isfile(c.channelTracePath)
        chasi_v6_generate_parameter_trace(scene,c.sceneSeed+600000, ...
            c.channelTracePath);
    end
    logStage(parentDir,'TRACE_AVAILABLE',generationClock);
    chasi_v6_channel_trace(c.channelTracePath,scene);
    frozen=load(c.channelTracePath,'meta');
    assert(strcmp(frozen.meta.generatorSha256, ...
        chasi_sha256_file(which('chasi_v6_generate_parameter_trace'))), ...
        'Generated trace source changed; freeze a new v6 input identity');
    for j=1:numel(frozen.meta.componentNames)
        name=frozen.meta.componentNames{j};
        if strcmp(name,'chasi_v6_tr38901_rebuild_link')
            assert(ismember(frozen.meta.componentSha256{j}, ...
                {chasi_sha256_file(which(name)), '507e920a0a64fcce9dfbcc5f53cbb5e6e6de251febb4af7a7908ae73bbe471f0'}), ...
                'Unrecognized trace rebuild source; do not reuse');
            continue % Runtime code is frozen in the new parent input.
        elseif strcmp(name,'chasi_v6_srs_prior_blocks')
            assert(ismember(frozen.meta.componentSha256{j}, ...
                {chasi_sha256_file(which(name)), '885eebaea8b459101f4aa0e3a313c513a509fddc5b663ddad1aa3efc16117251'}), ...
                'Unrecognized SRS prior audit helper; do not reuse');
            continue % Syntax-only audit fix does not change saved rays.
        end
        assert(strcmp(frozen.meta.componentSha256{j}, ...
            chasi_sha256_file(which(name))), ...
            'Generated trace component changed; freeze a new v6 identity');
    end
else
    assert(isempty(v6.channelTracePath), ...
        'Simplified source cannot select an external trace');
end
if validationGroups<17,c.validationGroups=validationGroups;end
parentCfg=fullfile(parentDir,'v5_parent_config.json');
parentInput=fullfile(parentDir,'v5_parent_input.mat');
if ~isfile(parentCfg)
 fid=fopen(parentCfg,'w');assert(fid>0);
 fwrite(fid,jsonencode(c,PrettyPrint=true),'char');fclose(fid);
else
 assert(isequaln(jsondecode(fileread(parentCfg)),c));
end
logStage(parentDir,'PARENT_INPUT_START',generationClock);
if ~isfile(parentInput)
 prepare_srs_csi_v5_input(root,parentCfg,parentInput);
end
logStage(parentDir,'PARENT_INPUT_AVAILABLE',generationClock);
assert(strcmp(chasi_sha256_file(parentInput), ...
    strtrim(fileread([parentInput '.sha256']))));
x=load(parentInput,'data');d=x.data;
assert(strcmp(d.configSha256,chasi_sha256_file(parentCfg)) && ...
    strcmp(d.sourceCodeSha256, ...
        chasi_sha256_file(which('prepare_srs_csi_v5_input'))) && ...
    strcmp(d.snapshotCodeSha256, ...
        chasi_sha256_file(which('srs_overlap_snapshot'))) && ...
    strcmp(d.sceneGeneratorSha256, ...
        chasi_sha256_file(which('chasi_generate_scene'))), ...
    'v6 parent input was generated by a different source identity');
assert(isfield(d,'channelRebuildRuntimeSha256') && ...
    strcmp(d.channelRebuildRuntimeSha256, ...
        chasi_sha256_file(which('chasi_v6_tr38901_rebuild_link'))) && ...
    isfield(d,'losEventRuntimeSha256') && ...
    strcmp(d.losEventRuntimeSha256, ...
        chasi_sha256_file(which('chasi_v6_los_transition_events'))), ...
    'Parent input predates LOS fix; preserve and quarantine before regeneration');
assert(numel(d.resources)==validationGroups);
d.parentInputSha256=chasi_sha256_file(parentInput);
d.parentModelId=d.modelId;
d.modelId='srs_csi_joint_v6_formal';d.schemaVersion=6;
d.config.modelId=d.modelId;
d.channelScope=v6.channelScope;
d.channelSource=char(v6.channelSource);
d.formalChannelEligible=false;
if ~isempty(d.channelTracePath)
    d.channelTraceSha256=d.channelTraceInfo.fileSha256;
    d.channelTraceLoaderSha256= ...
        chasi_sha256_file(which('chasi_v6_channel_trace'));
    d.channelRebuildSha256= ...
        chasi_sha256_file(which('chasi_v6_tr38901_rebuild_link'));
    d.losEventSha256=chasi_sha256_file(which('chasi_v6_los_transition_events'));
    d.channelResponseSha256= ...
        chasi_sha256_file(which('chasi_v6_tr38901_ray_response'));
    d.channelPanelSha256= ...
        chasi_sha256_file(which('chasi_tr38901_array_panel'));
    d.formalChannelEligible=d.channelTraceInfo.formalChannelEligible;
    d.config.channelMode='tr38901_network_trace';
    d.sceneConfig.channelMode='tr38901_network_trace';
    if strcmp(v6.channelSource,'generated_parameters')
        d.channelScope='generated TR 38.901 parameter trace; validation gates pending';
    else
        d.channelScope='validated independent TR 38.901 UMi/UMa network trace';
    end
else
    d.channelTraceSha256='';
    d.channelTraceLoaderSha256='';
end
d.externalDependencies=struct( ...
    'channel','TR 38.901 UMi/UMa 7.5/7.6 clusters, spatial consistency and 8-by-4 dual-polarized 64-port array implementation or validated network trace', ...
    'bler','Independent Rank-2 IRC multi-TRP SINR/MCS/TBS/transport-block BLER curve MAT matching frozen input SHA', ...
    'arvidsonOriginal','Original LTE 4-RB SRS estimator/simulator and independent EPA/ETU/AWGN trials');
d.parameterSource='v6 UMi pathloss subset, TS 38.213 open-loop SRS equation on simulated pathloss, finite pilot Gaussian posterior; not full TR 38.901';
if ~isempty(d.channelTracePath)
    if strcmp(v6.channelSource,'generated_parameters')
        d.parameterSource='deterministic generated ray parameters, analytic receive covariance and configured measurement SNR; independent channel and posterior validation pending';
    else
        d.parameterSource='independently validated TR 38.901 UMi/UMa network trace and prior, TS 38.213 SRS open-loop equation on trace pathloss, project Gaussian posterior';
    end
end
d.errorModel=struct('id',v6.errorModel, ...
    'sourceNames',{{'target_residual','pilot_pollution', ...
        'srs_observation_noise','aging_innovation', ...
        'csi_rs_observation_noise'}}, ...
    'priorRxField','data.priorRx','pilotIdField','data.pilotId', ...
    'pilotEnergyField','data.pilotEnergy', ...
    'matchedNoiseVariance',d.pilotNoiseVariance, ...
    'arvidsonEq23OriginalCalibrated',false, ...
    'temporalPosteriorMatched', ...
        ~isempty(d.channelTracePath) && ...
        d.channelTraceInfo.meta.temporalPosteriorMatched, ...
    'priorPosteriorMatched', ...
        ~isempty(d.channelTracePath) && ...
        d.channelTraceInfo.meta.priorPosteriorMatched, ...
    'crossUeResidualMatched', ...
        ~isempty(d.channelTracePath) && ...
        d.channelTraceInfo.meta.crossUeResidualMatched, ...
    'crossTermAssumption', ...
        ['zero cross covariance only for independent polarization-phase ' ...
         'innovations; cross-UE spatial-field covariance requires validation'], ...
    'snapshotSha256',d.snapshotCodeSha256, ...
    'attributionSha256',chasi_sha256_file(which('srs_overlap_source_statistics')));
if isempty(d.channelTracePath)
 assert(strcmp(d.config.channelMode,v6.channelMode) && ...
     strcmp(d.sceneConfig.channelMode,v6.channelMode));
else
 assert(strcmp(d.config.channelMode,'tr38901_network_trace') && ...
     strcmp(d.sceneConfig.channelMode,'tr38901_network_trace'));
end
d.config.trafficModel='target_busy_fraction';
d.config.trafficLoad=v6.targetBusyFraction;
d.formalTraffic=chasi_v6_formal_traffic(d.sceneConfig.users, ...
    size(d.prbSchedule.allocatedRbByGroupTti,2), ...
    d.trafficSeed,v6.targetBusyFraction, ...
    v6.payloadBitsPerPlannedBusyTti,v6.tailPayloadFraction);
d.sceneConfig.trafficModel='target_busy_fraction';
d.sceneConfig.trafficLoad=v6.targetBusyFraction;
d.v6ConfigSha256=chasi_sha256_file(v6cfg);
d.v6GeneratorSha256=chasi_sha256_file([mfilename('fullpath') '.m']);
d.srsUlPowerControlSha256= ...
    chasi_sha256_file(which('chasi_srs_ul_power_control'));
d.parentGeneratorSha256=d.sourceCodeSha256;
d.sourceCodeSha256=d.v6GeneratorSha256;
d.formalConfigAudit=chasi_v6_formal_input_audit(d);
assert(isempty(d.formalConfigAudit.mismatch), ...
    'Configured formal scene differs from generated effective scene');
data=d;tmp=[inputPath '.partial'];assert(~isfile(tmp));
save(tmp,'data','-v7.3');assert(movefile(tmp,inputPath));
hash=chasi_sha256_file(inputPath);
fid=fopen([inputPath '.sha256'],'w');assert(fid>0);
fprintf(fid,'%s\n',hash);fclose(fid);
info=struct('inputPath',inputPath,'inputSha256',hash, ...
    'audit',d.formalConfigAudit);
logStage(parentDir,'V6_INPUT_COMPLETE',generationClock);
end

function logStage(folder,stage,clockStart)
path=fullfile(folder,'input_generation.log');
fid=fopen(path,'a');assert(fid>0,'Cannot append input generation log');
fprintf(fid,'%s stage=%s elapsed_s=%.3f\n', ...
    datestr(now,31),stage,toc(clockStart));fclose(fid);
fprintf('V6_INPUT %s elapsed_s=%.3f\n',stage,toc(clockStart));
end
