function verify_v6_los_transition_boundary()
% Fast regression: five LOS-field cycles inside one legacy 0.1 m step.
field=struct('scenario','UMi','los',struct( ...
    'kx',[100*pi;zeros(63,1)],'ky',zeros(64,1), ...
    'cosWeight',[8;zeros(63,1)],'sinWeight',zeros(64,1), ...
    'features',64));
xy=[0 0];velocity=[1 0 0];trp=[100 0];elapsed=.1;
first=chasi_v6_tr38901_site_field('los',field,xy,trp);
last=chasi_v6_tr38901_site_field('los',field,xy+elapsed*velocity(1:2),trp);
assert(first==last,'Fixture must have equal endpoint LOS states');
[epoch,count]=chasi_v6_los_transition_events( ...
    field,xy,velocity,trp,elapsed);
assert(count==10 && epoch>0 && epoch<elapsed, ...
    'Even number of LOS events was missed');
left=chasi_v6_tr38901_site_field('los',field, ...
    xy+(epoch-1e-8)*velocity(1:2),trp);
right=chasi_v6_tr38901_site_field('los',field, ...
    xy+(epoch+1e-8)*velocity(1:2),trp);
assert(left~=right && right==last, ...
    'Last event does not enter the final physical LOS state');
fprintf('LOS_BOUNDARY_PASS events=%d epoch=%.12g\n',count,epoch);
end
