function H=chasi_v6_tr38901_ray_response(ray,rx,tx,carrierHz,frequencyHz,timeSeconds)
% TR 38.901 v17.1.0 7.5 steps 10-11: polarized per-ray array response.
% Inputs are already generated cluster/ray parameters, not a complete
% network channel or a spatial-consistency generator.
% ray: power [N,1] linear, delaySeconds [N,1], arrival/departure
% unit vectors [N,3], xprLinear [N,1], phasesRad [N,4], velocityMps [1,3].
% rx/tx: positionMeters [ports,3], fieldTheta/fieldPhi [ports,N].
% Output: [rxPort,txPort,frequency,time] complex channel coefficients.
assert(isfinite(carrierHz) && carrierHz>0 && ...
    isvector(frequencyHz) && all(isfinite(frequencyHz(:))) && ...
    isvector(timeSeconds) && all(isfinite(timeSeconds(:))));
c0=299792458;lambda=c0/carrierHz;
needed={'power','delaySeconds','arrivalUnit','departureUnit', ...
    'xprLinear','phasesRad','velocityMps'};
for j=1:numel(needed),assert(isfield(ray,needed{j}),needed{j});end
p=double(ray.power(:));tau=double(ray.delaySeconds(:));
xpr=double(ray.xprLinear(:));phase=double(ray.phasesRad);
N=numel(p);assert(N>0 && isequal(size(tau),[N,1]) && ...
    isequal(size(xpr),[N,1]) && isequal(size(phase),[N,4]) && ...
    isequal(size(ray.arrivalUnit),[N,3]) && ...
    isequal(size(ray.departureUnit),[N,3]) && ...
    isequal(size(ray.velocityMps),[1,3]) && ...
    all(isfinite(p) & p>=0) && all(isfinite(tau) & tau>=0) && ...
    all(xpr>0 & ~isnan(xpr)) && all(isfinite(phase(:))) && ...
    all(isfinite(ray.arrivalUnit(:))) && ...
    all(isfinite(ray.departureUnit(:))) && ...
    all(isfinite(ray.velocityMps(:))) && ...
    max(abs(sum(double(ray.arrivalUnit).^2,2)-1))<1e-8 && ...
    max(abs(sum(double(ray.departureUnit).^2,2)-1))<1e-8);
Nr=size(rx.positionMeters,1);Nt=size(tx.positionMeters,1);
assert(isequal(size(rx.positionMeters),[Nr,3]) && ...
    isequal(size(tx.positionMeters),[Nt,3]) && ...
    isequal(size(rx.fieldTheta),[Nr,N]) && ...
    isequal(size(rx.fieldPhi),[Nr,N]) && ...
    isequal(size(tx.fieldTheta),[Nt,N]) && ...
    isequal(size(tx.fieldPhi),[Nt,N]) && ...
    all(isfinite(rx.positionMeters(:))) && ...
    all(isfinite(tx.positionMeters(:))) && ...
    all(isfinite(rx.fieldTheta(:))) && all(isfinite(rx.fieldPhi(:))) && ...
    all(isfinite(tx.fieldTheta(:))) && all(isfinite(tx.fieldPhi(:))));
f=double(frequencyHz(:));t=double(timeSeconds(:));
H=complex(zeros(Nr,Nt,numel(f),numel(t)));
for n=1:N
    pol=[exp(1i*phase(n,1)),exp(1i*phase(n,2))/sqrt(xpr(n)); ...
         exp(1i*phase(n,3))/sqrt(xpr(n)),exp(1i*phase(n,4))];
    rxField=[rx.fieldTheta(:,n),rx.fieldPhi(:,n)];
    txField=[tx.fieldTheta(:,n),tx.fieldPhi(:,n)];
    rxArray=exp(1i*2*pi/lambda* ...
        (double(rx.positionMeters)*double(ray.arrivalUnit(n,:)).'));
    txArray=exp(1i*2*pi/lambda* ...
        (double(tx.positionMeters)*double(ray.departureUnit(n,:)).'));
    spatial=sqrt(p(n))*(rxField*pol*txField.').* ...
        (rxArray*txArray.');
    doppler=dot(double(ray.arrivalUnit(n,:)), ...
        double(ray.velocityMps))/lambda;
    for fi=1:numel(f)
        frequencyPhase=exp(-1i*2*pi*f(fi)*tau(n));
        for ti=1:numel(t)
            H(:,:,fi,ti)=H(:,:,fi,ti)+spatial*frequencyPhase* ...
                exp(1i*2*pi*doppler*t(ti));
        end
    end
end
end
