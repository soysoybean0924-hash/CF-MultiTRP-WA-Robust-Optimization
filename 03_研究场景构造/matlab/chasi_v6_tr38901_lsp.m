function out=chasi_v6_tr38901_lsp(p,stream,normalDraw)
% TR 38.901 7.5 Step 4, Table 7.5-6 Part 1. Order SF,K,DS,ASD,ASA,ZSD,ZSA.
% normalDraw may be supplied by the 7.6.3 spatial random-field sampler.
if nargin<3,normalDraw=randn(stream,7,1);end
assert(isequal(size(normalDraw),[7,1]) && all(isfinite(normalDraw)));
C=eye(7);
% Columns are UMi LOS, UMi NLOS, UMa LOS, UMa NLOS.
col=1+~p.isLos+2*strcmp(p.scenario,'UMa');
pair=[4 3;5 3;5 1;4 1;3 1;4 5;4 2;5 2;3 2;1 2; ...
      6 1;7 1;6 2;7 2;6 3;7 3;6 4;7 4;6 5;7 5;6 7];
value=[.5 0 .4 .4;.8 .4 .8 .6;-.4 -.4 -.5 0; ...
 -.5 0 -.5 -.6;-.4 -.7 -.4 -.4;.4 0 0 .4; ...
 -.2 0 0 0;-.3 0 -.2 0;-.7 0 -.4 0; ...
 .5 0 0 0;0 0 0 0;0 0 -.8 -.4; ...
 0 0 0 0;0 0 0 0;0 -.5 -.2 -.5; ...
 .2 0 0 0;.5 .5 .5 .5;.3 .5 0 -.1; ...
 0 0 -.3 0;0 .2 .4 0;0 0 0 0];
for j=1:size(pair,1)
 a=pair(j,1);b=pair(j,2);C(a,b)=value(j,col);C(b,a)=C(a,b);
end
if ~p.isLos,C(2,:)=0;C(:,2)=0;C(2,2)=1;end
[L,flag]=chol(C,'lower');assert(flag==0,'Table LSP correlation not PSD');
z=L*normalDraw;
out=struct('sfDb',z(1)*ternary(strcmp(p.scenario,'UMi'), ...
    ternary(p.isLos,4,7.82),ternary(p.isLos,4,6)), ...
    'kDb',NaN,'dsSeconds',10^(p.muLog(1)+p.sigmaLog(1)*z(3)), ...
    'asdDeg',min(104,10^(p.muLog(2)+p.sigmaLog(2)*z(4))), ...
    'asaDeg',min(104,10^(p.muLog(3)+p.sigmaLog(3)*z(5))), ...
    'zsdDeg',min(52,10^(p.muLog(4)+p.sigmaLog(4)*z(6))), ...
    'zsaDeg',min(52,10^(p.muLog(5)+p.sigmaLog(5)*z(7))), ...
    'standardNormal',normalDraw,'correlation',C);
if p.isLos
 if strcmp(p.scenario,'UMi'),ks=5;else,ks=3.5;end
 out.kDb=9+ks*z(2);
end
end
function v=ternary(flag,a,b)
if flag,v=a;else,v=b;end
end
