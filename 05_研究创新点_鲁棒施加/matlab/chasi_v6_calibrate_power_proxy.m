function calibration=chasi_v6_calibrate_power_proxy(checkpointPaths,summaryPaths,outPath)
% Offline, independent-seed calibration of optimistic proxy mean-loss bias.
% First N-1 completed windows fit the margin; final window is held out.
% This function is never called from an online WA decision.
assert(iscell(checkpointPaths) && iscell(summaryPaths) && ...
    numel(checkpointPaths)==numel(summaryPaths) && ...
    numel(checkpointPaths)>=3 && ~isfile(outPath));
n=numel(checkpointPaths);inputSha=cell(1,n);sceneSeeds=zeros(1,n);
proxySha='';constraintMode='';channelSource='';traceKind='';
records=struct([]);
for j=1:n
 x=load(checkpointPaths{j},'state');y=load(summaryPaths{j},'summary');
 state=x.state;summary=y.summary;
 assert(isfield(state,'experienceConstraintConfig') && ...
     isfield(state.experienceConstraintConfig,'experienceConstraint') && ...
     state.experienceConstraintConfig.experienceConstraint.enabled);
 currentMode=state.experienceConstraintConfig.experienceConstraint.modeId;
 currentProxySha=state.identity.powerProxySha256;
 if j==1,proxySha=currentProxySha;constraintMode=currentMode;end
 assert(strcmp(proxySha,currentProxySha) && ...
     strcmp(constraintMode,currentMode), ...
     'Calibration campaigns use different proxy implementations');
 assert(state.iter==1000 && summary.ttiCount==1000 && ...
     strcmp(state.identity.inputSha256,summary.inputSha256) && ...
     isequal(size(state.proxyRateMbps,3),2));
 assert(summary.formalOneSecondComplete && ...
     all(cellfun(@(z)z.linkValidated,summary.branches([1 2 6]))) && ...
     ~isempty(summary.powerAblationPair) && ...
     summary.powerAblationPair.paired, ...
     'Calibration requires paired runs and validated BLER outcomes');
 forbidden={'channel_not_full_tr38901', ...
     'channel_trace_not_full_or_independently_validated', ...
     'error_posterior_not_independently_validated', ...
     'ray_temporal_posterior_not_independently_validated', ...
     'ray_prior_gaussian_posterior_model_mismatch', ...
     'spatial_field_cross_ue_pilot_covariance_not_validated'};
 assert(~any(ismember(summary.blockingReasons,forbidden)), ...
     'Calibration requires an independently validated channel model');
 if j==1
  channelSource=summary.channelAudit.source;
  traceKind=summary.channelAudit.traceKind;
 end
 assert(strcmp(channelSource,summary.channelAudit.source) && ...
     strcmp(traceKind,summary.channelAudit.traceKind), ...
     'Calibration channel identities differ');
 inputSha{j}=summary.inputSha256;
 sceneSeeds(j)=state.identity.sceneSeed;
 assert(numel(unique(inputSha(1:j)))==j, ...
     'Power proxy calibration windows must use independent input identities');
 assert(numel(unique(sceneSeeds(1:j)))==j, ...
     'Power proxy calibration windows must use independent scene seeds');
 base=summary.branches{1}.counter;
 ideal=summary.branches{2}.counter;
 source=summary.branches{6}.counter;
 mask=base.valid & ideal.valid & source.valid;
 assert(all(mask(:)) && any(mask(:)), ...
     'Calibration needs complete common UE-second samples');
 proxyBase=mean(state.proxyRateMbps(:,:,1),2);
 proxySource=mean(state.proxyRateMbps(:,:,2),2);
 assert(isequal(size(proxyBase),size(base.rateMbps)) && ...
     isequal(size(proxySource),size(source.rateMbps)));
 b=mean(base.rateMbps(mask));m=mean(source.rateMbps(mask));
 pb=mean(proxyBase(mask));pm=mean(proxySource(mask));
 assert(all(isfinite([b,m,pb,pm])) && b>0 && pb>0);
 actualLoss=(b-m)/b;proxyLoss=(pb-pm)/pb;
 records(j)=struct('inputSha256',inputSha{j}, ...
     'checkpointSha256',chasi_sha256_file(checkpointPaths{j}), ...
     'summarySha256',chasi_sha256_file(summaryPaths{j}), ...
     'commonUeSeconds',nnz(mask), ...
     'actualAckMeanLoss',actualLoss, ...
     'estimatedProxyMeanLoss',proxyLoss, ...
     'optimisticError',actualLoss-proxyLoss); %#ok<AGROW>
end
margin=max(0,max([records(1:end-1).optimisticError]))+.02;
heldout=records(end).optimisticError;
validationPassed=isfinite(margin) && margin<.10 && ...
    heldout<=margin && abs(heldout)<=.05;
calibration=struct('proxyModelId', ...
    'causal_Hhat_physicalC_Gaussian_logdet_v1', ...
    'proxySourceSha256',proxySha, ...
    'constraintModeId',constraintMode, ...
    'channelSource',channelSource,'traceKind',traceKind, ...
    'inputSha256',{inputSha},'sceneSeeds',sceneSeeds, ...
    'records',records, ...
    'fitWindowCount',n-1,'heldoutWindowCount',1, ...
    'optimismMargin',margin,'heldoutOptimisticError',heldout, ...
    'validationPassed',validationPassed, ...
    'failureReason','');
if ~validationPassed
 calibration.failureReason= ...
     'heldout_proxy_ack_loss_mismatch_or_margin_exceeds_10_percent';
end
if ~isfolder(fileparts(outPath)),mkdir(fileparts(outPath));end
partial=[tempname(fileparts(outPath)) '.mat'];
save(partial,'calibration','-v7.3');
[ok,msg]=movefile(partial,outPath);assert(ok,msg);
end
