function manifest=run_v4_campaign(root,targetOuter)
% New v4 chain; never reads or overwrites historical v3 checkpoints.
startup;assert(targetOuter>=1);
config=fullfile(root,'03_研究场景构造','config', ...
    'srs_csi_joint_v4_prb50.json');
input=fullfile(root,'03_研究场景构造','inputs', ...
    'srs_csi_joint_v4_prb50','input.mat');
if ~isfile(input)
    prepare_srs_csi_v4_input(root,config,input);
end
x=load(input,'data');d=x.data;
assert(strcmp(d.modelId,'srs_csi_joint_v4') && d.schemaVersion==4 && ...
    d.fullScaleInput && numel(d.resources)==17 && ...
    d.prbRequested==.5 && abs(d.prbEffective-.5)<.04);
cfgRoot=fullfile(root,'05_研究创新点_鲁棒施加','config','v4_prb50');
if ~isfile(fullfile(cfgRoot,'source_all.json'))
    chasi_v3_make_policy_configs(root,cfgRoot,input,1:8);
end
names={'nominal','physical','uniform','source_all'};
outRoot=fullfile(root,'07_实验结果与进展','local_runs','srs_csi_joint_v4_prb50');
states=cell(1,numel(names));
for i=1:numel(names)
    states{i}=run_v3_policy_batch(root,input, ...
        fullfile(cfgRoot,[names{i} '.json']), ...
        fullfile(outRoot,names{i}),targetOuter,17);
end
manifest=struct('input',input,'inputSha256',chasi_sha256_file(input), ...
    'modelId',d.modelId,'prbRequested',d.prbRequested, ...
    'prbEffective',d.prbEffective,'branchNames',{names}, ...
    'branchStates',{states},'edgeStatus','unjudged_missing_acked_rlc_events', ...
    'powerStatus','unjudged_missing_acked_rlc_events', ...
    'formalProtocolComplete',false, ...
    'reason','Online one-second SRS/CSI-RS/WA and ACKed SDU event source not yet connected');
if ~isfolder(outRoot),mkdir(outRoot);end
save(fullfile(outRoot,'campaign_manifest.mat'),'manifest','-v7.3');
end
