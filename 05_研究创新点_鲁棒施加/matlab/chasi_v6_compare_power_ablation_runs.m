function paired=chasi_v6_compare_power_ablation_runs(basePath,constrainedPath)
% Freeze a source_all six-arm run against its constrained source ablation.
assert(isfile(basePath) && isfile(constrainedPath));
a=load(basePath,'state');b=load(constrainedPath,'state');
x=a.state;y=b.state;xi=x.identity;yi=y.identity;
assert(~isfield(x.experienceConstraintConfig, ...
    'experienceConstraint') && ...
    isfield(y.experienceConstraintConfig,'experienceConstraint') && ...
    y.experienceConstraintConfig.experienceConstraint.enabled);
baseConfig=x.experienceConstraintConfig;
constrainedConfig=rmfield(y.experienceConstraintConfig, ...
    'experienceConstraint');
sameSourcePolicy=isequaln(baseConfig,constrainedConfig);
sameFrozenInput=strcmp(xi.inputSha256,yi.inputSha256) && ...
    strcmp(xi.channelTraceSha256,yi.channelTraceSha256) && ...
    xi.sceneSeed==yi.sceneSeed && ...
    strcmp(xi.runnerSha256,yi.runnerSha256) && ...
    strcmp(xi.solverSha256,yi.solverSha256) && ...
    isequaln(xi.configHash(3:5),yi.configHash(3:5)) && ...
    isequaln(xi.solverOverride,yi.solverOverride) && ...
    xi.waOuter==yi.waOuter && ...
    strcmp(xi.executionMode,yi.executionMode) && ...
    strcmp(xi.coordinationMode,yi.coordinationMode) && ...
    isequaln(xi.hardwareIdentity,yi.hardwareIdentity) && ...
    x.iter==y.iter && ...
    isequaln(x.arrivalBits,y.arrivalBits) && ...
    isequaln(x.commonAckDraw,y.commonAckDraw) && ...
    isequaln(x.actualRbByGroupTti,y.actualRbByGroupTti);
baseRows=x.waLog;constrainedRows=y.waLog;
sameWaWindow=numel(baseRows)==numel(constrainedRows) && ...
    isequal({baseRows.branch},{constrainedRows.branch}) && ...
    isequal([baseRows.tti],[constrainedRows.tti]);
sameControlBeams=false;sameUnconstrainedSource=false;
if sameWaWindow && sameFrozenInput && sameSourcePolicy
 sameControlBeams=true;sameUnconstrainedSource=true;
 for j=1:6:numel(baseRows)
  left=load(baseRows(j).waAttemptPath,'attempt');
  right=load(constrainedRows(j).waAttemptPath,'attempt');
  sameFrozenInput=sameFrozenInput && ...
      isequaln(left.attempt.resourceInput, ...
          right.attempt.resourceInput);
  sameControlBeams=sameControlBeams && ...
      isequaln(left.attempt.precoders(1:5), ...
          right.attempt.precoders(1:5));
  audit=right.attempt.rows(6).experienceConstraint;
  sameUnconstrainedSource=sameUnconstrainedSource && ...
      ~isempty(audit) && ...
      isequaln(left.attempt.precoders{6}, ...
          audit.unconstrainedSourcePrecoder);
 end
end
paired=struct('baseCheckpointSha256',chasi_sha256_file(basePath), ...
    'constrainedCheckpointSha256', ...
        chasi_sha256_file(constrainedPath), ...
    'inputSha256',xi.inputSha256, ...
    'sameFrozenInputBusinessResourcesAndHardware',sameFrozenInput, ...
    'sameSourcePolicyBeforeConstraint',sameSourcePolicy, ...
    'sameWaWindow',sameWaWindow, ...
    'sameFiveControlBranchBeamsAtEveryWa',sameControlBeams, ...
    'sameUnconstrainedSourceBeamAtEveryWa', ...
        sameUnconstrainedSource, ...
    'paired',sameFrozenInput && sameSourcePolicy && ...
        sameWaWindow && sameControlBeams && sameUnconstrainedSource);
end
