function summary=chasi_v5_protocol_finalize(root,inputPath,checkpoint,outDir,curvePath)
% Recompute paired RLC outcomes from saved online capacity, common arrivals
% and common indexed ACK draws. Never infer ACK from static SE.
startup;addpath(fullfile(root,'08_一致性验证','matlab'));
x=load(inputPath,'data');d=x.data;y=load(checkpoint,'state');s=y.state;
if nargin<5
    curvePath='';
    if isfield(d,'linkCurvePath'),curvePath=d.linkCurvePath;end
end
curveSha256='';
if ~isempty(curvePath)
    assert(isfile(curvePath),'Calibrated curve file is missing');
    curveSha256=chasi_sha256_file(curvePath);
end
assert(strcmp(s.identity.inputSha256,chasi_sha256_file(inputPath)));
if isfield(d,'channelTracePath') && ~isempty(d.channelTracePath)
    assert(isfile(d.channelTracePath) && ...
        strcmp(d.channelTraceSha256, ...
            chasi_sha256_file(d.channelTracePath)), ...
        'Evaluation channel trace SHA differs from frozen input');
end
traceSha='';
if isfield(s.identity,'channelTraceSha256')
    traceSha=s.identity.channelTraceSha256;
end
channelAudit=struct('source','legacy_or_subset', ...
    'traceSha256',traceSha,'traceKind','none', ...
    'failureReason','', 'logicalHShape',[]);
if isfield(d,'channelSource'),channelAudit.source=d.channelSource;end
if isfield(d,'channelTraceInfo') && ~isempty(d.channelTraceInfo)
    m=d.channelTraceInfo.meta;
    if isfield(m,'traceKind'),channelAudit.traceKind=m.traceKind;
    else,channelAudit.traceKind='external_dense_H';end
    if isfield(m,'failureReason'),channelAudit.failureReason=m.failureReason;end
    if isfield(m,'logicalHShape'),channelAudit.logicalHShape=m.logicalHShape;end
end
T=s.iter;U=d.sceneConfig.users;
assert(T>=1 && T<=size(d.prbSchedule.allocatedRbByGroupTti,2));
if ~isfolder(outDir),mkdir(outDir);end
branches=cell(1,6);names=s.branchNames;
linkValidated=false(1,6);linkModes=cell(1,6);
for b=1:6
    cap=s.capacityBits(:,1:T,b);
    streamDiagnostic=[];prbByUe=zeros(U,T);
    if isfield(s,'streamSinrDb')
        streamDiagnostic=s.streamSinrDb(:,:,1:T,b);
        if isfield(s,'ueAllocatedRb')
            prbByUe=s.ueAllocatedRb(:,1:T,b);
        else
            assert(isempty(curvePath), ...
                'Legacy checkpoint lacks final-beam per-UE PRB allocation');
            prbByUe=zeros(U,T);
        end
        assert(all(prbByUe(:)>=0 & prbByUe(:)<=273 & ...
            prbByUe(:)==fix(prbByUe(:))));
        link=chasi_v6_link_abstraction(streamDiagnostic,d.config, ...
            d.sceneConfig,curvePath,prbByUe,s.identity.inputSha256);
    else
        link=struct('mode','fixed_proxy','bler',.05*ones(U,T), ...
            'mcsIndex',nan(U,T),'diagnosticSinrDb',nan(U,T), ...
            'validated',false,'curveSha256','', ...
            'reason','no_stream_sinr_in_legacy_checkpoint');
    end
    finalAirBeam={};finalService={};finalLinkPower={};
    if isfield(s,'finalAirPrecoder') && ...
            ~isempty(s.finalAirPrecoder{b})
        finalAirBeam=s.finalAirPrecoder{b};
        finalService=cell(1,numel(finalAirBeam));
        finalLinkPower=cell(1,numel(finalAirBeam));
        for g=1:numel(finalAirBeam)
            finalLinkPower{g}=squeeze(sum( ...
                abs(finalAirBeam{g}).^2,[3 4]));
            finalService{g}=finalLinkPower{g}>0;
        end
    end
    linkValidated(b)=link.validated;linkModes{b}=link.mode;
    if link.validated,cap=link.transportBlockBits;end
    ev=chasi_v4_rlc_event_sim(s.arrivalBits(:,1:T,:),cap, ...
        link.bler,d.trafficSeed,s.commonAckDraw(:,1:T));
    assert(isequal(double(ev.arrivalBits), ...
        sum(double(s.arrivalBits(:,1:T,:)),3)), ...
        'Six branches must replay the same SDU arrivals');
    ev.ackModel=link.mode;
    ev.linkCurveSha256=link.curveSha256;
    ev.mcsIndex=link.mcsIndex;
    ev.mcsIndex(ev.attemptedBits==0)=NaN;
    if isfield(s,'uePowerW')
        ev.attemptPowerW=s.uePowerW(:,1:T,b);
        ev.attemptPowerW(ev.attemptedBits==0)=NaN;
    end
    if isfield(s,'streamSinrDb')
        ev.sinrDb=link.diagnosticSinrDb;
        ev.sinrDb(ev.attemptedBits==0)=NaN;
        ev.sinrDefinition='minimum post-IRC layer SINR across active groups; diagnostic only, no calibrated MCS/BLER';
    end
    counter=chasi_acked_rlc_seconds(ev,d.config.ttiMs);
    counter.totalAirPowerW=mean(sum(s.powerW(:,1:T,b),1));
    beamScale=ones(T,1);
    if isfield(s,'appliedBeamScale')
        beamScale=s.appliedBeamScale(1:T,b);
    end
    branches{b}=struct('name',names{b},'inputSha256',s.identity.inputSha256, ...
        'ttiCount',T,'precoder',{s.precoders{b}}, ...
        'finalActualAirPrecoder',{finalAirBeam}, ...
        'finalServingMask',{finalService}, ...
        'finalLinkPowerW',{finalLinkPower}, ...
        'meanTotalAirPowerW',mean(sum(s.powerW(:,1:T,b),1)), ...
        'trueRateByTti',s.trueRate(:,1:T,b), ...
        'powerWByTrpTti',s.powerW(:,1:T,b), ...
        'uePowerWByTti',s.uePowerW(:,1:T,b), ...
        'ueAllocatedRbByTti',prbByUe, ...
        'appliedBeamScale',beamScale, ...
        'streamSinrDb',streamDiagnostic, ...
        'capacityBits',cap,'ackEvents',ev,'counter',counter, ...
        'linkMode',link.mode,'linkValidated',link.validated, ...
        'linkCurveSha256',link.curveSha256, ...
        'waLog',s.waLog(b:6:end));
    dir=fullfile(outDir,names{b});if ~isfolder(dir),mkdir(dir);end
    branch=branches{b};save(fullfile(dir,'latest.mat'),'branch','-v7.3');
end
edgeStatus='unjudged_incomplete_window';powerStatus=edgeStatus;
if T>1000
    edgeStatus='unjudged_nonformal_window';powerStatus=edgeStatus;
end
edge=[];power=[];proxy=[];
blockingReasons={};
usedRb=sum(s.actualRbByGroupTti(:,1:T),1);
if T==1000 && (abs(mean(usedRb)/d.sceneConfig.rbTotal-.5)>1e-12 || ...
        any(abs(usedRb-d.prbSchedule.usedRbByTti(1:T))>1e-8))
    blockingReasons{end+1}='actual_prb_fraction_not_50_percent';
end
actualPowerFeasible=all(isfinite(s.powerW(:,1:T,:)),'all') && ...
    all(s.powerW(:,1:T,:)<=d.config.powerWattPerTrp+1e-6,'all');
if ~actualPowerFeasible
    blockingReasons{end+1}='actual_air_power_infeasible';
end
if ~all(linkValidated)
    blockingReasons{end+1}='missing_validated_sinr_mcs_bler_curve';
end
mode='legacy_unspecified';
if isfield(s.identity,'executionMode'),mode=s.identity.executionMode;end
coordinationMode='centralized_legacy';
if isfield(s.identity,'coordinationMode')
    coordinationMode=s.identity.coordinationMode;
end
paired=[];
pairPath=fullfile(fileparts(checkpoint), ...
    sprintf('coordination_pair_tti_%04d.mat',T));
if isfile(pairPath)
    loaded=load(pairPath,'paired');paired=loaded.paired;
    assert(strcmp(paired.coordinatedCheckpointSha256, ...
        chasi_sha256_file(checkpoint)) && ...
        strcmp(paired.inputSha256,s.identity.inputSha256), ...
        'Paired coordination comparison identity mismatch');
end
if strcmp(d.modelId,'srs_csi_joint_v6_formal') && ...
        ~strcmp(coordinationMode,'centralized') && ...
        (isempty(paired) || ~paired.validated)
    blockingReasons{end+1}= ...
        'coordination_not_paired_validated_against_centralized';
end
timing=struct('executionMode',mode, ...
    'budgetSeconds',d.config.ttiMs/1000, ...
    'maximumObservedSeconds',max([s.waLog.elapsedSeconds]), ...
    'exceeded',max([s.waLog.elapsedSeconds])>d.config.ttiMs/1000);
if strcmp(timing.executionMode,'realtime_diagnostic') && timing.exceeded
    blockingReasons{end+1}='wa_wall_time_exceeds_1ms_tti';
end
if isfield(s.waLog,'fallbackApplied') && any([s.waLog.fallbackApplied])
    blockingReasons{end+1}='wa_fallback_applied';
end
if isfield(s.waLog,'serviceFeasible') && ...
        ~all([s.waLog.serviceFeasible])
    blockingReasons{end+1}='wa_requested_service_infeasible';
end
powerProxyAudit=struct('enabled',false,'calibrationValidated',false, ...
    'observedProxyLoss',NaN,'observedAckLoss',NaN, ...
    'observedOptimisticError',NaN,'allowedOptimisticError',NaN, ...
    'onlineConstraintFeasible',false,'failureReason','');
powerPair=[];
if isfield(s,'experienceConstraintConfig') && ...
        isfield(s.experienceConstraintConfig,'experienceConstraint') && ...
        s.experienceConstraintConfig.experienceConstraint.enabled
    constraint=s.experienceConstraintConfig.experienceConstraint;
    powerProxyAudit.enabled=true;
    pairPath=fullfile(fileparts(checkpoint), ...
        sprintf('power_ablation_pair_tti_%04d.mat',T));
    if isfile(pairPath)
        loaded=load(pairPath,'powerPair');powerPair=loaded.powerPair;
        assert(strcmp(powerPair.constrainedCheckpointSha256, ...
            chasi_sha256_file(checkpoint)) && ...
            strcmp(powerPair.inputSha256,s.identity.inputSha256), ...
            'Power ablation paired checkpoint identity mismatch');
    end
    if isempty(powerPair) || ~powerPair.paired
        blockingReasons{end+1}= ...
            'power_ablation_not_paired_with_unconstrained_source';
    end
    sourceRows=s.waLog(strcmp({s.waLog.branch},'source'));
    feasible=~isempty(sourceRows);
    for j=1:numel(sourceRows)
        feasible=feasible && ...
            ~isempty(sourceRows(j).experienceConstraint) && ...
            sourceRows(j).experienceConstraint.feasible && ...
            ~sourceRows(j).fallbackApplied;
    end
    powerProxyAudit.onlineConstraintFeasible=feasible;
    if ~feasible
        blockingReasons{end+1}='online_power_proxy_constraint_infeasible';
    end
    cal=[];
    if ~isempty(constraint.proxyCalibrationPath) && ...
            isfile(constraint.proxyCalibrationPath) && ...
            strcmp(chasi_sha256_file(constraint.proxyCalibrationPath), ...
                constraint.proxyCalibrationSha256)
        loaded=load(constraint.proxyCalibrationPath,'calibration');
        cal=loaded.calibration;
        powerProxyAudit.calibrationValidated=cal.validationPassed && ...
            strcmp(cal.proxyModelId,constraint.proxyModelId) && ...
            strcmp(cal.proxySourceSha256, ...
                s.identity.powerProxySha256) && ...
            strcmp(cal.constraintModeId,constraint.modeId) && ...
            strcmp(cal.channelSource,channelAudit.source) && ...
            strcmp(cal.traceKind,channelAudit.traceKind) && ...
            ~any(strcmp(cal.inputSha256,s.identity.inputSha256)) && ...
            ~any(cal.sceneSeeds==s.identity.sceneSeed);
    end
    if ~powerProxyAudit.calibrationValidated
        powerProxyAudit.failureReason= ...
            'independent_seed_proxy_ack_calibration_missing_or_failed';
        blockingReasons{end+1}=powerProxyAudit.failureReason;
    elseif T==1000
        mask=branches{1}.counter.valid & ...
            branches{2}.counter.valid & branches{6}.counter.valid;
        if ~all(mask(:)) || ~any(mask(:))
            blockingReasons{end+1}='power_proxy_common_ack_samples_missing';
        else
            pb=mean(mean(s.proxyRateMbps(:,:,1),2),'all');
            pm=mean(mean(s.proxyRateMbps(:,:,2),2),'all');
            ab=mean(branches{1}.counter.rateMbps(mask));
            am=mean(branches{6}.counter.rateMbps(mask));
            if pb<=0 || ab<=0
                blockingReasons{end+1}='power_proxy_denominator_nonpositive';
            else
                powerProxyAudit.observedProxyLoss=(pb-pm)/pb;
                powerProxyAudit.observedAckLoss=(ab-am)/ab;
                powerProxyAudit.observedOptimisticError= ...
                    powerProxyAudit.observedAckLoss- ...
                    powerProxyAudit.observedProxyLoss;
                powerProxyAudit.allowedOptimisticError= ...
                    cal.optimismMargin;
                if powerProxyAudit.observedProxyLoss>= ...
                        constraint.maximumMeanLoss-cal.optimismMargin
                    blockingReasons{end+1}= ...
                        'power_proxy_window_loss_exceeds_constraint';
                end
                if powerProxyAudit.observedOptimisticError> ...
                        cal.optimismMargin
                    blockingReasons{end+1}= ...
                        'power_proxy_ack_loss_mismatch';
                end
            end
        end
    end
end
if isfield(d,'channelTracePath') && ~isempty(d.channelTracePath)
    if ~isfield(d,'formalChannelEligible') || ...
            ~d.formalChannelEligible || ...
            ~d.channelTraceInfo.meta.validationPassed || ...
            ~d.channelTraceInfo.meta.spatialConsistency
        blockingReasons{end+1}='channel_trace_not_full_or_independently_validated';
    end
    if ~d.channelTraceInfo.meta.errorModelValidationPassed
        blockingReasons{end+1}='error_posterior_not_independently_validated';
    end
    if ~d.channelTraceInfo.meta.temporalPosteriorMatched
        blockingReasons{end+1}='ray_temporal_posterior_not_independently_validated';
    end
    if ~d.channelTraceInfo.meta.priorPosteriorMatched
        blockingReasons{end+1}='ray_prior_gaussian_posterior_model_mismatch';
    end
    if ~d.channelTraceInfo.meta.crossUeResidualMatched
        blockingReasons{end+1}='spatial_field_cross_ue_pilot_covariance_not_validated';
    end
elseif (isfield(d,'formalChannelEligible') && ~d.formalChannelEligible) || ...
        (isfield(d.config,'channelMode') && ...
        ismember(d.config.channelMode, ...
            {'geometry_correlated_surrogate','umi_pathloss_subset', ...
             'uma_pathloss_subset'}))
    blockingReasons{end+1}='channel_not_full_tr38901';
end
if ~strcmp(d.modelId,'srs_csi_joint_v6_formal')
    blockingReasons{end+1}='legacy_input_not_v6_formal_business';
end
if T==1000
    proxy=chasi_two_objective_decision(branches{1}.counter, ...
        branches{2}.counter,branches{6}.counter,struct());
    if strcmp(proxy.edgeStatus,'missing_samples') || ...
            strcmp(proxy.powerStatus,'missing_samples')
        blockingReasons{end+1}='no_complete_common_ue_second_samples';
    end
    if strcmp(proxy.edgeStatus,'nonpositive_denominator')
        blockingReasons{end+1}='nonpositive_ideal_r5_gain_denominator';
    end
    if strcmp(proxy.powerStatus,'nonpositive_denominator')
        blockingReasons{end+1}='nonpositive_independent_mean_or_power_denominator';
    end
    logs=s.waLog;waBranches=~strcmp({logs.branch},'independent');
    if ~all([logs(waBranches).converged])
        blockingReasons{end+1}='wa_updates_not_converged';
    end
    [edgeStatus,powerStatus,edge,power]= ...
        chasi_v6_formal_decision_gate(proxy,blockingReasons, ...
            all([logs(waBranches).converged]));
end
prb=struct('requested',d.prbRequested,'actualByGroupTti',s.actualRbByGroupTti(:,1:T), ...
    'accountingScope','integer PRBs allocated to each shared frequency group per TTI; UE actual-beam allocations stored per branch', ...
    'actualRbByTti',sum(s.actualRbByGroupTti(:,1:T),1), ...
    'plannedRbByTti',d.prbSchedule.usedRbByTti(1:T), ...
    'perTrpFraction',repmat(mean(sum(s.actualRbByGroupTti(:,1:T),1))/273,1,d.sceneConfig.trps), ...
    'matchesPlan',all(abs(sum(s.actualRbByGroupTti(:,1:T),1)- ...
        d.prbSchedule.usedRbByTti(1:T))<1e-8));
summary=struct('inputSha256',s.identity.inputSha256,'ttiCount',T, ...
    'powerProxyAudit',powerProxyAudit, ...
    'powerAblationPair',powerPair, ...
    'waSolverMode',coordinationMode, ...
    'trpCoordination',struct('centralizedBaseline', ...
        'same_input_same_hardware_same_tolerances', ...
        'executionMode',coordinationMode, ...
        'pairedComparison',paired, ...
        'parallelSpeedupJudged',false, ...
        'exchangeBytesAreEstimated',true, ...
        'actualOnlineWaTriggerCount',getOnlineCount(s), ...
        'freshOnlineWaByBranch',getOnlineBranchCount( ...
            s,'onlineWaFreshByBranch'), ...
        'convergedOnlineWaByBranch',getOnlineBranchCount( ...
            s,'onlineWaConvergedByBranch'), ...
        'waWallSeconds',[s.waLog.elapsedSeconds]), ...
    'channelTraceSha256',traceSha, ...
    'channelAudit',channelAudit, ...
    'requestedCurveSha256',curveSha256, ...
    'eventSimulatorSha256',chasi_sha256_file(which('chasi_v4_rlc_event_sim')), ...
    'counterSha256',chasi_sha256_file(which('chasi_acked_rlc_seconds')), ...
    'decisionSha256',chasi_sha256_file(which('chasi_two_objective_decision')), ...
    'decisionGateSha256',chasi_sha256_file(which('chasi_v6_formal_decision_gate')), ...
    'linkAbstractionSha256',chasi_sha256_file(which('chasi_v6_link_abstraction')), ...
    'checkpointSha256',chasi_sha256_file(checkpoint), ...
    'finalizerSha256',chasi_sha256_file(which('chasi_v5_protocol_finalize')), ...
    'branchNames',{names},'branches',{branches}, ...
    'sharedBusiness',struct('trafficSeed',d.trafficSeed, ...
        'onlineTtiCount',T, ...
        'absoluteTtiWindow',[d.config.decisionTti+1, ...
            d.config.decisionTti+T], ...
        'offeredSduCount',nnz(s.arrivalBits(:,1:T,:)), ...
        'sharedPrbByTti',s.actualRbByGroupTti(:,1:T), ...
        'commonAckDrawShape',size(s.commonAckDraw(:,1:T))), ...
    'prbRequested',d.prbRequested, ...
    'prbEffective',mean(prb.actualRbByTti)/273,'prbAudit',prb, ...
    'ackModel',linkModes{1},'linkModes',{linkModes}, ...
    'timingDiagnostic',timing, ...
    'actualAirPowerFeasible',actualPowerFeasible, ...
    'blockingReasons',{blockingReasons}, ...
    'edgeStatus',edgeStatus,'powerStatus',powerStatus, ...
    'edgeDecision',edge,'powerDecision',power, ...
    'proxyDecision',proxy, ...
    'formalOneSecondComplete',T==1000);
save(fullfile(outDir,'summary.mat'),'summary','-v7.3');
fprintf('V5_PROTOCOL tti=%d edge=%s power=%s ack=%s\n',T, ...
    edgeStatus,powerStatus,mat2str(cellfun(@(z)sum(z.ackEvents.sduAckBits,'all'),branches)));
end

function count=getOnlineCount(state)
count=NaN;
if isfield(state,'onlineWaTriggerCount')
    count=state.onlineWaTriggerCount;
end
end

function count=getOnlineBranchCount(state,name)
count=nan(1,6);
if isfield(state,name),count=state.(name);end
end
