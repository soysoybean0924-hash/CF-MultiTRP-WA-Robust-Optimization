function summary=run_v6_formal_batch(root,runTag,targetTti,curvePath,sceneSeed)
% Full 21-TRP/210-UE/17-group v6 campaign in resumable 20-TTI batches.
% A partial batch is never an acceptance result. No solver limits reduced.
if nargin<3,error('Specify root, runTag and cumulative targetTti');end
if nargin<4,curvePath='';end
if nargin<5,sceneSeed=[];end
assert(isfolder(root) && ischar(runTag) && ...
    ~isempty(regexp(runTag,'^[A-Za-z0-9_]+$','once')));
assert(isscalar(targetTti) && targetTti==fix(targetTti) && ...
    targetTti>=20 && targetTti<=1000 && mod(targetTti,20)==0);
assert(isempty(sceneSeed) || (isscalar(sceneSeed) && ...
    ismember(sceneSeed,[41 67])));
startup;
parentConfig=fullfile(root,'03_研究场景构造','config', ...
    'srs_csi_joint_v5_prb50.json');
v6Config=fullfile(root,'03_研究场景构造','config', ...
    'srs_csi_joint_v6_formal.json');
pc=jsondecode(fileread(parentConfig));vc=jsondecode(fileread(v6Config));
assert(pc.usersPerCell>=10 && pc.usersPerCell<=20 && ...
    pc.resourceGroups==17 && pc.prbUtilization==.5 && ...
    pc.speedKmh==3 && pc.protocolTti==1000 && ...
    pc.hopIntervalTti==20 && pc.revisitTti==340 && ...
    pc.csiRsPeriodTti==40 && pc.admmIterations==100 && ...
    pc.cgIterations==100 && pc.maxOuter==2000);
assert(strcmp(vc.channelSource,'generated_parameters') && ...
    vc.targetBusyFraction==.3 && ...
    strcmp(vc.trafficModel,'target_busy_fraction_batched_sdu'));
if ~isempty(curvePath),assert(isfile(curvePath));end
seedDir='srs_csi_joint_v6_formal';
if ~isempty(sceneSeed)
    seedDir=sprintf('srs_csi_joint_v6_formal_seed%d',sceneSeed);
end
input=fullfile(root,'03_研究场景构造','inputs',seedDir,'input.mat');
prepare_srs_csi_v6_formal_input(root,input,17,sceneSeed);
loaded=load(input,'data');d=loaded.data;c=d.sceneConfig;
assert(c.sites==7 && c.sectorsPerSite==3 && c.trps==21 && ...
    c.users==21*pc.usersPerCell && c.siteSpacingM==300 && ...
    c.txPorts==64 && c.ueTxPorts==2 && c.ueRxPorts==4 && ...
    c.bandwidthHz==100e6 && c.scsHz==30e3 && c.rbTotal==273 && ...
    c.speedKmh==3 && numel(d.resources)==17 && ...
    d.prbEffective==.5 && d.config.decisionTti==340);
% Keep the original formal solver budget and all six branches. The runner
% checkpoints every 20 TTIs and validates identity on resume.
summary=run_v6_online_formal(root,pc.maxOuter,targetTti,runTag, ...
    struct(),'source_all','offline',1,curvePath,sceneSeed);
out=fullfile(root,'07_实验结果与进展','local_runs', ...
    seedDir,'source_all_strength1000',runTag);
checkpoint=fullfile(out,'online','latest.mat');
assert(isfile(checkpoint) && summary.ttiCount==targetTti && ...
    strcmp(summary.inputSha256,chasi_sha256_file(input)));
manifest=struct('purpose','full_scale_v6_batch', ...
    'acceptanceEligibleWindow',targetTti==1000, ...
    'inputSha256',chasi_sha256_file(input), ...
    'checkpointSha256',chasi_sha256_file(checkpoint), ...
    'parentConfigSha256',chasi_sha256_file(parentConfig), ...
    'v6ConfigSha256',chasi_sha256_file(v6Config), ...
    'runnerSha256',chasi_sha256_file(which('run_v6_online_formal')), ...
    'batchWrapperSha256',chasi_sha256_file([mfilename('fullpath') '.m']), ...
    'matlabVersion',version,'sceneSeed',d.sceneSeed, ...
    'measurementSeed',d.measurementSeed, ...
    'trafficSeed',d.trafficSeed,'targetTti',targetTti, ...
    'waOuterBudget',pc.maxOuter,'solverOverride',struct(), ...
    'curvePath',curvePath,'edgeStatus',summary.edgeStatus, ...
    'powerStatus',summary.powerStatus, ...
    'blockingReasons',{summary.blockingReasons});
manifestPath=fullfile(out,sprintf('batch_manifest_tti_%04d.mat',targetTti));
if isfile(manifestPath)
    prior=load(manifestPath,'manifest');
    assert(strcmp(prior.manifest.checkpointSha256, ...
        manifest.checkpointSha256),'Existing batch manifest differs');
else
    save(manifestPath,'manifest','-v7.3');
end
fprintf('FULL_SCALE_BATCH tti=%d checkpoint=%s manifest=%s\n', ...
    targetTti,checkpoint,manifestPath);
end
