function state=run_v5_online_six(root,inputPath,configDir,outDir,targetTti,waOuter,solverOverride,executionMode,coordinationMode)
% Same-input six-arm online simulation; targetTti is total post-decision TTIs.
% Event order: truth innovation, SRS, CSI-RS, WA, transmission, ACK.
startup;addpath(fullfile(root,'08_一致性验证','matlab'));
if nargin<7,solverOverride=struct();end
if nargin<8,executionMode='offline';end
if nargin<9,coordinationMode='centralized';end
assert(ismember(executionMode,{'offline','realtime_diagnostic'}));
assert(ismember(coordinationMode, ...
    {'centralized','trp_jacobi_serial','trp_jacobi_parallel'}));
allowed={'outer_rel_tol','outer_precoder_tol','admm_iterations', ...
    'cg_iterations','eps_abs','eps_rel','max_update_seconds', ...
    'fallback_on_nonconverged'};
assert(all(ismember(fieldnames(solverOverride),allowed)));
assert(all(structfun(@(v)isnumeric(v)&&isscalar(v)&&isfinite(v)&&v>=0,solverOverride)));
if isfield(solverOverride,'max_update_seconds')
 assert(solverOverride.max_update_seconds>0);
end
if isfield(solverOverride,'fallback_on_nonconverged')
 assert(ismember(solverOverride.fallback_on_nonconverged,[0 1]));
end
for name={'admm_iterations','cg_iterations'}
 field=name{1};
 if isfield(solverOverride,field)
  assert(solverOverride.(field)>=1 && ...
      solverOverride.(field)==fix(solverOverride.(field)));
 end
end
assert(targetTti>=1 && waOuter>=1);
assert(strcmp(chasi_sha256_file(inputPath),strtrim(fileread([inputPath '.sha256']))));
x=load(inputPath,'data');d=x.data;
assert((strcmp(d.modelId,'srs_csi_joint_v5') && d.schemaVersion==5) || ...
    (strcmp(d.modelId,'srs_csi_joint_v6_formal') && d.schemaVersion==6));
G=numel(d.resources);U=d.sceneConfig.users;L=d.sceneConfig.trps;
nT=size(d.prbSchedule.allocatedRbByGroupTti,2);
assert(targetTti<=nT);
names={'independent','ideal','nominal','physical','uniform','source'};
traceSha='';
if isfield(d,'channelTraceSha256'),traceSha=d.channelTraceSha256;end
if isfield(d,'channelTracePath') && ~isempty(d.channelTracePath)
 assert(isfile(d.channelTracePath) && ...
     strcmp(traceSha,chasi_sha256_file(d.channelTracePath)), ...
     'Frozen channel parameters/trace changed before online replay');
end
configNames={'','','nominal','physical','uniform','source_all'};
spec=cell(1,6);configHash=cell(1,6);
for b=3:6
 path=fullfile(configDir,[configNames{b} '.json']);
 spec{b}=jsondecode(fileread(path));configHash{b}=chasi_sha256_file(path);
end
constrainedMode=isfield(spec{6},'experienceConstraint') && ...
    spec{6}.experienceConstraint.enabled;
identity=struct('inputSha256',chasi_sha256_file(inputPath), ...
    'sceneSeed',d.sceneSeed, ...
    'channelTraceSha256',traceSha, ...
    'channelSource',getChannelSource(d), ...
    'channelTraceLoaderSha256',chasi_sha256_file(which('chasi_v6_channel_trace')), ...
    'channelRebuildSha256',chasi_sha256_file(which('chasi_v6_tr38901_rebuild_link')), ...
    'losEventSha256',chasi_sha256_file(which('chasi_v6_los_transition_events')), ...
    'channelFieldSha256',chasi_sha256_file(which('chasi_v6_tr38901_spectral_field')), ...
    'channelResponseSha256',chasi_sha256_file(which('chasi_v6_tr38901_ray_response')), ...
    'arrayPanelSha256',chasi_sha256_file(which('chasi_tr38901_array_panel')), ...
    'runnerSha256',chasi_sha256_file(which('run_v5_online_six')), ...
    'solverSha256',chasi_sha256_file(which('chasi_matrix_wmmse')), ...
    'rateSha256',chasi_sha256_file(which('chasi_v3_true_rates')), ...
    'measurementSha256',chasi_sha256_file(which('chasi_v5_online_measurement')), ...
    'policySha256',chasi_sha256_file(which('chasi_v3_source_policy')), ...
    'linkPowerSha256',chasi_sha256_file(which('chasi_v3_link_power')), ...
    'independentSha256',chasi_sha256_file(which('chasi_independent_power_control')), ...
    'configHash',{configHash},'waOuter',waOuter, ...
    'solverOverride',solverOverride,'executionMode',executionMode, ...
    'coordinationMode',coordinationMode, ...
    'hardwareIdentity',struct('host',getenv('COMPUTERNAME'), ...
        'architecture',computer,'matlabRelease',version('-release')), ...
    'groups',G);
if d.schemaVersion==6
 identity.powerProxySha256=chasi_sha256_file( ...
     which('chasi_v6_estimated_experience_proxy'));
 identity.constrainedPowerSha256=chasi_sha256_file( ...
     which('chasi_v6_constrained_air_power'));
 identity.channelStatisticsSha256= ...
     chasi_sha256_file(which('chasi_v6_channel_statistics'));
 identity.temporalPosteriorSha256= ...
     chasi_sha256_file(which('chasi_v6_temporal_posterior'));
 identity.publicJointPriorSha256= ...
     chasi_sha256_file(which('chasi_v6_public_srs_prior'));
 identity.priorAuditBlocksSha256= ...
     chasi_sha256_file(which('chasi_v6_srs_prior_blocks'));
end
if ~isfolder(outDir),mkdir(outDir);end
checkpoint=fullfile(outDir,'latest.mat');
if isfile(checkpoint)
 y=load(checkpoint,'state');state=y.state;
 assert(isequaln(identity,state.identity),'Online checkpoint identity mismatch');
 for eventIndex=1:numel(state.eventLog)
  event=state.eventLog(eventIndex);
  if isfield(event,'measurementPath') && ~isempty(event.measurementPath)
   assert(isfile(event.measurementPath), ...
       'Checkpoint references a missing raw measurement event');
   frozen=load(event.measurementPath,'measurement');
   traceMatches=d.schemaVersion~=6 || ...
       (isfield(frozen.measurement,'channelTraceSha256') && ...
       strcmp(frozen.measurement.channelTraceSha256, ...
           identity.channelTraceSha256));
   assert(strcmp(frozen.measurement.inputSha256,identity.inputSha256) && ...
       traceMatches && ...
       frozen.measurement.tti==event.tti, ...
       'Raw measurement identity differs from checkpoint');
  end
 end
 assert(state.iter<=targetTti, ...
     'Requested TTI is earlier than the frozen online checkpoint');
 if state.iter==targetTti,return;end
else
 stream=RandStream('mt19937ar','Seed',d.measurementSeed+940);
 allTrue=cell(1,G);Nr=size(d.priorRx,1);Nt=size(d.resources(1).H,4);
 for g=1:G
  if isfield(d,'channelTracePath') && ~isempty(d.channelTracePath)
   allTrue{g}=[]; % reconstructed from frozen trace at each absolute TTI
   continue
  end
  r=d.resources(g);A=complex(zeros(U,L,Nr,Nt,'single'));
  for u=1:U
   for l=1:L
    R=d.priorRx(:,:,u,l);z=cn(stream,Nr,Nt);
    A(u,l,:,:)=single(reshape(chol(R,'lower')*z,1,1,Nr,Nt));
   end
  end
  A(double(r.ueIds),:,:,:)=r.H_true;allTrue{g}=A;
 end
 traffic=RandStream('mt19937ar','Seed',d.trafficSeed+990);
 if isfield(d,'formalTraffic')
  arrivals=d.formalTraffic.arrivalSduBits;
  assert(size(arrivals,1)==U && size(arrivals,2)==nT);
 else
  arrivals=12000*double(rand(traffic,U,nT)<.03);
 end
 draws=rand(traffic,U,nT);
 state=struct('identity',identity,'iter',0,'resources',d.resources, ...
     'allTrue',{allTrue},'rngState',stream.State, ...
     'arrivalBits',arrivals,'commonAckDraw',draws, ...
     'precoders',{cell(1,6)},'capacityBits',zeros(U,nT,6), ...
     'finalAirPrecoder',{cell(1,6)}, ...
     'trueRate',zeros(U,nT,6),'powerW',zeros(L,nT,6), ...
     'streamSinrDb',nan(U,d.config.rank,nT,6), ...
     'uePowerW',zeros(U,nT,6), ...
     'ueAllocatedRb',zeros(U,nT,6), ...
     'proxyRateMbps',zeros(U,nT,2), ...
     'appliedBeamScale',ones(nT,6), ...
     'actualRbByGroupTti',zeros(G,nT), ...
     'waLog',struct([]),'eventLog',struct([]), ...
     'onlineWaTriggerCount',0, ...
     'onlineWaFreshByBranch',zeros(1,6), ...
     'onlineWaConvergedByBranch',zeros(1,6), ...
     'policyState',{cell(1,6)},'policyLog',struct([]), ...
     'experienceConstraintConfig',spec{6}, ...
     'branchNames',{names},'inputModelId',d.modelId);
 [state.precoders,logRows,state.policyState]=runWAOnce(outDir,identity, ...
     state.resources,d,spec,waOuter,names,cell(1,6), ...
     d.config.decisionTti,solverOverride,executionMode,coordinationMode);
 beamPath=saveBeam(outDir,state.precoders,state.policyState,identity.inputSha256, ...
     d.config.decisionTti,coordinationMode);
 for b=1:6,logRows(b).beamSnapshotPath=beamPath;end
 state.waLog=logRows;
 compact=cell(1,6);
 for b=1:6
  compact{b}=rmfield(state.policyState{b}, ...
      {'policyCov','requestedPolicyCov'});
 end
 state.policyLog=struct('tti',d.config.decisionTti, ...
     'policyState',{compact});
 saveAtomic(checkpoint,state);
end

stream=RandStream('mt19937ar','Seed',d.measurementSeed+940);
stream.State=state.rngState;
for t=state.iter+1:targetTti
 absoluteTti=d.config.decisionTti+t;
 [state.resources,state.allTrue,event]=chasi_v5_online_measurement( ...
     d,state.resources,state.allTrue,absoluteTti,stream);
 if event.srsGroup>0 || event.csiRs
  event=saveMeasurement(outDir,event,state.identity.inputSha256, ...
      state.identity.channelTraceSha256,d.measurementSeed,stream.State);
 end
 event.onlineStep=t;
 event.waEffectiveTti=0;
 for g=1:G
  state.resources(g).resourceWeightNu= ...
      d.prbSchedule.allocatedRbByGroupTti(g,t)/273;
  state.actualRbByGroupTti(g,t)=273*state.resources(g).resourceWeightNu;
 end
 if event.waTrigger
  [state.precoders,rows,state.policyState]=runWAOnce(outDir,identity, ...
      state.resources,d,spec,waOuter,names,state.precoders, ...
      absoluteTti,solverOverride,executionMode,coordinationMode);
  beamPath=saveBeam(outDir,state.precoders,state.policyState, ...
      identity.inputSha256,absoluteTti,coordinationMode);
  for b=1:6,rows(b).beamSnapshotPath=beamPath;end
  state.waLog=[state.waLog rows]; %#ok<AGROW>
  state.onlineWaTriggerCount=state.onlineWaTriggerCount+1;
  state.onlineWaFreshByBranch=state.onlineWaFreshByBranch+ ...
      double([rows.freshUpdateApplied]);
  state.onlineWaConvergedByBranch= ...
      state.onlineWaConvergedByBranch+double([rows.converged]);
  compact=cell(1,6);
  for b=1:6
   compact{b}=rmfield(state.policyState{b}, ...
       {'policyCov','requestedPolicyCov'});
  end
  auditRow=struct('tti',absoluteTti,'policyState',{compact});
  if isempty(state.policyLog),state.policyLog=auditRow;
  else,state.policyLog(end+1)=auditRow;end %#ok<AGROW>
  event.waEffectiveTti=absoluteTti;
 end
 event.powerRescaleByBranch=ones(1,6);
 for b=1:6
  v=state.precoders{b};
  requestedPower=powerByTrp(state.resources,v);
  scale=min(1,sqrt(d.config.powerWattPerTrp/ ...
      max(max(requestedPower),eps)));
  if scale<1
   for g=1:G,v{g}=scale*v{g};end
  end
  state.appliedBeamScale(t,b)=scale;
  state.finalAirPrecoder{b}=v;
  event.powerRescaleByBranch(b)=scale;
  [rate,sinr]=chasi_v3_true_rates(state.resources,v,U);
  state.trueRate(:,t,b)=rate;
  state.streamSinrDb(:,:,t,b)=sinr;
  state.capacityBits(:,t,b)=floor(max(0,rate)* ...
      d.sceneConfig.bandwidthHz*d.config.ttiMs/1000);
  state.powerW(:,t,b)=powerByTrp(state.resources,v);
  state.uePowerW(:,t,b)=powerByUe(state.resources,v,U);
  state.ueAllocatedRb(:,t,b)=allocatedRbByUe(state.resources,v,U);
 end
 if constrainedMode
  proxyResources=rmfield(state.resources,'H_true');
  baseProxy=chasi_v6_estimated_experience_proxy( ...
      proxyResources,state.finalAirPrecoder{1},U, ...
      d.sceneConfig.bandwidthHz);
  sourceProxy=chasi_v6_estimated_experience_proxy( ...
      proxyResources,state.finalAirPrecoder{6},U, ...
      d.sceneConfig.bandwidthHz);
  state.proxyRateMbps(:,t,1)=baseProxy.perUeMbps;
  state.proxyRateMbps(:,t,2)=sourceProxy.perUeMbps;
 end
 state.iter=t;state.rngState=stream.State;
 if isfield(d,'channelTracePath') && ~isempty(d.channelTracePath)
  state.allTrue=cell(1,G); % do not checkpoint reconstructible H snapshots
 end
 if isempty(state.eventLog),state.eventLog=event;
 else,state.eventLog(end+1)=event;end %#ok<AGROW>
 if mod(t,20)==0 || t==targetTti,saveAtomic(checkpoint,state);end
end
end

function [precoders,rows,decision]=runWAOnce(outDir,identity,resources, ...
    d,spec,waOuter,names,previous,tti,solverOverride,executionMode,coordinationMode)
folder=fullfile(outDir,'wa_attempts');
if ~isfolder(folder),mkdir(folder);end
stem=fullfile(folder,sprintf('tti_%04d',tti));
startedPath=[stem '_started.mat'];finishedPath=[stem '_finished.mat'];
if isfile(startedPath)
 frozen=load(startedPath,'attempt');
 assert(isequaln(frozen.attempt.identity,identity) && ...
     frozen.attempt.tti==tti && ...
     isequaln(frozen.attempt.resourceInput,resources) && ...
     isequaln(frozen.attempt.previousPrecoder,previous), ...
     'WA attempt input changed across checkpoint resume');
else
 attempt=struct('identity',identity,'tti',tti, ...
     'stage','started','resourceInput',{resources}, ...
     'previousPrecoder',{previous});
 saveImmutable(startedPath,'attempt',attempt);
end
if isfile(finishedPath)
 frozen=load(finishedPath,'attempt');
 assert(isequaln(frozen.attempt.identity,identity) && ...
     frozen.attempt.tti==tti && ...
     isequaln(frozen.attempt.resourceInput,resources) && ...
     strcmp(frozen.attempt.stage,'finished'), ...
     'Finished WA attempt differs from resumed resource input');
 precoders=frozen.attempt.precoders;
 rows=frozen.attempt.rows;
 decision=frozen.attempt.decision;
 return
end
[precoders,rows,decision]=optimize(resources,d,spec,waOuter,names, ...
    previous,tti,solverOverride,executionMode,coordinationMode);
for b=1:6,rows(b).waAttemptPath=finishedPath;end
attempt=struct('identity',identity,'tti',tti,'stage','finished', ...
    'resourceInput',{resources},'previousPrecoder',{previous}, ...
    'precoders',{precoders},'rows',{rows},'decision',{decision});
saveImmutable(finishedPath,'attempt',attempt);
end

function saveImmutable(path,name,value)
assert(~isfile(path),'Immutable stage already exists');
partial=[tempname(fileparts(path)) '.mat'];
data=struct();data.(name)=value;
save(partial,'-struct','data','-v7.3');
[ok,msg]=movefile(partial,path);assert(ok,msg);
end

function path=saveBeam(outDir,precoders,policyState,inputSha,tti,coordinationMode)
folder=fullfile(outDir,'precoders');if ~isfolder(folder),mkdir(folder);end
path=fullfile(folder,sprintf('tti_%04d.mat',tti));
beam=struct('inputSha256',inputSha,'tti',tti, ...
    'coordinationMode',coordinationMode, ...
    'branchNames',{{'independent','ideal','nominal','physical', ...
    'uniform','source'}},'precoders',{precoders}, ...
    'policyState',{policyState});
if isfile(path)
 saved=load(path,'beam');
 assert(isequaln(saved.beam,beam),'Frozen WA beam differs on replay');
else
 partial=[path '.partial'];if isfile(partial),delete(partial);end
 save(partial,'beam','-v7.3');
 [ok,msg]=movefile(partial,path);assert(ok,msg);
end
end

function rb=allocatedRbByUe(resources,v,U)
rb=zeros(U,1);
for g=1:numel(resources)
 ids=double(resources(g).ueIds(:));
 weighted=double(resources(g).resourceWeightNu)*273;
 allocated=round(weighted);assert(abs(weighted-allocated)<1e-8);
 for k=1:numel(ids)
  if sum(abs(v{g}(:,k,:,:)).^2,'all')>0
   rb(ids(k))=rb(ids(k))+allocated;
  end
 end
end
end

function p=powerByUe(resources,v,U)
p=zeros(U,1);
for g=1:numel(resources)
 ids=double(resources(g).ueIds(:));
 for k=1:numel(ids)
  p(ids(k))=p(ids(k))+double(resources(g).resourceWeightNu)* ...
      sum(abs(v{g}(:,k,:,:)).^2,'all');
 end
end
end

function [precoders,rows,decision]=optimize(resources,d,spec,waOuter,names,previous,tti,solverOverride,executionMode,coordinationMode)
G=numel(resources);U=d.sceneConfig.users;c=d.config;
cfg=struct('rank',c.rank,'budget',c.powerWattPerTrp, ...
    'outer_iterations',waOuter,'outer_rel_tol',c.outerObjectiveRelativeTolerance, ...
    'outer_precoder_tol',c.outerCovarianceRelativeTolerance, ...
    'admm_iterations',c.admmIterations,'cg_iterations',c.cgIterations, ...
    'eps_abs',c.admmAbsoluteTolerance,'eps_rel',c.admmRelativeTolerance, ...
    'pf_floor',c.pfFloor,'users',U);
if strcmp(d.modelId,'srs_csi_joint_v6_formal')
 cfg.defer_true_evaluation=true;
end
fields=fieldnames(solverOverride);
for j=1:numel(fields)
 if ~ismember(fields{j},{'max_update_seconds','fallback_on_nonconverged'})
  cfg.(fields{j})=solverOverride.(fields{j});
 end
end
% Offline research runs to numerical tolerance. The explicit real-time
% diagnostic checks a 1 ms soft boundary; actual wall time is also logged.
maxSeconds=inf;
if strcmp(executionMode,'realtime_diagnostic')
 maxSeconds=c.ttiMs/1000;
end
if isfield(solverOverride,'max_update_seconds')
 maxSeconds=solverOverride.max_update_seconds;end
cfg.max_wall_seconds=maxSeconds;
cfg.coordinationMode=coordinationMode;
fallbackOnNonconverged=false;
if isfield(solverOverride,'fallback_on_nonconverged')
 fallbackOnNonconverged=logical(solverOverride.fallback_on_nonconverged);end
precoders=cell(1,6);rows=repmat(struct('branch','','tti',tti,'outerBudget',waOuter, ...
    'reason','','converged',false,'maxPowerViolationW',NaN, ...
    'objectiveInitial',NaN,'objectiveFinal',NaN,'objectiveRelativeChange',NaN, ...
    'objectiveScope','', ...
    'terminalOuterRelativeChange',NaN,'terminalPrecoderChange',NaN, ...
    'outerStepsExecuted',NaN, ...
    'beamRelativeChange',NaN,'admmPrimal',NaN,'admmDual',NaN, ...
    'admmEpsPrimal',NaN,'admmEpsDual',NaN,'elapsedSeconds',NaN, ...
    'finalActualPowerMaxW',NaN,'powerFeasible',false, ...
    'serviceFeasible',false, ...
    'postWaLinkPowerApplied',false,'deadlineSeconds',maxSeconds, ...
    'deadlineExceeded',false,'fallbackApplied',false, ...
    'effectiveReason','','solverStatus','', ...
    'solverError','','coordinationMode',coordinationMode, ...
    'solverTrajectory',[],'lastAdmmHistory',[], ...
    'solverWallSeconds',NaN,'actualCoordinationRounds',0, ...
    'estimatedExchangeBytes',0,'freshUpdateApplied',false, ...
    'experienceConstraint',[], ...
    'initializationMode','','warmStartUsed',false, ...
    'outerRelativeTolerance',cfg.outer_rel_tol, ...
    'outerPrecoderTolerance',cfg.outer_precoder_tol, ...
    'admmAbsoluteTolerance',cfg.eps_abs, ...
    'admmRelativeTolerance',cfg.eps_rel, ...
    'admmIterationLimit',cfg.admm_iterations, ...
    'cgIterationLimit',cfg.cg_iterations, ...
    'solverPowerBudgetW',cfg.budget),1,6);
decision=cell(1,6);
for b=1:6
 started=tic;
 cfg.budget=c.powerWattPerTrp;
 r=resources;
 if b~=2
  hiddenOrDiagnostic=intersect(fieldnames(r), ...
      {'H_true','error_diagnostic','srs_diagnostic', ...
       'csi_diagnostic','priorMeanCurrent','priorRxCurrent', ...
       'temporal_diagnostic'});
  if ~isempty(hiddenOrDiagnostic)
   r=rmfield(r,hiddenOrDiagnostic);
  end
 end
 sourceAudit=[];
 linkPowerAudit=[];
 experienceConstraint=[];
 solverError='';
 if b==1
  [sol,solverError]=safeSolve('independent',r,cfg,[]);
 elseif b==2
  for g=1:G,r(g).H=r(g).H_true;r(g).policyCov=[];end
  cfg.branch='matrix_pf_nominal';
  [sol,solverError]=safeSolve('wa',r,cfg, ...
      warmStart(previous{b},r,cfg.budget));
 else
  p=spec{b}.policy;p.enabled=logical(p.enabled);
  if b~=6,p.enabled=false(size(p.enabled));end
  tmp=struct('modelId',d.modelId,'resources',r,'config',d.config);
  [r,audit]=chasi_v3_source_policy(tmp,1:G,p);
  if b==6,sourceAudit=audit;end
  if b==3
   for g=1:G,r(g).C=zeros(size(r(g).C),'like',r(g).C);r(g).policyCov=[];end
   assert(all(arrayfun(@(x)all(x.C(:)==0) && ...
       isempty(x.policyCov),r)));
   cfg.branch='matrix_pf_nominal';
  else
   cfg.branch='matrix_pf_statistical';
   if b==4,for g=1:G,r(g).policyCov=[];end,end
   if b==5,for g=1:G,r(g).policyCov= ...
       spec{b}.uniformExtra*double(r(g).C);end,end
   if b==4
    assert(all(arrayfun(@(g)isequaln(r(g).C,resources(g).C) && ...
        isempty(r(g).policyCov),1:G)));
   elseif b==5
    assert(all(arrayfun(@(g)norm(double(r(g).policyCov(:))- ...
        spec{b}.uniformExtra*double(resources(g).C(:)))<1e-8,1:G)));
   elseif b==6
    assert(all([sourceAudit.physicalCUnchanged]));
   end
  end
  if b==6
   cfg.budget=min([r.powerWattPerTrp]);
  end
  [sol,solverError]=safeSolve('wa',r,cfg, ...
      warmStart(previous{b},r,cfg.budget));
  if b==6 && isempty(solverError) && any(p.enabled(:,3))
   risk=cell(1,G);
   for g=1:G
    risk{g}=zeros(size(audit(g).sourceShare,1), ...
        size(audit(g).sourceShare,2));
    for q=1:size(audit(g).appliedStrength,3)
     risk{g}=risk{g}+audit(g).appliedStrength(:,:,q,3).* ...
         audit(g).sourceShare(:,:,q);
    end
    risk{g}=min(1,max(0,risk{g}));
   end
   try
    pc=chasi_v3_link_power(r,sol.precoder, ...
        min([r.powerWattPerTrp])*ones(size(sol.power)),risk, ...
        spec{b}.powerControl);
    sol.precoder=pc.precoder;
    linkPowerAudit=rmfield(pc,'precoder');
   catch failure
    solverError=sprintf('link_power: %s: %s', ...
        failure.identifier,failure.message);
   end
  end
  if b==6 && isempty(solverError) && ...
          isfield(spec{b},'experienceConstraint') && ...
          spec{b}.experienceConstraint.enabled
   constraintOptions=spec{b}.experienceConstraint;
   calibration=[];
   if ~isempty(constraintOptions.proxyCalibrationPath)
    assert(strcmp(chasi_sha256_file( ...
        constraintOptions.proxyCalibrationPath), ...
        constraintOptions.proxyCalibrationSha256), ...
        'Frozen proxy calibration changed');
    loaded=load(constraintOptions.proxyCalibrationPath,'calibration');
    calibration=loaded.calibration;
    calibration.fileSha256= ...
        constraintOptions.proxyCalibrationSha256;
    assert(~any(strcmp(calibration.inputSha256, ...
        constraintOptions.decisionInputSha256)), ...
        'Power proxy calibration reused the decision input');
    assert(~any(calibration.sceneSeeds==d.sceneSeed), ...
        'Power proxy calibration reused the decision scene seed');
    assert(strcmp(calibration.proxySourceSha256, ...
        chasi_sha256_file(which('chasi_v6_estimated_experience_proxy'))) && ...
        strcmp(calibration.constraintModeId, ...
        constraintOptions.modeId), ...
        'Power proxy calibration source or mode identity changed');
    assert(strcmp(calibration.channelSource,d.channelSource) && ...
        strcmp(calibration.traceKind, ...
            d.channelTraceInfo.meta.traceKind), ...
        'Power proxy calibration channel model changed');
   end
   constraintOptions.powerBudgetW=cfg.budget* ...
       ones(size(sol.power));
   try
    experienceConstraint=chasi_v6_constrained_air_power( ...
        r,sol.precoder,precoders{1},U, ...
        d.sceneConfig.bandwidthHz,constraintOptions,calibration);
    sol.precoder=experienceConstraint.precoder;
   catch failure
    solverError=sprintf('constrained_air_power: %s: %s', ...
        failure.identifier,failure.message);
   end
  end
 end
 elapsed=toc(started);deadlineExceeded=elapsed>maxSeconds || ...
     contains(sol.reason,'wall_budget_exceeded');
 candidate=sol.precoder;
 candidatePower=powerByTrp(resources,candidate);
 infeasible=any(~isfinite(candidatePower)) || ...
     max(candidatePower)>c.powerWattPerTrp+1e-6;
 numericFailure=~isempty(solverError) || ...
     ~isfinite(sol.optimization_objective) || ...
     (~deadlineExceeded && ismember(sol.reason, ...
         {'optimization_objective_decrease', ...
         'inexact_precoder_step_no_proxy_improvement'}));
 fallback=numericFailure || deadlineExceeded || infeasible || ...
     (fallbackOnNonconverged && ~sol.converged);
 effectiveReason=sol.reason;
 if fallback
  candidate=fallbackBeam(previous{b},r,c.rank,cfg.budget);
  if strcmp(sol.reason,'parallel_dependency_unavailable')
   effectiveReason='parallel_dependency_fallback';
  elseif numericFailure,effectiveReason='numerical_failure_fallback';
  elseif deadlineExceeded,effectiveReason='deadline_fallback_last_feasible';
  elseif infeasible,effectiveReason='infeasible_fallback_last_feasible';
  else,effectiveReason='nonconverged_fallback_last_feasible';end
 end
 if strcmp(sol.reason,'parallel_dependency_unavailable')
  status='parallel_dependency_unavailable';
 elseif numericFailure,status='numerical_failure';
 elseif deadlineExceeded,status='budget_truncated';
 elseif infeasible,status='infeasible';
 elseif fallback,status='nonconverged_fallback';
 elseif b==6 && ~isempty(experienceConstraint) && ...
         ~experienceConstraint.feasible
  status='proxy_constraint_infeasible';
  effectiveReason=experienceConstraint.status;
 elseif b==1,status='local_feasible_complete';
 elseif sol.converged,status='converged_feasible';
 else,status='feasible_unconverged';end
 precoders{b}=candidate;
 finalPower=powerByTrp(resources,candidate);
 serviceFeasible=true;
 for g=1:G
  outside=candidate{g}.*reshape(~r(g).servingMask, ...
      size(r(g).servingMask,1),size(r(g).servingMask,2),1,1);
  serviceFeasible=serviceFeasible && ...
      sum(abs(outside).^2,'all')<=1e-12;
 end
 masks=cell(1,G);requestedMasks=cell(1,G);
 extra=cell(1,G);physicalTrace=cell(1,G);
 for g=1:G
  requestedMasks{g}=r(g).servingMask;
  masks{g}=squeeze(sum(abs(candidate{g}).^2,[3 4]))>0;
  if isfield(r(g),'policyCov'),extra{g}=r(g).policyCov;
  else,extra{g}=[];end
  physicalTrace{g}=real(squeeze(trace4(resources(g).C)));
 end
 if fallback,appliedExtra=cell(1,G);appliedSourceAudit=[];
 else,appliedExtra=extra;appliedSourceAudit=sourceAudit;end
 requestedSwitch=false(5,3);appliedSwitch=requestedSwitch;
 requestedStrength=cell(1,G);appliedStrength=cell(1,G);
 serviceChanged=zeros(1,G);beamExtraFro=zeros(1,G);
 linkPowerReduction=zeros(1,G);
 beamDifferenceFromPhysical=zeros(1,G);
 if b==6
  requestedSwitch=logical(p.enabled);
  requestedStrength=arrayfun(@(a)a.appliedStrength,sourceAudit, ...
      'UniformOutput',false);
  if ~fallback
   appliedSwitch=requestedSwitch;
   appliedStrength=requestedStrength;
   for g=1:G
    serviceChanged(g)=nnz(r(g).servingMask~=resources(g).servingMask);
    beamExtraFro(g)=norm(double(extra{g}(:)));
   end
   if ~isempty(linkPowerAudit)
    for g=1:G
     linkPowerReduction(g)=sum( ...
         linkPowerAudit.initialLinkPowerW(:,:,g)- ...
         linkPowerAudit.linkPowerW(:,:,g),'all');
    end
   end
  else
   appliedStrength=cellfun(@(x)zeros(size(x)),requestedStrength, ...
       'UniformOutput',false);
  end
  physicalBeams=precoders{4};
  for g=1:G
   beamDifferenceFromPhysical(g)=norm(double( ...
       candidate{g}(:)-physicalBeams{g}(:)));
  end
 end
 decision{b}=struct('serviceMask',{masks}, ...
     'requestedServiceMask',{requestedMasks}, ...
     'policyCov',{appliedExtra},'requestedPolicyCov',{extra}, ...
     'physicalCTrace',{physicalTrace}, ...
     'sourceAudit',appliedSourceAudit, ...
     'requestedSourceAudit',sourceAudit, ...
     'requestedSourceLocationEnabled',requestedSwitch, ...
     'appliedSourceLocationEnabled',appliedSwitch, ...
     'requestedStrengthByGroup',{requestedStrength}, ...
     'appliedStrengthByGroup',{appliedStrength}, ...
     'serviceMaskChangesByGroup',serviceChanged, ...
     'beamExtraCovFroByGroup',beamExtraFro, ...
     'linkPowerReductionWByGroup',linkPowerReduction, ...
     'beamDifferenceFromPhysicalFroByGroup', ...
         beamDifferenceFromPhysical, ...
     'fallbackApplied',fallback, ...
     'solverStatus',status,'solverError',solverError, ...
     'effectiveReason',effectiveReason, ...
     'requestedLinkPowerAudit',linkPowerAudit, ...
     'experienceConstraint',experienceConstraint, ...
     'finalLinkPowerW',{linkPowerByGroup(candidate)}, ...
     'finalTrpPowerW',finalPower, ...
     'serviceFeasible',serviceFeasible, ...
     'rank',c.rank);
 firstObj=sol.trajectory(1).objective;finalObj=sol.optimization_objective;
 terminal=sol.trajectory(end);
 beamDelta=NaN;
 if ~isempty(previous{b})
  num=0;den=0;
  for g=1:G
   num=num+sum(abs(candidate{g}-previous{b}{g}).^2,'all');
   den=den+sum(abs(previous{b}{g}).^2,'all');
  end
  beamDelta=sqrt(num)/max(1,sqrt(den));
 end
 admm=[NaN NaN NaN NaN];
 if ~isempty(sol.last_admm_history)
  h=sol.last_admm_history(end);
  admm=[h.primal h.dual h.eps_primal h.eps_dual];
 end
 rows(b)=struct('branch',names{b},'tti',tti,'outerBudget',waOuter, ...
     'reason',sol.reason,'converged',sol.converged && ~fallback && ...
         (isempty(experienceConstraint) || experienceConstraint.feasible), ...
     'maxPowerViolationW',sol.max_power_violation, ...
     'objectiveInitial',firstObj,'objectiveFinal',finalObj, ...
     'objectiveRelativeChange',abs(finalObj-firstObj)/max(1,abs(firstObj)), ...
     'objectiveScope', ...
         'solver beam before any post-solver source power update', ...
     'terminalOuterRelativeChange',terminal.relative_objective_change, ...
     'terminalPrecoderChange',terminal.previous_precoder_change, ...
     'outerStepsExecuted',terminal.outer, ...
     'beamRelativeChange',beamDelta,'admmPrimal',admm(1), ...
     'admmDual',admm(2),'admmEpsPrimal',admm(3), ...
     'admmEpsDual',admm(4),'elapsedSeconds',toc(started), ...
     'finalActualPowerMaxW',max(finalPower), ...
     'powerFeasible',max(finalPower)<=c.powerWattPerTrp+1e-6, ...
     'serviceFeasible',serviceFeasible, ...
     'postWaLinkPowerApplied',b==6 && ~fallback && ...
         ~isempty(linkPowerAudit), ...
     'deadlineSeconds',maxSeconds,'deadlineExceeded',deadlineExceeded, ...
     'fallbackApplied',fallback,'effectiveReason',effectiveReason, ...
     'solverStatus',status,'solverError',solverError, ...
     'coordinationMode',coordinationMode, ...
     'solverTrajectory',{sol.trajectory}, ...
     'lastAdmmHistory',{sol.last_admm_history}, ...
     'solverWallSeconds',sol.solver_elapsed_seconds, ...
     'actualCoordinationRounds', ...
         countCoordinationRounds(sol.trajectory), ...
     'estimatedExchangeBytes', ...
         countExchangeBytes(sol.trajectory), ...
     'freshUpdateApplied',~fallback, ...
     'experienceConstraint',experienceConstraint, ...
     'initializationMode',initializationMode(b,previous), ...
     'warmStartUsed',b>1 && ~isempty(previous{b}), ...
     'outerRelativeTolerance',cfg.outer_rel_tol, ...
     'outerPrecoderTolerance',cfg.outer_precoder_tol, ...
     'admmAbsoluteTolerance',cfg.eps_abs, ...
     'admmRelativeTolerance',cfg.eps_rel, ...
     'admmIterationLimit',cfg.admm_iterations, ...
     'cgIterationLimit',cfg.cg_iterations, ...
     'solverPowerBudgetW',cfg.budget);
end
end

function beams=zeroPrecoder(resources,rank)
beams=cell(1,numel(resources));
for g=1:numel(resources)
 r=resources(g);
 beams{g}=complex(zeros(size(r.H,2),size(r.H,1), ...
     size(r.H,4),rank));
end
end

function mode=initializationMode(branch,previous)
if branch==1,mode='local_home_link_waterfill';
elseif isempty(previous{branch}),mode='estimated_channel_svd';
else,mode='previous_beam_masked_to_current_service';end
end

function candidate=fallbackBeam(previous,resources,rank,budget)
if isempty(previous)
    candidate=zeroPrecoder(resources,rank);
else
    candidate=previous;
    for g=1:numel(resources)
        mask=resources(g).servingMask;
        candidate{g}=candidate{g}.*reshape(mask, ...
            size(mask,1),size(mask,2),1,1);
    end
end
p=powerByTrp(resources,candidate);
if any(~isfinite(p))
    candidate=zeroPrecoder(resources,rank);
    return
end
scale=min(1,sqrt(budget/max(max(p),eps)));
for g=1:numel(candidate),candidate{g}=scale*candidate{g};end
end

function [sol,problem]=safeSolve(kind,resources,cfg,initial)
problem='';started=tic;
try
 if strcmp(kind,'independent')
  sol=chasi_independent_power_control(resources,cfg);
 else
  sol=chasi_matrix_wmmse(resources,cfg,initial);
 end
catch failure
 problem=sprintf('%s: %s',failure.identifier,failure.message);
 failureReason='numerical_failure';
 if contains(failure.message,'Parallel Computing Toolbox') || ...
         contains(failure.message,'existing pool')
  failureReason='parallel_dependency_unavailable';
 end
 if isempty(initial)
  candidate=cell(1,numel(resources));
  for g=1:numel(resources)
   r=resources(g);
   candidate{g}=complex(zeros(size(r.H,2),size(r.H,1), ...
       size(r.H,4),cfg.rank));
  end
 else,candidate=initial;end
 power=powerByTrp(resources,candidate);
 sol=struct('precoder',{candidate},'reason',failureReason, ...
     'converged',false,'power',power, ...
     'max_power_violation',max(max(power-cfg.budget,0)), ...
     'optimization_objective',NaN, ...
     'trajectory',struct('outer',0,'objective',NaN, ...
         'relative_objective_change',NaN, ...
         'previous_precoder_change',NaN), ...
     'last_admm_history',[],'solver_elapsed_seconds',toc(started));
end
end

function count=countCoordinationRounds(trajectory)
count=0;
for j=1:numel(trajectory)
 if isfield(trajectory(j),'admm_trace')
  h=trajectory(j).admm_trace;
  if ~isempty(h) && isfield(h,'coordinationRounds')
   count=count+sum([h.coordinationRounds]);
  end
 end
end
end

function count=countExchangeBytes(trajectory)
count=0;
for j=1:numel(trajectory)
 if isfield(trajectory(j),'admm_trace')
  h=trajectory(j).admm_trace;
  if ~isempty(h) && isfield(h,'estimatedExchangeBytes')
   count=count+sum([h.estimatedExchangeBytes]);
  end
 end
end
end

function warm=warmStart(previous,resources,budget)
if isempty(previous),warm=[];return;end
warm=previous;
assert(numel(warm)==numel(resources));
for g=1:numel(resources)
 [L,K,~,~]=size(warm{g});
 assert(isequal(size(resources(g).servingMask),[L,K]));
 warm{g}=warm{g}.*reshape(resources(g).servingMask,L,K,1,1);
 for k=1:K
  if sum(abs(warm{g}(:,k,:,:)).^2,'all')==0
   allowed=find(resources(g).servingMask(:,k),1);
   if ~isempty(allowed)
    h=reshape(double(resources(g).H(k,allowed,:,:)), ...
        size(resources(g).H,3),size(resources(g).H,4));
    [~,~,v]=svd(h,'econ');
    warm{g}(allowed,k,:,:)=reshape(v(:,1:size(warm{g},4)), ...
        1,1,size(warm{g},3),size(warm{g},4));
   end
  end
 end
end
p=powerByTrp(resources,warm);
assert(all(isfinite(p)));
scale=min(1,sqrt(budget/max(max(p),eps)));
if scale<1,for g=1:numel(warm),warm{g}=scale*warm{g};end,end
end

function t=trace4(C)
[K,L,Nr,~]=size(C);t=zeros(K,L);
for k=1:K,for l=1:L
 t(k,l)=real(trace(reshape(C(k,l,:,:),Nr,Nr)));
end,end
end

function p=powerByTrp(resources,v)
L=size(v{1},1);p=zeros(L,1);
for g=1:numel(resources)
 for l=1:L
  p(l)=p(l)+double(resources(g).resourceWeightNu)* ...
      sum(abs(v{g}(l,:,:,:)).^2,'all');
 end
end
end

function p=linkPowerByGroup(v)
p=cell(1,numel(v));
for g=1:numel(v)
    p{g}=squeeze(sum(abs(v{g}).^2,[3 4]));
end
end

function mask=servingByBeam(v)
mask=cell(1,numel(v));
for g=1:numel(v)
    mask{g}=squeeze(sum(abs(v{g}).^2,[3 4]))>0;
end
end

