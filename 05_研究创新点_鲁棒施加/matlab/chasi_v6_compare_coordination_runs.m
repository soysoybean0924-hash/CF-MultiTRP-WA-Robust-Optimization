function report=chasi_v6_compare_coordination_runs(centralPath,coordinatedPath)
% Same-input, same-host, same-tolerance WA comparison. A serial Jacobi
% run never produces an actual parallel speedup claim.
assert(isfile(centralPath) && isfile(coordinatedPath));
a=load(centralPath,'state');b=load(coordinatedPath,'state');
central=a.state;coordinated=b.state;
x=central.identity;y=coordinated.identity;
assert(strcmp(x.coordinationMode,'centralized') && ...
    ismember(y.coordinationMode, ...
        {'trp_jacobi_serial','trp_jacobi_parallel'}));
sameInput=strcmp(x.inputSha256,y.inputSha256) && ...
    strcmp(x.channelTraceSha256,y.channelTraceSha256) && ...
    strcmp(x.solverSha256,y.solverSha256) && ...
    strcmp(x.runnerSha256,y.runnerSha256) && ...
    isequaln(x.configHash,y.configHash) && ...
    x.waOuter==y.waOuter && ...
    isequaln(x.solverOverride,y.solverOverride) && ...
    strcmp(x.executionMode,y.executionMode) && ...
    central.iter==coordinated.iter && ...
    isequaln(central.arrivalBits,coordinated.arrivalBits) && ...
    isequaln(central.commonAckDraw,coordinated.commonAckDraw) && ...
    isequaln(central.actualRbByGroupTti, ...
        coordinated.actualRbByGroupTti);
sameHardware=isequaln(x.hardwareIdentity,y.hardwareIdentity);
left=central.waLog;right=coordinated.waLog;
sameWindow=numel(left)==numel(right) && ...
    isequal({left.branch},{right.branch}) && ...
    isequal([left.tti],[right.tti]);
objectiveDifference=NaN;
bothConverged=false;bothFeasible=false;bothServiceFeasible=false;
centralSeconds=NaN;coordinatedSeconds=NaN;
if sameWindow
 selected=~strcmp({left.branch},'independent');
 objectiveDifference=max(abs( ...
     [left(selected).objectiveFinal]- ...
     [right(selected).objectiveFinal])./ ...
     max(1,abs([left(selected).objectiveFinal])));
 bothConverged=all([left(selected).converged]) && ...
     all([right(selected).converged]);
 bothFeasible=all([left(selected).powerFeasible]) && ...
     all([right(selected).powerFeasible]);
 bothServiceFeasible=all([left(selected).serviceFeasible]) && ...
     all([right(selected).serviceFeasible]);
 centralSeconds=sum([left(selected).solverWallSeconds]);
 coordinatedSeconds=sum([right(selected).solverWallSeconds]);
end
samePrecision=isfinite(objectiveDifference) && ...
    objectiveDifference<=1e-3;
validated=sameInput && sameHardware && sameWindow && ...
    samePrecision && bothConverged && bothFeasible && ...
    bothServiceFeasible;
ratio=NaN;
if validated && strcmp(y.coordinationMode,'trp_jacobi_parallel') && ...
        centralSeconds>0 && coordinatedSeconds>0
    ratio=centralSeconds/coordinatedSeconds;
end
report=struct('centralCheckpointSha256', ...
    chasi_sha256_file(centralPath), ...
    'coordinatedCheckpointSha256', ...
    chasi_sha256_file(coordinatedPath), ...
    'inputSha256',x.inputSha256,'mode',y.coordinationMode, ...
    'sameInput',sameInput,'sameHardware',sameHardware, ...
    'sameWaWindow',sameWindow,'bothConverged',bothConverged, ...
    'bothPowerFeasible',bothFeasible, ...
    'bothServiceFeasible',bothServiceFeasible, ...
    'maximumRelativeObjectiveDifference',objectiveDifference, ...
    'objectiveTolerance',1e-3,'samePrecision',samePrecision, ...
    'validated',validated, ...
    'centralSolverWallSeconds',centralSeconds, ...
    'coordinatedSolverWallSeconds',coordinatedSeconds, ...
    'pairedParallelWallRatioDiagnostic',ratio, ...
    'parallelSpeedupClaimed',false, ...
    'reason',reason(validated,sameInput,sameHardware,sameWindow, ...
        samePrecision,bothConverged,bothFeasible, ...
        bothServiceFeasible));
end

function value=reason(validated,input,hardware,window,precision,converged,feasible,service)
if validated,value='paired_solver_equivalence_at_declared_tolerance';
elseif ~input,value='input_business_or_resource_identity_mismatch';
elseif ~hardware,value='hardware_identity_mismatch';
elseif ~window,value='wa_window_or_branch_mismatch';
elseif ~converged,value='one_or_both_solvers_not_converged';
elseif ~feasible,value='one_or_both_solvers_power_infeasible';
elseif ~service,value='one_or_both_solvers_service_infeasible';
elseif ~precision,value='objective_precision_mismatch';
else,value='unknown_pairing_failure';end
end
