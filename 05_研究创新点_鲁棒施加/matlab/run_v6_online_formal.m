function summary=run_v6_online_formal(root,waOuter,targetTti,runTag,solverOverride,ablation,executionMode,strengthScale,curvePath,sceneSeedOverride,coordinationMode,centralBaselineCheckpoint,proxyCalibrationPath,sourceBaselineCheckpoint)
% Same 17-group v6 input; separate output/checkpoint for each ablation.
startup;
if nargin<3,targetTti=1000;end
if nargin<4,runTag=sprintf('outer%d',waOuter);end
if nargin<5,solverOverride=struct();end
if nargin<6,ablation='source_all';end
if nargin<7,executionMode='offline';end
if nargin<8,strengthScale=1;end
if nargin<9,curvePath='';end
if nargin<10,sceneSeedOverride=[];end
if nargin<11,coordinationMode='centralized';end
if nargin<12,centralBaselineCheckpoint='';end
if nargin<13,proxyCalibrationPath='';end
if nargin<14,sourceBaselineCheckpoint='';end
assert(isempty(proxyCalibrationPath) || ...
    strcmp(ablation,'source_power_constrained'));
assert(isempty(sourceBaselineCheckpoint) || ...
    strcmp(ablation,'source_power_constrained'));
assert(ismember(executionMode,{'offline','realtime_diagnostic'}));
assert(ismember(coordinationMode, ...
    {'centralized','trp_jacobi_serial','trp_jacobi_parallel'}));
if strcmp(coordinationMode,'trp_jacobi_parallel')
    assert(license('test','Distrib_Computing_Toolbox') && ...
        ~isempty(gcp('nocreate')), ...
        'Parallel path requires Parallel Computing Toolbox and an existing pool');
end
curveSha='';curveTag='proxy';
if ~isempty(curvePath)
    assert(isfile(curvePath));
    curveSha=chasi_sha256_file(curvePath);
    curveTag=['curve_' curveSha(1:16)];
end
assert(targetTti>=1 && targetTti<=1000 && ...
    ischar(runTag) && ~isempty(regexp(runTag,'^[A-Za-z0-9_]+$','once')));
developmentInput=fullfile(root,'03_研究场景构造','inputs', ...
    'srs_csi_joint_v6_formal','input.mat');
input=developmentInput;seedDir='srs_csi_joint_v6_formal';
if ~isempty(sceneSeedOverride)
    assert(sceneSeedOverride>=0 && ...
        sceneSeedOverride==fix(sceneSeedOverride));
    seedDir=sprintf('srs_csi_joint_v6_formal_seed%d',sceneSeedOverride);
    input=fullfile(root,'03_研究场景构造','inputs',seedDir,'input.mat');
    assert(isfile(developmentInput), ...
        'Independent seed requires frozen development input for calibration');
    dev=load(developmentInput,'data');
    assert(dev.data.sceneSeed~=sceneSeedOverride, ...
        'Validation seed must differ from development seed');
end
prepare_srs_csi_v6_formal_input(root,input,17,sceneSeedOverride);
x=load(input,'data');d=x.data;
assert(d.fullScaleInput && d.schemaVersion==6 && ...
    strcmp(d.modelId,'srs_csi_joint_v6_formal') && ...
    numel(d.resources)==17 && d.sceneConfig.users==210 && ...
    d.sceneConfig.trps==21 && d.prbEffective==.5);
configDir=chasi_v6_make_ablation_configs(root,input,ablation, ...
    strengthScale,developmentInput,proxyCalibrationPath);
campaignTag=sprintf('%s_strength%04d',ablation, ...
    round(1000*strengthScale));
if strcmp(ablation,'source_power_constrained')
    if isempty(proxyCalibrationPath),calibrationTag='uncalibrated';
    else
        calibrationSha=chasi_sha256_file(proxyCalibrationPath);
        calibrationTag=calibrationSha(1:16);
    end
    campaignTag=[campaignTag '_proxy' calibrationTag];
end
out=fullfile(root,'07_实验结果与进展','local_runs', ...
    seedDir,campaignTag,runTag);
if ~strcmp(coordinationMode,'centralized')
    out=fullfile(out,coordinationMode);
end
state=run_v5_online_six(root,input,configDir,fullfile(out,'online'), ...
    targetTti,waOuter,solverOverride,executionMode,coordinationMode);
if ~isempty(sourceBaselineCheckpoint)
    assert(isfile(sourceBaselineCheckpoint));
    powerPair=chasi_v6_compare_power_ablation_runs( ...
        sourceBaselineCheckpoint,fullfile(out,'online','latest.mat'));
    powerPairPath=fullfile(out,'online', ...
        sprintf('power_ablation_pair_tti_%04d.mat',state.iter));
    if isfile(powerPairPath)
        saved=load(powerPairPath,'powerPair');
        assert(isequaln(saved.powerPair,powerPair), ...
            'Existing paired power comparison differs');
    else
        partial=[tempname(fullfile(out,'online')) '.mat'];
        save(partial,'powerPair','-v7.3');
        [ok,msg]=movefile(partial,powerPairPath);assert(ok,msg);
    end
    curveTag=[curveTag '_powerpair' ...
        powerPair.baseCheckpointSha256(1:16)];
end
if ~isempty(centralBaselineCheckpoint)
    assert(~strcmp(coordinationMode,'centralized') && ...
        isfile(centralBaselineCheckpoint));
    paired=chasi_v6_compare_coordination_runs( ...
        centralBaselineCheckpoint,fullfile(out,'online','latest.mat'));
    pairPath=fullfile(out,'online', ...
        sprintf('coordination_pair_tti_%04d.mat',state.iter));
    if isfile(pairPath)
        saved=load(pairPath,'paired');
        assert(isequaln(saved.paired,paired), ...
            'Existing paired coordination comparison differs');
    else
        partial=[tempname(fullfile(out,'online')) '.mat'];
        save(partial,'paired','-v7.3');
        [ok,msg]=movefile(partial,pairPath);assert(ok,msg);
    end
    curveTag=[curveTag '_pair' paired.centralCheckpointSha256(1:16)];
end
evaluation=fullfile(out,'evaluation', ...
    sprintf('tti_%04d_%s',state.iter,curveTag));
savedSummary=fullfile(evaluation,'summary.mat');
if isfile(savedSummary)
    previous=load(savedSummary,'summary');summary=previous.summary;
    assert(strcmp(summary.inputSha256,chasi_sha256_file(input)) && ...
        summary.ttiCount==state.iter && ...
        strcmp(summary.requestedCurveSha256,curveSha) && ...
        isfield(summary,'checkpointSha256') && ...
        strcmp(summary.checkpointSha256,chasi_sha256_file( ...
            fullfile(out,'online','latest.mat'))) && ...
        isfield(summary,'finalizerSha256') && ...
        strcmp(summary.finalizerSha256,chasi_sha256_file( ...
            which('chasi_v5_protocol_finalize'))) && ...
        strcmp(summary.eventSimulatorSha256,chasi_sha256_file( ...
            which('chasi_v4_rlc_event_sim'))) && ...
        strcmp(summary.counterSha256,chasi_sha256_file( ...
            which('chasi_acked_rlc_seconds'))) && ...
        strcmp(summary.decisionSha256,chasi_sha256_file( ...
            which('chasi_two_objective_decision'))) && ...
        strcmp(summary.decisionGateSha256,chasi_sha256_file( ...
            which('chasi_v6_formal_decision_gate'))) && ...
        strcmp(summary.linkAbstractionSha256,chasi_sha256_file( ...
            which('chasi_v6_link_abstraction'))), ...
        'Existing evaluation identity mismatch');
    return
end
assert(~isfolder(evaluation),'Unexpected completed evaluation directory');
if ~isfolder(fileparts(evaluation)),mkdir(fileparts(evaluation));end
building=tempname(fileparts(evaluation));
% An interrupted evaluation is recomputed from the current online
% checkpoint in a fresh staging directory. Earlier partial files remain
% untouched; only a complete summary is promoted to the public path.
summary=chasi_v5_protocol_finalize(root,input, ...
    fullfile(out,'online','latest.mat'), ...
    building,curvePath);
assert(isfile(fullfile(building,'summary.mat')));
[ok,msg]=movefile(building,evaluation);assert(ok,msg);
end
