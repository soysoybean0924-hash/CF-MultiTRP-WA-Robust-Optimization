% Re-evaluate the rejected probe without held-out baseline fitting, then
% compare Eq.23-form and total-variance models on disjoint flat-MF data.
startup;
addpath(fullfile(pwd,'08_一致性验证','matlab'));
base=fullfile(pwd,'08_一致性验证');
original=load(fullfile(base,'arvidson_calibration_probe.mat'),'result');
rebuilt=load(fullfile(base,'arvidson_calibration_probe_rebuilt.mat'),'result');
assert(isequaln(original.result.testObserved,rebuilt.result.testObserved) && ...
    isequaln(original.result.coefficients,rebuilt.result.coefficients), ...
    'Rebuilt old probe must reproduce its saved test target and coefficients');
old=diagnose_arvidson_probe( ...
    fullfile(base,'arvidson_calibration_probe_rebuilt.mat'), ...
    fullfile(base,'arvidson_probe_diagnostic_corrected.mat'));
controlled=calibrate_srs_rms_controlled(fullfile(base, ...
    'srs_rms_controlled_with_total_baseline.mat'));
fprintf('REJECTED_PROBE MAE=%.7g trainConstantMAE=%.7g normalized=%.7g\n', ...
    old.eq23Mae,old.constantMae,old.eq23NormalizedMae);
fprintf(['CONTROLLED_RMS Eq23MAE=%.7g totalVarianceMAE=%.7g ', ...
    'trainConstantMAE=%.7g normalizedEq23=%.7g\n'], ...
    controlled.testMae,controlled.testQuadratureMae, ...
    controlled.testConstantMae,controlled.testRelativeMae);
