function run_diagnostic_fixture()
root=fileparts(fileparts(mfilename('fullpath')));
input=load(fullfile(root,'reproduction','inputs','diagnostic_fixture.mat'));
out=wmmse_admm_power(input.a,input.B,input.Pmax,'sumSE',input.draws,size(input.draws,3),25000);
fprintf('initial_sumSE=%.15g Python=%.15g abs_error=%.3g\n', ...
    out.objective(1),input.initial_sumSE,abs(out.objective(1)-input.initial_sumSE));
fprintf('final_sumSE=%.15g max_AP_power=%.15g stop=%s\n', ...
    out.objective(end),out.maxPower,out.stopReason);
fprintf('Python final=%.15g absolute_error=%.3g mu_max_abs_error=%.3g\n', ...
    input.python_final_sumSE,abs(out.objective(end)-input.python_final_sumSE), ...
    max(abs(out.mu(:)-input.python_mu(:))));
fprintf('first_v_error=%.3g first_e_error=%.3g first_w_error=%.3g\n', ...
    max(abs(out.debugV(:)-input.first_v(:))), ...
    max(abs(out.debugE(:)-input.first_e(:))), ...
    max(abs(out.debugW(:)-input.first_w(:))));
fprintf('first_q_error=%.3g first_mu_error=%.3g first_projected_error=%.3g\n', ...
    max(abs(out.debugFirstQ(:)-input.first_q(:))), ...
    max(abs(out.debugFirstMu(:)-input.first_mu(:))), ...
    max(abs(out.debugFirstQProjected(:)-input.first_q_projected(:))));
fprintf('MATLAB inner counts: '); fprintf('%d ',out.innerCount); fprintf('\n');
fprintf('Python inner counts inferred from original norm calls: ');
fprintf('%d ',input.python_norm_counts/2+5); fprintf('\n');
fprintf('trajectory max_abs_error=%.3g\n', ...
    max(abs(out.objective(:)-input.python_objective_trace(:))));
save(fullfile(root,'reproduction','matlab','diagnostic_result.mat'),'out');
end
